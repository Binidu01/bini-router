function resolveSlotDefaultComponent(slotRoot: string, ctx: ImportContext, slotDefaultFileToName: Map<string, string>, lazyImports: string[], importedModules: Set<string>): string {
  const file = findFile(slotRoot, DEFAULT_FILES);
  if (!file) return 'DefaultSlotFallback';
  const nearest = path.join(slotRoot, file);
  if (!isUsableLayout(nearest)) return 'DefaultSlotFallback';
  const existing = slotDefaultFileToName.get(nearest);
  if (existing) return existing;
  const name = `SlotDefault${slotDefaultFileToName.size}`;
  slotDefaultFileToName.set(nearest, name);
  const importPath = toImportPath(nearest, ctx.importRoot);
  if (!importedModules.has(importPath)) { lazyImports.push(`const ${name} = lazyP(() => import('${importPath}'));`); importedModules.add(importPath); }
  return name;
}

function resolveGlobalError(appDir: string, ctx: ImportContext, lazyImports: string[], importedModules: Set<string>): string | null {
  const file = findFile(appDir, GLOBAL_ERROR_FILES);
  if (!file) return null;
  const fullPath = path.join(appDir, file);
  if (!isUsableLayout(fullPath)) return null;
  const importPath = toImportPath(fullPath, ctx.importRoot);
  const name = 'GlobalError';
  if (!importedModules.has(importPath)) { lazyImports.push(`const ${name} = lazyP(() => import('${importPath}'));`); importedModules.add(importPath); }
  return name;
}

// ─── Plugin ────────────────────────────────────────────────────────────────

export function biniroute(options: BiniPluginOptions = {}): Plugin[] {
  const { cors: corsConfig = false, trustProxy = false } = options;

  const st = createRouterState();
  const run = <T>(fn: () => T): T => withState(st, fn);

  let projectRoot = process.cwd();
  let isPreview = false;
  let routerBasename = '/';
  let apiBasePrefix = '';
  let allowedHosts: string[] | true | undefined;
  let viteBase = '';

  const getAppDir = (): string => path.join(projectRoot, APP_DIR);
  const getApiDir = (): string => path.join(projectRoot, API_DIR);

  // Resolve the app entry filename lazily: before `configResolved`, project
  // type detection falls back to `process.cwd()`, which matches the
  // AutoImport `dts` behaviour. After `configResolved` the correct root is
  // used for both.
  const appEntryFile = (): string => (getIsTypeScriptCached() ? APP_ENTRY_TS : APP_ENTRY_JS);
  const getAppEntryId = (): string => norm(path.join(projectRoot, 'src', appEntryFile()));
  const isAppEntry = (id: string): boolean => {
    const clean = norm(id.split('?')[0]);
    return (
      clean === getAppEntryId() ||
      clean === '/src/' + APP_ENTRY_TS ||
      clean === '/src/' + APP_ENTRY_JS
    );
  };

  let debounceTimer: ReturnType<typeof setTimeout> | null = null;
  let lastGeneratedCode = '';
  let hasGenerated = false;
  let apiRouter: ReturnType<typeof createRouter> | null = null;
  const moduleCache = new Map<string, CachedModule>();
  let isGenerating = false;
  let cachedIsTs: boolean | null = null;
  let cachedIsTsRoot: string | null = null;
  let cachedApiDirExists: boolean | null = null;

  let manifestCache: RouteManifest | null = null;
  const getManifest = (): RouteManifest =>
    (manifestCache ??= run(() => generateRouteManifest(getAppDir(), getApiDir())));

  const findMainFile = (): string => {
    for (const ext of ['tsx', 'ts', 'jsx', 'js']) {
      const f = path.join(projectRoot, 'src', `main.${ext}`);
      if (fs.existsSync(f)) return norm(f);
    }
    return norm(path.join(projectRoot, 'src', 'main.tsx'));
  };

  function getIsTypeScriptCached(): boolean {
    if (cachedIsTs !== null && cachedIsTsRoot === projectRoot) return cachedIsTs;
    cachedIsTs = isTypeScriptProject(projectRoot);
    cachedIsTsRoot = projectRoot;
    return cachedIsTs;
  }

  function getApiDirExistsCached(): boolean {
    if (cachedApiDirExists !== null) return cachedApiDirExists;
    cachedApiDirExists = fs.existsSync(getApiDir());
    return cachedApiDirExists;
  }

  function isPageFile(f: string): boolean {
    const nf = norm(f);
    const base = path.basename(f, path.extname(f));
    const ext = path.extname(f);
    if (!(SUPPORTED_EXTS as readonly string[]).includes(ext)) return false;
    if (!isInDir(nf, norm(getAppDir()))) return false;
    if (isInDir(nf, norm(getApiDir()))) return false;
    if (base.startsWith('_')) return false;
    return true;
  }

  function isApiFile(f: string): boolean {
    const nf = norm(f);
    return isInDir(nf, norm(getApiDir())) && (API_EXTS as readonly string[]).includes(path.extname(f));
  }

  function generateAppCode(): string | null {
    if (isPreview) return null;
    if (isGenerating) return null;
    isGenerating = true;
    st.errors.length = 0;
    try {
      const dir = getAppDir();
      if (!fs.existsSync(dir)) return null;
      hasGenerated = true;
      const isTs = getIsTypeScriptCached();
      const { code } = generateApp(dir, getApiDir(), projectRoot, routerBasename, isTs);
      if (st.isBuild) flushErrors();
      if (code === lastGeneratedCode) return code;
      lastGeneratedCode = code;
      return code;
    } catch (error) {
      if (st.isBuild) throw error;
      viteErrorLog(`Failed to generate app: ${error instanceof Error ? error.message : String(error)}`, S, error);
      return null;
    } finally {
      isGenerating = false;
    }
  }

  function scheduleRegen(server: ViteDevServer, delay = DEBOUNCE_MS, reason = 'route change'): void {
    manifestCache = null;
    if (debounceTimer) clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      debounceTimer = null;
      run(() => {
        const before = lastGeneratedCode;
        const code = generateAppCode();
        if (code === null || code === before) return;
        const mod = server.moduleGraph.getModuleById(RESOLVED_VIRTUAL_ROUTES_ID);
        if (mod) server.moduleGraph.invalidateModule(mod);
        const appMod = server.moduleGraph.getModuleById(getAppEntryId());
        if (appMod) server.moduleGraph.invalidateModule(appMod);
        server.ws.send({ type: 'full-reload', path: '*' });
      });
    }, delay);
  }

  function createApiMiddleware(server: ViteDevServer | null) {
    return (req: any, res: any, next: any) => {
      if (!req.url) return next();
      const originalUrl = req.url;
      const apiPath = resolveApiPath(req.url, apiBasePrefix);
      if (apiPath === null) return next();
      if (!getApiDirExistsCached()) return next();
      req.url = apiPath;
      const ctx: ApiContext = {
        st,
        apiDir: getApiDir(),
        cors: corsConfig,
        trustProxy,
        allowedHosts,
        getRouter: () => apiRouter,
        setRouter: (v) => { apiRouter = v; },
        moduleCache,
        server,
      };
      handleApiRequest(req, res, ctx).catch((error) => {
        req.url = originalUrl;
        viteErrorLog(`Unhandled API middleware error: ${error instanceof Error ? error.message : String(error)}`, st, error);
        if (!res.headersSent) sendJson(res, 500, { error: 'Internal Server Error' });
      });
    };
  }

  function transformSource(code: string, id: string): { code: string; map: any } | undefined {
    if (shouldBailMdx(id)) return;
    const nid = norm(id);
    const appDir = getAppDir();
    const apiDir = getApiDir();
    if (!isInDir(nid, norm(path.join(projectRoot, 'src')))) return;
    if (isInDir(nid, norm(apiDir))) return;
    if (isAppEntry(nid)) return;
    if (nid.endsWith('.mdx') || nid.endsWith('.md')) return;
    if (nid.endsWith('.d.ts') || nid.endsWith('.d.mts') || nid.endsWith('.d.cts')) return;

    const inApp = isInDir(nid, norm(appDir));
    if (!inApp) return;

    const parsed = parseFile(code, id);
    if (!parsed) return;

    const ms = stripAppExports(code, parsed);
    if (!ms) return;
    return { code: ms.toString(), map: ms.generateMap({ hires: true, source: id }) };
  }

  const routerPlugin: Plugin = {
    name: 'bini-router',
    enforce: 'pre',

    config(_, env) {
      st.isBuild = env.command === 'build';
      isPreview = Boolean((env as { isPreview?: boolean }).isPreview);
    },

    configResolved(config) {
      run(() => {
        const newRoot = config.root || process.cwd();
        if (newRoot !== projectRoot) { cachedIsTs = null; cachedIsTsRoot = null; cachedApiDirExists = null; }
        projectRoot = newRoot;
        st.logger = config.logger;
        const derived = deriveBase(config.base || '/', config.command);
        routerBasename = derived.routerBasename;
        apiBasePrefix = derived.apiPrefix === '/' ? '' : derived.apiPrefix;
        viteBase = (config.base || '/').replace(/\/$/, '');
        const serverHosts = (config.server as { allowedHosts?: string[] | true } | undefined)?.allowedHosts;
        const previewHosts = (config.preview as { allowedHosts?: string[] | true } | undefined)?.allowedHosts;
        allowedHosts = isPreview ? (previewHosts ?? serverHosts) : serverHosts;
        st.routerVersion = readRouterVersion(projectRoot);
      });
    },

    transform: {
      filter: { id: { include: /\.(tsx|jsx|ts|js|mdx|md)$/ } },
      handler(code, id) {
        return run(() => transformSource(code, id));
      },
    },

    transformIndexHtml(_html, ctx) {
      if (!ctx.server) return;
      return [{
        tag: 'script',
        attrs: { type: 'module' },
        injectTo: 'head-prepend',
        children: `
import { createHotContext } from ${JSON.stringify(viteBase + '/@vite/client')};
const hot = createHotContext('/__bini_router_recover');
const LOAD_FAIL = ${LOAD_FAIL_PATTERN.toString()};
const crash = () => { window.__bini_crashed = true; };

window.addEventListener('error', (e) => {
  if (e.target && e.target !== window) {
    if (e.target.tagName === 'SCRIPT' && e.target.type === 'module') crash();
    return;
  }
  if (!window.__bini_mounted || LOAD_FAIL.test(String(e.message))) crash();
}, true);
window.addEventListener('unhandledrejection', (e) => {
  if (LOAD_FAIL.test(String(e.reason && e.reason.message))) crash();
});

hot.on('vite:error', () => {
  const root = document.getElementById('root');
  if (!root || !root.firstElementChild) crash();
});

hot.on('vite:beforeUpdate', () => {
  if (window.__bini_crashed) location.reload();
});`,
      }];
    },

    hotUpdate(this: any, { file, server, modules }: any) {
      const env = this.environment?.name;
      const nf = norm(file);
      const inSrc = isInDir(nf, norm(path.join(projectRoot, 'src')));
      const external = !isInDir(nf, norm(projectRoot)) || nf.includes('/node_modules/');

      if (process.env.BINI_DEBUG_HMR) {
        st.logger?.info(
          `[bini] hotUpdate env=${env} inSrc=${inSrc} external=${external} modules=${modules?.length ?? 0} ${relPath(file)}`,
          { timestamp: true },
        );
      }

      if (!inSrc && external) {
        if (env === 'client') server.ws.send({ type: 'full-reload', path: '*' });
        return [];
      }
      if (inSrc && env === 'ssr') return [];
    },

    buildStart(): void {
      run(() => {
        if (!hasGenerated) generateAppCode();
      });
    },

    buildEnd(): void {
      run(() => {
        apiRouter = null;
        moduleCache.clear();
        clearBuildCaches();
        manifestCache = null;
        if (debounceTimer) { clearTimeout(debounceTimer); debounceTimer = null; }
      });
    },

    configureServer(server): void {
      run(() => {
        const appDir = getAppDir();
        const apiDir = getApiDir();
        cachedApiDirExists = fs.existsSync(apiDir);
        if (!fs.existsSync(appDir)) return;

        server.watcher.add(appDir);

        for (const event of ['add', 'unlink'] as const) {
          server.watcher.on(event, (f) => run(() => {
            try {
              if (!isPageFile(f)) return;
              manifestCache = null;
              const base = path.basename(f, path.extname(f));
              if (SHAPE_BASES.has(base)) { scheduleRegen(server, event === 'add' ? 300 : DEBOUNCE_MS, `${event} shape ${base}`); return; }
              if (event === 'add' && !S.dataSigs.has(f)) {
                scheduleRegen(server, 300, `new route ${shortPath(f)}`);
                return;
              }
            }
            catch (error) { viteErrorLog(`Error handling ${event}: ${error instanceof Error ? error.message : String(error)}`, S, error, f); }
          }));
        }

        server.watcher.on('unlink', (f) => run(() => {
          try { forgetFile(f); forgetWarnings(f); } catch { /* best-effort */ }
        }));

        server.watcher.on('change', (f) => run(() => {
          try {
            if (!isPageFile(f)) return;
            manifestCache = null;
            forgetWarnings(f);
            const base = path.basename(f, path.extname(f));
            if (SHAPE_BASES.has(base)) { scheduleRegen(server, DEBOUNCE_MS, `shape change ${base}`); return; }
            const parsed = readAndParse(f);
            if (parsed && dataSignature(parsed) !== S.dataSigs.get(f)) {
              scheduleRegen(server, DEBOUNCE_MS, `data signature ${shortPath(f)}`);
            }
          } catch (error) { viteErrorLog(`Error handling change: ${error instanceof Error ? error.message : String(error)}`, S, error, f); }
        }));

        server.watcher.on('addDir', (d) => run(() => {
          try {
            const nd = norm(d);
            if (nd === norm(apiDir)) cachedApiDirExists = true;
            if (!isInDir(nd, norm(appDir)) || d.includes('node_modules') || isInDir(nd, norm(apiDir))) return;
            server.watcher.add(d);
            manifestCache = null;
            setTimeout(() => { if (PAGE_FILES.some(f => fs.existsSync(path.join(d, f)))) scheduleRegen(server, 300, `new directory ${shortPath(d)}`); }, 300);
          } catch (error) { viteErrorLog(`Error handling directory add: ${error instanceof Error ? error.message : String(error)}`, S, error, d); }
        }));

        server.watcher.on('unlinkDir', (d) => run(() => {
          try {
            const nd = norm(d);
            if (nd === norm(apiDir)) { cachedApiDirExists = false; apiRouter = null; return; }
            if (isInDir(nd, norm(appDir)) && !d.includes('node_modules') && !isInDir(nd, norm(apiDir))) {
              manifestCache = null;
              scheduleRegen(server, DEBOUNCE_MS, `removed directory ${shortPath(d)}`);
            }
          } catch (error) { viteErrorLog(`Error handling directory unlink: ${error instanceof Error ? error.message : String(error)}`, S, error, d); }
        }));

        if (fs.existsSync(apiDir)) {
          server.watcher.add(apiDir);
          const resetApi = (f?: string, event?: string): void => {
            apiRouter = null;
            if (f) moduleCache.delete(f);
            if (f) viteLog(f, event === 'add' ? 'api route added' : event === 'unlink' ? 'api route removed' : 'hmr update');
            if (event === 'add' || event === 'unlink') server.ws.send({ type: 'full-reload', path: '*' });
          };
          server.watcher.on('add', (f) => run(() => { if (isApiFile(f)) resetApi(f, 'add'); }));
          server.watcher.on('unlink', (f) => run(() => { if (isApiFile(f)) resetApi(f, 'unlink'); }));
          server.watcher.on('change', (f) => run(() => { if (isApiFile(f)) resetApi(f, 'change'); }));
        }

        server.middlewares.use(async (req, res, next) => {
          if (!isHtmlNavigation(req)) return next();
          try {
            const indexPath = path.join(projectRoot, 'index.html');
            const rawTemplate = fs.readFileSync(indexPath, 'utf8');
            const template = await server.transformIndexHtml(req.url ?? '/', rawTemplate);

            // Resolve `src/main.{tsx,ts,jsx,js}` so the SSR entry point
            // matches whatever file actually exists in the project. This is
            // the same file the app's HTML loads as a module script.
            const mainFilePath = findMainFile();
            const mainUrl = '/' + norm(path.relative(projectRoot, mainFilePath));
            const mod = await server.ssrLoadModule(mainUrl);
            if (typeof mod.render !== 'function') {
              return next(makeViteError('BINI_INTERNAL', `${relPath(mainFilePath)} does not export render(url)`, { file: mainFilePath }));
            }
            const inner = await mod.render(req.url ?? '/');

            const urlPath = (req.url ?? '/').split('?')[0];
            const base = routerBasename === '/' ? '' : routerBasename;
            const routePath = base && urlPath.startsWith(base) ? urlPath.slice(base.length) || '/' : urlPath;

            const manifest = getManifest();
            const entry = getMetadataForRoute(manifest, routePath) ?? manifest.metadata['/'] ?? null;
            const roots = [
              mainFilePath,
              ...(entry?.layouts ?? []).map(norm),
              ...(entry ? [norm(entry.filePath)] : []),
            ];

            // Prefer the document.head structure from the manifest. Fall back
            // to hoisting <title>/<meta>/<link> out of the rendered inner HTML
            // for routes that render head tags inline instead of via `document`.
            const documentHead = entry?.document?.head?.length
              ? renderHeadNodes(entry.document.head)
              : '';

            let templateWithHead = template;
            let innerWithoutHead = inner;
            if (!documentHead) {
              const hoisted = hoistHeadFromInner(template, inner);
              templateWithHead = hoisted.template;
              innerWithoutHead = hoisted.inner;
            }

            const cssBlock = await collectDevCss(server, roots, st);
            const withCss = injectIntoHead(templateWithHead, documentHead + cssBlock);

            const html = injectRootHtml(withCss, innerWithoutHead);

            res.statusCode = 200;
            res.setHeader('Content-Type', 'text/html');
            res.setHeader('Cache-Control', 'no-cache');
            res.end(html);
          } catch (err) {
            next(err as Error);
          }
        });

        server.middlewares.use(createApiMiddleware(server));
      });
    },

    configurePreviewServer(server): void {
      run(() => { cachedApiDirExists = fs.existsSync(getApiDir()); server.middlewares.use(createApiMiddleware(null)); });
    },

    resolveId(id) {
      if (id === VIRTUAL_ROUTES_ID || id === RESOLVED_VIRTUAL_ROUTES_ID) return RESOLVED_VIRTUAL_ROUTES_ID;
      // Accept both extensionless and `.tsx`/`.jsx` forms of the virtual app
      // id. The actual file the plugin resolves to depends on project type,
      // so `isAppEntry` covers any concrete path the app entry can take.
      if (id === VIRTUAL_APP_ID || id === `${VIRTUAL_APP_ID}.tsx` || id === `${VIRTUAL_APP_ID}.jsx` || isAppEntry(id)) {
        return getAppEntryId();
      }
      return null;
    },

    load(id) {
      return run(() => {
        if (id === RESOLVED_VIRTUAL_ROUTES_ID) {
          const manifestModule = getRouteManifestModule(getAppDir(), getApiDir());
          if (st.isBuild) flushErrors();
          return manifestModule;
        }
        if (isAppEntry(id)) {
          const code = generateAppCode();
          if (code === null) {
            return 'export default function App() { return null; }\nexport function AppRoutes() { return null; }\nexport const basename = "/";\nexport const routes = [];\nexport function getRouter() { return null; }\nexport function preloadRoute() { return Promise.resolve(); }\nexport function routerReady() { return Promise.resolve(); }\nexport function resetNavState() {}\nexport function reportBiniError() {}\nexport const rootOptions = {};\n';
          }
          if (st.isBuild) flushErrors();
          return code;
        }
        return null;
      });
    },
  };

  const mdxExts = [...((MDX_OPTIONS.mdExtensions as string[] | undefined) ?? []), ...((MDX_OPTIONS.mdxExtensions as string[] | undefined) ?? [])];
  let mdxImpl: Plugin | null = null;

  const mdxPlugin: Plugin = {
    name: 'bini-router:mdx',
    async transform(code, id, ...rest) {
      if (shouldBailMdx(id)) return null;
      const clean = id.split('?')[0];
      if (!mdxExts.some(e => clean.endsWith(e))) return null;
      if (!mdxImpl) {
        let mod: any;
        try { mod = await import('@mdx-js/rollup'); }
        catch { throw makeViteError('BINI_INTERNAL', `Missing @mdx-js/rollup for ${relPath(clean)}. Install it with: npm i -D @mdx-js/rollup`, { file: clean }); }
        mdxImpl = mod.default(MDX_OPTIONS) as unknown as Plugin;
      }
      const impl = mdxImpl.transform as any;
      const fn = typeof impl === 'function' ? impl : impl?.handler;
      return fn ? fn.call(this, code, id, ...rest) : null;
    },
  };

  const autoImportPlugin = AutoImport({
    imports: [
      'react',
      {
        'react-router-dom': [
          'Link', 'NavLink', 'useNavigate', 'useParams', 'useLocation',
          'useSearchParams', 'Outlet', 'useLoaderData', 'useActionData',
          'useNavigation', 'useFetcher', 'useFetchers', 'useMatches',
          'useRouteLoaderData', 'useRouteError', 'useRevalidator', 'useSubmit',
          'Await', 'useAsyncValue', 'useAsyncError', 'Form', 'redirect',
          'isRouteErrorResponse',
        ],
      },
    ],
    dts: isTypeScriptProject(process.cwd()) ? 'src/auto-imports.d.ts' : false,
  }) as Plugin | Plugin[];

  const autoImportPlugins = Array.isArray(autoImportPlugin) ? autoImportPlugin : [autoImportPlugin];

  return [routerPlugin, mdxPlugin, ...autoImportPlugins];
}

