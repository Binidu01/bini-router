function hoistHeadFromInner(template: string, inner: string): { template: string; inner: string } {
  const hoisted: string[] = [];
  const stripped = inner
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi, (m) => { hoisted.push(m); return ''; })
    .replace(/<meta\b[^>]*\/?>/gi, (m) => { hoisted.push(m); return ''; })
    .replace(/<link\b[^>]*\/?>/gi, (m) => { hoisted.push(m); return ''; });
  if (hoisted.length === 0) return { template, inner };
  const withHead = template.replace(/<\/head>/i, `${hoisted.join('\n')}</head>`);
  return { template: withHead, inner: stripped };
}

function escapeHtmlAttr(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;');
}

function escapeHtmlText(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;');
}

/**
 * Serialize `HeadNode[]` into HTML for `<head>`.
 *
 * - `text`    → HTML-escaped text.
 * - `raw`     → emitted verbatim, except inside `<script>` where `<` is
 *               escaped as `\u003c` so a `</script>` in a JSON-LD payload
 *               cannot close the tag early. `\u003c` is a valid JSON escape
 *               for `<`, so parsers still see the original string.
 * - `element` → tag with attrs and recursively-rendered children. Void
 *               elements are self-closed, per HTML5.
 */
function renderHeadNodes(nodes: HeadNode[]): string {
  const out: string[] = [];
  for (const node of nodes) {
    if (node.t === 'text') {
      out.push(escapeHtmlText(node.value));
    } else if (node.t === 'raw') {
      out.push(node.value);
    } else {
      const attrs = Object.entries(node.attrs)
        .map(([k, v]) => (v === '' ? ` ${k}` : ` ${k}="${escapeHtmlAttr(v)}"`))
        .join('');
      if (VOID_HEAD_TAGS.has(node.tag)) {
        out.push(`<${node.tag}${attrs}/>`);
      } else if (node.tag === 'script') {
        const safe = node.children
          .map((c) => (c.t === 'raw' ? c.value.replace(/</g, '\\u003c') : renderHeadNodes([c])))
          .join('');
        out.push(`<${node.tag}${attrs}>${safe}</${node.tag}>`);
      } else {
        out.push(`<${node.tag}${attrs}>${renderHeadNodes(node.children)}</${node.tag}>`);
      }
    }
  }
  return out.join('');
}

function isHtmlNavigation(req: import('http').IncomingMessage): boolean {
  const accept = String(req.headers.accept ?? '');
  if (!accept.includes('text/html')) return false;
  const method = req.method ?? 'GET';
  if (method !== 'GET' && method !== 'HEAD') return false;
  const url = req.url ?? '';
  const pathname = url.split('?')[0];
  if (
    pathname.startsWith('/@') ||
    pathname.startsWith('/src/') ||
    pathname.startsWith('/node_modules/') ||
    pathname.startsWith('/api/') ||
    pathname.startsWith('/__') ||
    /\.[a-z0-9]+$/i.test(pathname)
  ) return false;
  return true;
}

async function collectDevCss(
  server: ViteDevServer,
  roots: string[],
  st: RouterState,
): Promise<string> {
  const seen = new Set<string>();
  const cssMods: { url: string; file: string }[] = [];

  const visit = (mod: any): void => {
    if (!mod?.id || seen.has(mod.id)) return;
    seen.add(mod.id);
    const file = norm(String(mod.file ?? mod.id).split('?')[0]);
    if (CSS_EXT_PATTERN.test(file)) {
      if (!/[?&](direct|inline|raw|url|worker|sharedworker)\b/.test(String(mod.url ?? ''))) {
        cssMods.push({ url: mod.url ?? mod.id, file });
      }
      return;
    }
    if (file.includes('/node_modules/')) return;
    for (const dep of mod.importedModules ?? []) visit(dep);
  };

  for (const file of roots) {
    const nf = norm(file);
    const mods = server.moduleGraph.getModulesByFile(nf) ?? server.moduleGraph.getModulesByFile(nf.replace(/\\/g, '/'));
    for (const mod of mods ?? []) visit(mod);
  }

  const tags: string[] = [];
  for (const { url, file } of cssMods) {
    try {
      let css: string | null = null;
      const sep = url.includes('?') ? '&' : '?';
      const direct = await server.transformRequest(`${url}${sep}direct`);
      if (direct?.code) css = direct.code;
      if (css === null) {
        const inline = await server.transformRequest(`${url}${sep}inline`);
        if (inline?.code) css = inline.code;
      }
      if (css) {
        tags.push(`<style type="text/css" data-vite-dev-id="${file}">${css.replace(/<\/style/gi, '<\\/style')}</style>`);
      }
    } catch (err) {
      if (st.isBuild) throw err;
    }
  }
  return tags.join('\n');
}

function isApiPath(url: string): boolean { return /^\/api(?=[/?]|$)/.test(url); }
function stripApiPrefix(url: string): string {
  const rest = url.replace(/^\/api(?=[/?]|$)/, '');
  if (rest === '') return '/';
  if (rest.startsWith('?')) return '/' + rest;
  return rest;
}
function resolveApiPath(reqUrl: string, basePrefix: string): string | null {
  if (isApiPath(reqUrl)) return stripApiPrefix(reqUrl);
  if (basePrefix && reqUrl.startsWith(basePrefix + '/api')) {
    const afterBase = reqUrl.slice(basePrefix.length);
    if (isApiPath(afterBase)) return stripApiPrefix(afterBase);
  }
  return null;
}

export function isAllowedHost(host: string, allowedHosts: string[] | true | undefined): boolean {
  if (allowedHosts === true) return true;
  const raw = host.toLowerCase();
  const hostname = raw.startsWith('[') ? raw.slice(0, raw.indexOf(']') + 1) : raw.replace(/:\d+$/, '');
  if (hostname === 'localhost' || hostname.endsWith('.localhost')) return true;
  if (IPV4_HOSTNAME_PATTERN.test(hostname) || hostname.startsWith('[')) return true;
  if (!allowedHosts || allowedHosts.length === 0) return false;
  return allowedHosts.some(entry => {
    const a = entry.toLowerCase();
    if (a === '*') return true;
    if (a.startsWith('.')) return hostname === a.slice(1) || hostname.endsWith(a);
    return hostname === a;
  });
}

