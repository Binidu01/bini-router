function createRouterState(): RouterState {
  return {
    nearestFileCache: new Map(), layoutChainCache: new Map(),
    templateCache: new Map(), parsedFileCache: new Map(),
    mdxAstCache: new Map(), isUsableLayoutCache: new Map(),
    dirListingCache: new Map(), fileParseCache: new Map(),
    dataSigs: new Map(), warned: new Set(), errors: [],
    logger: null, routerVersion: null, isBuild: false,
  };
}

let S: RouterState = createRouterState();

function withState<T>(next: RouterState, fn: () => T): T {
  const prev = S;
  S = next;
  try { return fn(); } finally { S = prev; }
}

function hashSource(source: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < source.length; i++) {
    h ^= source.charCodeAt(i);
    h = (h * 0x01000193) >>> 0;
  }
  return h.toString(36) + ':' + source.length.toString(36);
}

function clearBuildCaches(): void {
  S.nearestFileCache.clear(); S.layoutChainCache.clear();
  S.templateCache.clear(); S.mdxAstCache.clear();
  S.isUsableLayoutCache.clear(); S.dirListingCache.clear();
}

function forgetFile(filePath: string): void {
  S.parsedFileCache.delete(filePath);
  S.fileParseCache.delete(filePath);
  S.mdxAstCache.delete(filePath);
}

function forgetWarnings(file: string): void {
  const needle = `|${norm(file)}|`;
  for (const k of [...S.warned]) if (k.includes(needle)) S.warned.delete(k);
}

