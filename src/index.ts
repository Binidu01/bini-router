// ─── Route Manifest API ──────────────────────────────────────────────────────

export interface RouteManifest {
  static: string[];
  dynamic: string[];
  all: string[];
  metadata: {
    [routePath: string]: {
      title?: string;
      layouts: string[];
      filePath: string;
      dynamic: boolean;
    };
  };
}

export interface RouteMatchResult {
  type: 'static' | 'dynamic' | 'not_found';
  routePath?: string;
  params?: Record<string, string>;
}

export function generateRouteManifest(
  appDir: string,
  apiDir: string = path.join(appDir, 'api'),
): RouteManifest {
  let routes = scanRoutes(appDir, appDir, apiDir, '', [], 0);

  const rootPage = findFile(appDir, PAGE_FILES);
  if (rootPage) {
    routes.unshift({
      routePath: normalizeRoutePath('/'),
      filePath: path.join(appDir, rootPage),
      layouts: resolveLayoutChain(appDir, appDir),
      template: resolveTemplate(appDir, appDir),
      dynamic: false,
      segments: [],
    });
  }

  const validRoutes = deduplicateRoutes(
    routes.filter(r => hasDefaultExport(r.filePath)),
  ).map(r => ({ ...r, layouts: r.layouts.filter(l => isUsableLayout(l)) }));

  const staticRoutes: string[] = [];
  const dynamicRoutes: string[] = [];
  const metadata: RouteManifest['metadata'] = {};

  for (const route of validRoutes) {
    const isDynamic = route.dynamic || route.routePath.includes(':') || route.routePath.includes('*');

    if (isDynamic) {
      dynamicRoutes.push(route.routePath);
    } else {
      staticRoutes.push(route.routePath);
    }

    const layoutMetas = route.layouts.map(l => parseLayoutMetadata(l));
    const title = resolveTitleFromChain(
      parseLayoutMetadata(route.filePath),
      layoutMetas,
    ) ?? undefined;

    metadata[route.routePath] = {
      title,
      layouts: route.layouts,
      filePath: route.filePath,
      dynamic: isDynamic,
    };
  }

  return {
    static: [...new Set(staticRoutes)],
    dynamic: [...new Set(dynamicRoutes)],
    all: [...new Set([...staticRoutes, ...dynamicRoutes])],
    metadata,
  };
}

export function matchRoute(pattern: string, pathname: string): Record<string, string> | null {
  const patParts = pattern.split('/').filter(Boolean);
  const urlParts = pathname.split('/').filter(Boolean);

  const isCatchAll = patParts[patParts.length - 1] === '*';
  if (isCatchAll) {
    const prefix = patParts.slice(0, -1);
    if (urlParts.length < prefix.length) return null;

    const params: Record<string, string> = {};
    for (let i = 0; i < prefix.length; i++) {
      if (prefix[i].startsWith(':')) {
        let value: string;
        try {
          value = decodeURIComponent(urlParts[i]);
        } catch {
          return null;
        }
        if (value.includes('..') || value.includes('//')) return null;
        params[prefix[i].slice(1)] = value;
      } else if (prefix[i] !== urlParts[i]) {
        return null;
      }
    }

    params['*'] = urlParts.slice(prefix.length).join('/');
    return params;
  }

  if (patParts.length !== urlParts.length) return null;

  const params: Record<string, string> = {};
  for (let i = 0; i < patParts.length; i++) {
    if (patParts[i].startsWith(':')) {
      let value: string;
      try {
        value = decodeURIComponent(urlParts[i]);
      } catch {
        return null;
      }
      if (value.includes('..') || value.includes('//')) return null;
      params[patParts[i].slice(1)] = value;
    } else if (patParts[i] !== urlParts[i]) {
      return null;
    }
  }
  return params;
}

export function matchManifestRoute(
  manifest: RouteManifest,
  pathname: string,
): RouteMatchResult {
  const exact = manifest.metadata[pathname];
  if (exact) {
    return {
      type: exact.dynamic ? 'dynamic' : 'static',
      routePath: pathname,
    };
  }

  for (const pattern of manifest.dynamic) {
    const params = matchRoute(pattern, pathname);
    if (params) {
      return {
        type: 'dynamic',
        routePath: pattern,
        params,
      };
    }
  }

  return { type: 'not_found' };
}

function getRouteManifestModule(appDir: string, apiDir: string): string {
  const full = generateRouteManifest(appDir, apiDir);

  const safeMetadata: Record<string, { title?: string; dynamic: boolean }> = {};
  for (const [k, v] of Object.entries(full.metadata)) {
    safeMetadata[k] = { title: v.title, dynamic: v.dynamic };
  }

  const manifest = {
    static: full.static,
    dynamic: full.dynamic,
    all: full.all,
    metadata: safeMetadata,
  };

  const json = JSON.stringify(manifest);
  return `
    export const staticRoutes = ${JSON.stringify(manifest.static)};
    export const dynamicRoutes = ${JSON.stringify(manifest.dynamic)};
    export const allRoutes = ${JSON.stringify(manifest.all)};
    export const routeMetadata = ${JSON.stringify(manifest.metadata)};
    export default ${json};
  `;
}

// ─── Generate App ────────────────────────────────────────────────────────────

function generateApp(
  appDir: string,
  apiDir: string,
  root: string,
  strictMode = false,
  basename: string = '/',
): string {
  const appFile = getAppFile(root);
  const importRoot = path.dirname(appFile);
  const ctx: ImportContext = { importRoot };

  let routes = scanRoutes(appDir, appDir, apiDir, '', [], 0);
  const ts = isTypeScriptProject(root);

  const rootPage = findFile(appDir, PAGE_FILES);
  if (rootPage) {
    routes.unshift({
      routePath: normalizeRoutePath('/'),
      filePath: path.join(appDir, rootPage),
      layouts: resolveLayoutChain(appDir, appDir),
      template: resolveTemplate(appDir, appDir),
      dynamic: false,
      segments: [],
    });
  }

  const routesFiltered = routes.map(r => ({
    ...r,
    layouts: r.layouts.filter(l => isUsableLayout(l)),
  }));

  let validRoutes = routesFiltered.filter(r => hasDefaultExport(r.filePath));

  const conflicts = detectRouteConflicts(validRoutes);
  if (conflicts.length > 0) {
    if (strictMode) {
      throw new RouteConflictError(conflicts);
    } else {
      viteWarnLog(`Route conflicts detected:\n${conflicts.map(c => `  ${c.path}: ${c.files.join(', ')}`).join('\n')}`);
    }
  }

  validRoutes = deduplicateRoutes(validRoutes);

  validRoutes.sort((a, b) => {
    if (a.dynamic !== b.dynamic) return a.dynamic ? 1 : -1;
    if (a.routePath.includes('*') !== b.routePath.includes('*')) {
      return a.routePath.includes('*') ? 1 : -1;
    }
    return a.routePath.length - b.routePath.length;
  });

  const allLayouts = new Set<string>();
  for (const r of validRoutes) {
    r.layouts.forEach(l => {
      if (isUsableLayout(l)) allLayouts.add(l);
    });
  }

  const allTemplates = new Set<string>();
  for (const r of validRoutes) {
    if (r.template) allTemplates.add(r.template);
  }

  const layoutNames = new Map<string, string>();
  const templateNames = new Map<string, string>();
  const pageNames = new Map<string, string>();
  const layoutMetas = new Map<string, Record<string, unknown>>();
  const pageMetas = new Map<string, Record<string, unknown>>();
  let li = 0, ti = 0, pi = 0;

  for (const l of allLayouts) {
    layoutNames.set(l, `Layout${li++}`);
    const meta = parseLayoutMetadata(l);
    if (meta) layoutMetas.set(l, meta);
  }

  for (const t of allTemplates) {
    templateNames.set(t, `Template${ti++}`);
  }

  for (const r of validRoutes) {
    if (!pageNames.has(r.filePath)) {
      pageNames.set(r.filePath, `Page${pi++}`);
      const meta = parseLayoutMetadata(r.filePath);
      if (meta) pageMetas.set(r.filePath, meta);
    }
  }

  const eagerImports: string[] = [];
  const lazyImports: string[] = [];
  const importedModules = new Set<string>();

  for (const [fp, name] of layoutNames) {
    const importPath = toImportPath(fp, ctx.importRoot);
    if (!importedModules.has(importPath)) {
      eagerImports.push(`import ${name} from '${importPath}';`);
      importedModules.add(importPath);
    }
  }

  for (const [fp, name] of templateNames) {
    const importPath = toImportPath(fp, ctx.importRoot);
    if (!importedModules.has(importPath)) {
      eagerImports.push(`import ${name} from '${importPath}';`);
      importedModules.add(importPath);
    }
  }

  const loadingFileToName = new Map<string, string>();
  const layoutLoadingNames = new Map<string, string>();
  const pageLoadingNames = new Map<string, string>();

  const errorFileToName = new Map<string, string>();
  const layoutErrorNames = new Map<string, string>();
  const pageErrorNames = new Map<string, string>();

  for (const l of allLayouts) {
    layoutLoadingNames.set(
      l,
      resolveLoadingComponentName(path.dirname(l), appDir, ctx, loadingFileToName, lazyImports, importedModules),
    );
    const errName = resolveErrorComponentName(path.dirname(l), appDir, ctx, errorFileToName, lazyImports, importedModules);
    if (errName) layoutErrorNames.set(l, errName);
  }

  const emittedPages = new Set<string>();
  for (const r of validRoutes) {
    if (emittedPages.has(r.filePath)) continue;
    emittedPages.add(r.filePath);
    const name = pageNames.get(r.filePath);
    if (!name) continue;
    const importPath = toImportPath(r.filePath, ctx.importRoot);
    if (!importedModules.has(importPath)) {
      lazyImports.push(`const ${name} = React.lazy(() => import('${importPath}'));`);
      importedModules.add(importPath);
    }
    pageLoadingNames.set(
      r.filePath,
      resolveLoadingComponentName(path.dirname(r.filePath), appDir, ctx, loadingFileToName, lazyImports, importedModules),
    );
    const errName = resolveErrorComponentName(path.dirname(r.filePath), appDir, ctx, errorFileToName, lazyImports, importedModules);
    if (errName) pageErrorNames.set(r.filePath, errName);
  }

  const chainMap = new Map<string, LayoutChainGroup>();
  for (const r of validRoutes) {
    const key = `${r.layouts.join('|')}::${r.template ?? ''}`;
    if (!chainMap.has(key)) {
      chainMap.set(key, { layouts: r.layouts, template: r.template, routes: [] });
    }
    const group = chainMap.get(key);
    if (group) {
      group.routes.push(r);
    }
  }

  const routeLines: string[] = [];
  for (const [, { layouts, template, routes: cr }] of chainMap) {
    routeLines.push(renderChain(
      layouts, template, cr, layoutNames, pageNames,
      pageMetas, layoutMetas,
      layoutLoadingNames, pageLoadingNames, layoutErrorNames, pageErrorNames,
      templateNames, 8,
    ));
  }

  const notFoundBoundaries = collectNotFoundBoundaries(appDir, appDir, apiDir, '');
  const rootEffectivePath = '/';

  const notFoundNames = new Map<string, string>();
  let nfi = 0;
  for (const b of notFoundBoundaries) {
    if (notFoundNames.has(b.filePath)) continue;
    const importPath = toImportPath(b.filePath, ctx.importRoot);
    const name = `NotFound${nfi++}`;
    if (!importedModules.has(importPath)) {
      lazyImports.push(`const ${name} = React.lazy(() => import('${importPath}'));`);
      importedModules.add(importPath);
    }
    notFoundNames.set(b.filePath, name);
  }

  const hasRootCustomNotFound = notFoundBoundaries.some(b => b.dirRoutePath === rootEffectivePath);

  const notFoundRouteLines: string[] = [];
  const notFoundFallbackNames: string[] = [];

  for (const b of notFoundBoundaries) {
    const name = notFoundNames.get(b.filePath);
    if (!name) continue;
    const ownFallback = resolveLoadingComponentName(
      path.dirname(b.filePath), appDir, ctx, loadingFileToName, lazyImports, importedModules,
    );
    notFoundFallbackNames.push(ownFallback);
    const ownErrorName = resolveErrorComponentName(
      path.dirname(b.filePath), appDir, ctx, errorFileToName, lazyImports, importedModules,
    );
    const wrapped = renderComponentWithLayouts(
      `<${name} />`, b.layouts, layoutNames,
      ownFallback, ownErrorName, 10,
    );
    const routePath = b.dirRoutePath === rootEffectivePath ? '*' : `${b.dirRoutePath}/*`;
    notFoundRouteLines.push(`        <Route path="${routePath}" element={${wrapped}} />`);
  }

  if (!hasRootCustomNotFound) {
    notFoundRouteLines.push(`        <Route path="*" element={<Default404 />} />`);
  }

  const usesDefaultSpinner =
    Array.from(layoutLoadingNames.values()).includes('Spinner') ||
    Array.from(pageLoadingNames.values()).includes('Spinner') ||
    notFoundFallbackNames.includes('Spinner');

  const errorBoundaryClass = generateErrorBoundary(ts);
  const titleSetterFn = generateTitleSetter(ts);
  const withParamsFn = generateWithParams(ts);
  const spinnerFn = usesDefaultSpinner ? DEFAULT_LOADING_COMPONENT : '';

  const basenameValue = basename || '/';

  return `${GENERATED_HEADER}
// @ts-nocheck
// oxlint-disable
// oxfmt-ignore

import React, { Suspense } from 'react';
import { BrowserRouter, Routes, Route, Outlet, useLocation, useParams } from 'react-router-dom';

${eagerImports.join('\n')}

${lazyImports.join('\n')}

// ─── Error Boundary ───────────────────────────────────────────────────────────
${errorBoundaryClass}

${withParamsFn}

${spinnerFn}

${titleSetterFn}

${!hasRootCustomNotFound ? DEFAULT_404_COMPONENT : ''}

export function AppRoutes() {
  const location = useLocation();
  return (
    <Routes>
${routeLines.join('\n')}
${notFoundRouteLines.join('\n')}
    </Routes>
  );
}

export const basename = ${JSON.stringify(basenameValue)};

export default function App() {
  return (
    <BrowserRouter basename={basename}>
      <AppRoutes />
    </BrowserRouter>
  );
}
`;
}

// ─── Metadata Parser (for index.html injection) ──────────────────────────────

function parseAppMetadata(appDir: string): MetaTags {
  const layout = findFile(appDir, LAYOUT_FILES);
  if (!layout) return {};

  try {
    const layoutPath = path.join(appDir, layout);
    const raw = parseLayoutMetadata(layoutPath);
    if (!raw) return {};

    return normalizeMetadata(raw);
  } catch (error) {
    viteErrorLog(`Failed to parse metadata: ${error instanceof Error ? error.message : String(error)}`);
    return {};
  }
}

function normalizeMetadata(raw: Record<string, unknown>): MetaTags {
  const meta: MetaTags = {};

  const str = (v: unknown): string | undefined => (typeof v === 'string' ? v : undefined);

  if (typeof raw.title === 'string') {
    meta.title = raw.title;
  } else if (raw.title && typeof raw.title === 'object' && !Array.isArray(raw.title)) {
    const t = raw.title as Record<string, unknown>;
    const def = str(t.default);
    const template = str(t.template);
    if (def || template) {
      meta.title = {
        default: def ?? '',
        template: template ?? '%s',
      };
    }
  }

  const stringFields: (keyof MetaTags)[] = [
    'description', 'viewport', 'themeColor',
    'charset', 'robots', 'canonical', 'manifest',
  ];
  for (const field of stringFields) {
    const value = str(raw[field as string]);
    if (value) (meta as any)[field] = value;
  }

  if (typeof raw.keywords === 'string') {
    meta.keywords = raw.keywords;
  } else if (Array.isArray(raw.keywords)) {
    const items = raw.keywords.filter((k): k is string => typeof k === 'string');
    if (items.length) meta.keywords = items.join(', ');
  }

  if (typeof raw.author === 'string') {
    meta.author = raw.author;
  } else if (raw.author && typeof raw.author === 'object' && !Array.isArray(raw.author)) {
    const name = str((raw.author as Record<string, unknown>).name);
    if (name) meta.author = name;
  }

  if (raw.openGraph && typeof raw.openGraph === 'object' && !Array.isArray(raw.openGraph)) {
    const og = raw.openGraph as Record<string, unknown>;
    const openGraph: Partial<OGMeta> = {};
    if (str(og.title)) openGraph.title = str(og.title);
    if (str(og.description)) openGraph.description = str(og.description);
    if (str(og.url)) openGraph.url = str(og.url);
    if (str(og.type)) openGraph.type = str(og.type);
    openGraph.image = extractImage(og);
    if (Object.keys(openGraph).length) meta.openGraph = openGraph;
  }

  if (raw.twitter && typeof raw.twitter === 'object' && !Array.isArray(raw.twitter)) {
    const tw = raw.twitter as Record<string, unknown>;
    const twitter: Partial<TwitterMeta> = {};
    if (str(tw.card)) twitter.card = str(tw.card);
    if (str(tw.title)) twitter.title = str(tw.title);
    if (str(tw.description)) twitter.description = str(tw.description);
    if (str(tw.creator)) twitter.creator = str(tw.creator);
    twitter.image = extractImage(tw);
    if (Object.keys(twitter).length) meta.twitter = twitter;
  }

  if (raw.icons && typeof raw.icons === 'object' && !Array.isArray(raw.icons)) {
    const iconsRaw = raw.icons as Record<string, unknown>;
    const icons: NonNullable<MetaTags['icons']> = {};
    for (const key of ['icon', 'shortcut', 'apple'] as const) {
      const arr = iconsRaw[key];
      if (!Array.isArray(arr)) continue;
      const entries: IconEntry[] = [];
      for (const item of arr) {
        if (!item || typeof item !== 'object') continue;
        const it = item as Record<string, unknown>;
        const url = str(it.url);
        if (!url) continue;
        const entry: IconEntry = { url };
        if (str(it.type)) entry.type = str(it.type);
        if (str(it.sizes)) entry.sizes = str(it.sizes);
        entries.push(entry);
      }
      if (entries.length) icons[key] = entries;
    }
    if (Object.keys(icons).length) meta.icons = icons;
  }

  return meta;
}

function extractImage(obj: Record<string, unknown>): string | undefined {
  if (typeof obj.image === 'string') return obj.image;
  if (Array.isArray(obj.images) && obj.images.length > 0) {
    const first = obj.images[0];
    if (typeof first === 'string') return first;
    if (first && typeof first === 'object') {
      const url = (first as Record<string, unknown>).url;
      if (typeof url === 'string') return url;
    }
  }
  return undefined;
}

// ─── API Route Scanner ───────────────────────────────────────────────────────

function scanApiRoutes(dir: string, baseRoute = '', depth = 0): ApiRoute[] {
  if (depth > MAX_DEPTH) {
    viteWarnLog(`Maximum API directory depth reached at ${dir}`);
    return [];
  }

  const routes: ApiRoute[] = [];
  if (!fs.existsSync(dir)) return routes;

  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (error) {
    viteErrorLog(`Failed to read API directory ${dir}: ${error instanceof Error ? error.message : String(error)}`);
    return routes;
  }

  entries.sort((a, b) => cmpStr(a.name, b.name));

  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      const isGroup = isRouteGroup(entry.name);
      const isCatchAll = entry.name.startsWith('[...') && entry.name.endsWith(']');
      const isDynamic = entry.name.startsWith('[') && entry.name.endsWith(']');

      let segment: string;
      if (isGroup) {
        segment = '';
      } else if (isCatchAll) {
        segment = '*';
      } else if (isDynamic) {
        const paramName = entry.name.slice(1, -1);
        if (!isValidParamName(paramName)) {
          viteWarnLog(`Invalid API parameter name: ${paramName}`);
          continue;
        }
        segment = `:${paramName}`;
      } else {
        if (!isValidRouteSegment(entry.name)) {
          viteWarnLog(`Invalid API directory name: ${entry.name}`);
          continue;
        }
        segment = entry.name;
      }

      const nextBase = segment ? `${baseRoute}/${segment}` : baseRoute;
      routes.push(...scanApiRoutes(fullPath, nextBase, depth + 1));
      continue;
    }

    const ext = path.extname(entry.name);
    const base = path.basename(entry.name, ext);
    if (!(API_EXTS as readonly string[]).includes(ext)) continue;

    const isCatchAll = base.startsWith('[...') && base.endsWith(']');
    const isDynamic = base.startsWith('[') && base.endsWith(']');

    let rawRoutePath: string;
    if (isCatchAll) {
      rawRoutePath = `${baseRoute}/*`;
    } else if (base === 'index') {
      rawRoutePath = baseRoute || '/';
    } else if (isDynamic) {
      const paramName = base.slice(1, -1);
      if (!isValidParamName(paramName)) {
        viteWarnLog(`Invalid API parameter name: ${paramName}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/:${paramName}`;
    } else {
      if (!isValidRouteSegment(base)) {
        viteWarnLog(`Invalid API route name: ${base}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/${base}`;
    }

    const routePath = normalizeRoutePath(rawRoutePath);
    routes.push({ routePath, filePath: fullPath });
  }

  routes.sort((a, b) => {
    const aCatch = a.routePath.includes('*') ? 1 : 0;
    const bCatch = b.routePath.includes('*') ? 1 : 0;
    if (aCatch !== bCatch) return aCatch - bCatch;
    const aDyn = a.routePath.includes(':') ? 1 : 0;
    const bDyn = b.routePath.includes(':') ? 1 : 0;
    if (aDyn !== bDyn) return aDyn - bDyn;
    return b.routePath.length - a.routePath.length;
  });

  return routes;
}

// ─── API Server ─────────────────────────────────────────────────────────────

interface CachedModule {
  mtime: number;
  handler: unknown;
  error?: Error;
}

async function importHandler(
  server: ViteDevServer | null,
  filePath: string,
  moduleCache: Map<string, CachedModule>,
): Promise<unknown> {
  if (server) {
    const mod = await server.ssrLoadModule(filePath);
    return mod.default ?? mod;
  }

  let mtime = 0;
  try {
    const stats = fs.statSync(filePath);
    if (stats.size > MAX_FILE_SIZE) return null;
    mtime = stats.mtimeMs;
  } catch {
    return null;
  }

  const cached = moduleCache.get(filePath);
  if (cached && cached.mtime === mtime) {
    if (cached.error) throw cached.error;
    return cached.handler;
  }

  try {
    const { pathToFileURL } = await import('url');
    const mod = await import(pathToFileURL(filePath).href + '?t=' + mtime);
    const handler = mod.default ?? null;
    moduleCache.set(filePath, { mtime, handler });
    return handler;
  } catch (error) {
    const err = error instanceof Error ? error : new Error(String(error));
    moduleCache.set(filePath, { mtime, handler: null, error: err });
    throw err;
  }
}

async function handleApiRequest(
  req: any,
  res: any,
  next: any,
  apiDir: string,
  corsConfig: boolean | { origin?: string; methods?: string[]; headers?: string[] },
  getCache: () => { routes: ApiRoute[] } | null,
  setCache: (v: { routes: ApiRoute[] }) => void,
  moduleCache: Map<string, CachedModule>,
  bodySizeLimit: number = DEFAULT_BODY_SIZE_LIMIT,
  server: ViteDevServer | null = null,
): Promise<void> {
  try {
    const allowedMethods = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'HEAD'];
    if (!allowedMethods.includes(req.method)) {
      req.resume();
      res.statusCode = 405;
      res.setHeader('Allow', allowedMethods.join(', '));
      res.end();
      return;
    }

    if (corsConfig && req.method === 'OPTIONS') {
      req.resume();
      res.statusCode = 204;

      const corsOptions = typeof corsConfig === 'boolean'
        ? { origin: '*', methods: allowedMethods, headers: 'Content-Type, Authorization, X-Requested-With' }
        : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods, headers: corsConfig.headers || 'Content-Type, Authorization, X-Requested-With' };

      res.setHeader('Access-Control-Allow-Origin', corsOptions.origin);
      res.setHeader('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
      res.setHeader('Access-Control-Allow-Headers', corsOptions.headers);
      if (corsOptions.origin !== '*') {
        res.setHeader('Access-Control-Allow-Credentials', 'true');
      }
      res.setHeader('Access-Control-Max-Age', '86400');
      res.end();
      return;
    }

    let cache = getCache();
    if (!cache) {
      const rawRoutes = scanApiRoutes(apiDir, '');
      cache = { routes: rawRoutes };
      setCache(cache);
    }

    const host = req.headers.host ?? 'localhost';
    const protocol = req.headers['x-forwarded-proto'] ?? 'http';
    const url = `${protocol}://${host}${req.url}`;

    if (!url) {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid URL');
      return;
    }

    const pathname = new URL(url).pathname;

    if (pathname.includes('..') || pathname.includes('//')) {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid path');
      return;
    }

    const contentLength = Number(req.headers['content-length'] ?? 0);
    if (contentLength > bodySizeLimit) {
      req.resume();
      res.statusCode = 413;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({
        error: 'Payload Too Large',
        message: `Request body exceeds ${bodySizeLimit} bytes limit`,
      }));
      return;
    }

    const chunks: Buffer[] = [];
    let totalSize = 0;

    for await (const chunk of req) {
      if (chunk instanceof Buffer) {
        totalSize += chunk.length;
        if (totalSize > bodySizeLimit) {
          req.resume();
          res.statusCode = 413;
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({
            error: 'Payload Too Large',
            message: `Request body exceeds ${bodySizeLimit} bytes limit`,
          }));
          return;
        }
        chunks.push(chunk);
      }
    }
    const body = chunks.length > 0 ? Buffer.concat(chunks) : undefined;

    const method = req.method;

    const webReq = new Request(url, {
      method,
      headers: normalizeHeaders(req.headers),
      body: !['GET', 'HEAD'].includes(method) && body?.length ? body : undefined,
    });

    let matchedAny = false;

    for (const route of cache.routes) {
      const params = matchRoute(route.routePath, pathname);
      if (params === null) continue;
      matchedAny = true;

      let handler;
      try {
        handler = await importHandler(server, route.filePath, moduleCache);
      } catch (error) {
        viteErrorLog(`Failed to load API handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        res.statusCode = 500;
        res.setHeader('Content-Type', 'application/json');
        res.end(JSON.stringify({ error: 'Internal Server Error' }));
        return;
      }

      if (!handler) continue;

      try {
        let webRes: Response;

        if (typeof (handler as any).fetch === 'function') {
          webRes = await (handler as any).fetch(webReq.clone());
        } else if (typeof handler === 'function') {
          const reqWithParams = new Request(webReq.clone(), {
            headers: {
              ...headersToObject(webReq.headers),
              'x-bini-params': JSON.stringify(params),
            },
          });

          webRes = await (handler as (...args: any[]) => Promise<Response>)(reqWithParams);
        } else {
          continue;
        }

        if (corsConfig) {
          const headers = new Headers(webRes.headers);
          const corsOptions = typeof corsConfig === 'boolean'
            ? { origin: '*', methods: allowedMethods }
            : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods };

          headers.set('Access-Control-Allow-Origin', corsOptions.origin);
          headers.set('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
          if (corsOptions.origin !== '*') {
            headers.set('Access-Control-Allow-Credentials', 'true');
          }

          webRes = new Response(webRes.body, {
            status: webRes.status,
            statusText: webRes.statusText,
            headers,
          });
        }

        res.statusCode = webRes.status;

        const setCookie =
          typeof (webRes.headers as any).getSetCookie === 'function'
            ? (webRes.headers as any).getSetCookie()
            : [];
        if (setCookie.length > 0) {
          res.setHeader('Set-Cookie', setCookie);
        }

        webRes.headers.forEach((value, key) => {
          if (key.toLowerCase() === 'set-cookie') return;
          res.setHeader(key, value);
        });

        if (method === 'HEAD') {
          res.end();
        } else {
          const buffer = Buffer.from(await webRes.arrayBuffer());
          res.end(buffer);
        }
        return;
      } catch (error) {
        viteErrorLog(`Error executing API handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        res.statusCode = 500;
        res.setHeader('Content-Type', 'application/json');
        res.end(JSON.stringify({ error: 'Internal Server Error' }));
        return;
      }
    }

    if (!matchedAny) {
      res.statusCode = 404;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({
        error: 'Not Found',
        message: `No API handler found for ${req.url}`,
      }));
      return;
    }

    res.statusCode = 404;
    res.setHeader('Content-Type', 'application/json');
    res.end(JSON.stringify({
      error: 'Not Found',
      message: `No API handler matched ${req.url}`,
    }));
  } catch (error) {
    viteErrorLog(`API request error: ${error instanceof Error ? error.message : String(error)}`);
    res.statusCode = 500;
    res.setHeader('Content-Type', 'application/json');
    res.end(JSON.stringify({ error: 'Internal Server Error' }));
  }
}

function normalizeHeaders(headers: Record<string, string | string[] | undefined>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers)) {
    if (v === undefined) continue;
    out[k] = Array.isArray(v) ? v.join(', ') : v;
  }
  return out;
}

function headersToObject(headers: Headers): Record<string, string> {
  const out: Record<string, string> = {};
  headers.forEach((v, k) => {
    out[k] = v;
  });
  return out;
}

// ─── Transform Helpers ───────────────────────────────────────────────────────

function stripExportByName(source: string, name: string, filePath: string): string {
  const parsed = parseFile(source, filePath);
  if (!parsed) return source;

  const range = getExportRange(parsed, name);
  if (!range) return source;

  const startChar = source.charCodeAt(range.start);
  const endChar = source.charCodeAt(range.end - 1);

  const looksValid =
    range.start >= 0 &&
    range.end <= source.length &&
    range.end > range.start &&
    (startChar === 101 || source.slice(range.start, range.start + 6) === 'export') &&
    (endChar === 59 || endChar === 125);

  if (!looksValid) {
    return stripByText(source, name);
  }

  const removed = source.slice(range.start, range.end);
  const newlineCount = (removed.match(/\n/g) ?? []).length;
  const padding = '\n'.repeat(newlineCount);
  return source.slice(0, range.start) + padding + source.slice(range.end);
}

function stripByText(source: string, name: string): string {
  const re = new RegExp(`export\\s+const\\s+${name}\\s*=`, 'g');
  let result = source;
  let match: RegExpExecArray | null;
  while ((match = re.exec(result)) !== null) {
    const braceIdx = result.indexOf('{', match.index);
    if (braceIdx === -1) break;

    let depth = 0;
    let end = braceIdx;
    let inString: string | null = null;
    let escaped = false;

    for (let i = braceIdx; i < result.length; i++) {
      const ch = result[i];
      if (inString) {
        if (escaped) escaped = false;
        else if (ch === '\\') escaped = true;
        else if (ch === inString) inString = null;
        continue;
      }
      if (ch === '"' || ch === "'" || ch === '`') {
        inString = ch;
        continue;
      }
      if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) {
          end = i;
          break;
        }
      }
    }

    let tail = end + 1;
    while (tail < result.length && (result[tail] === ' ' || result[tail] === '\t')) tail++;
    if (result[tail] === ';') tail++;

    const removed = result.slice(match.index, tail);
    const newlineCount = (removed.match(/\n/g) ?? []).length;
    const padding = '\n'.repeat(newlineCount);
    result = result.slice(0, match.index) + padding + result.slice(tail);

    re.lastIndex = match.index + padding.length;
  }
  return result;
}

function stripAppExports(source: string, filePath: string): string {
  let result = source;
  if (result.includes('export const metadata')) {
    result = stripExportByName(result, 'metadata', filePath);
  }
  if (result.includes('export const document')) {
    result = stripExportByName(result, 'document', filePath);
  }
  return result;
}

const ROUTER_EXPORTS = [
  'Link', 'NavLink', 'useNavigate', 'useParams', 'useLocation',
  'useSearchParams', 'Outlet',
] as const;

const REACT_EXPORTS = [
  'useState', 'useEffect', 'useRef', 'useMemo', 'useCallback',
  'useContext', 'createContext', 'useReducer', 'useId',
  'useTransition', 'useDeferredValue',
] as const;

const ENV_EXPORTS = ['getEnv', 'requireEnv'] as const;

interface AutoImportSpec {
  module: 'react-router-dom' | 'react' | 'bini-env';
  names: readonly string[];
}

const AUTO_IMPORTS: AutoImportSpec[] = [
  { module: 'react-router-dom', names: ROUTER_EXPORTS },
  { module: 'react', names: REACT_EXPORTS },
  { module: 'bini-env', names: ENV_EXPORTS },
];

function injectAutoImports(source: string, filePath: string): string {
  const parsed = parseFile(source, filePath);
  if (!parsed) return source;

  const existingImports = new Map<string, Set<string>>();
  const declared = new Set<string>();

  walk(parsed.program, (node) => {
    switch (node.type) {
      case 'ImportDeclaration': {
        const mod = node.source?.value;
        if (typeof mod === 'string') {
          const set = existingImports.get(mod) ?? new Set<string>();
          for (const spec of node.specifiers ?? []) {
            if (spec.local?.name) {
              declared.add(spec.local.name);
              if (spec.imported?.name) set.add(spec.imported.name);
            }
          }
          existingImports.set(mod, set);
        }
        return false;
      }
      case 'VariableDeclarator':
        collectPatternNames(node.id, declared);
        break;
      case 'FunctionDeclaration':
      case 'ClassDeclaration':
        if (node.id?.name) declared.add(node.id.name);
        break;
      case 'TSTypeAliasDeclaration':
      case 'TSInterfaceDeclaration':
      case 'TSEnumDeclaration':
      case 'TSModuleDeclaration':
        if (node.id?.name) declared.add(node.id.name);
        break;
    }
    return undefined;
  });

  const referenced = new Set<string>();
  walkReferences(parsed.program, referenced);

  const injected: string[] = [];
  for (const { module, names } of AUTO_IMPORTS) {
    const already = existingImports.get(module) ?? new Set<string>();
    const needed = names.filter(
      (n) => referenced.has(n) && !declared.has(n) && !already.has(n),
    );
    if (needed.length) {
      injected.push(`import { ${needed.join(', ')} } from '${module}';`);
    }
  }

  if (injected.length === 0) return source;

  const trimmed = source.replace(/^\uFEFF/, '');
  const directiveMatch = trimmed.match(/^(#![^\n]*\n)?(\s*['"][^'"]*['"]\s*;?\s*\n)?/);
  if (directiveMatch && directiveMatch[0]) {
    const prefix = directiveMatch[0];
    const rest = source.slice(prefix.length);
    return `${prefix}${injected.join(' ')} ${rest}`;
  }

  const prefix = injected.join(' ');
  return `${prefix} ${source}`;
}

function collectPatternNames(node: any, out: Set<string>): void {
  if (!node) return;
  switch (node.type) {
    case 'Identifier':
      out.add(node.name);
      break;
    case 'ObjectPattern':
      for (const prop of node.properties ?? []) {
        if (prop.type === 'RestElement') collectPatternNames(prop.argument, out);
        else collectPatternNames(prop.value, out);
      }
      break;
    case 'ArrayPattern':
      for (const el of node.elements ?? []) collectPatternNames(el, out);
      break;
    case 'AssignmentPattern':
      collectPatternNames(node.left, out);
      break;
    case 'RestElement':
      collectPatternNames(node.argument, out);
      break;
  }
}

function walkReferences(
  node: any,
  out: Set<string>,
  parent: any = null,
  key: string | null = null,
): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const child of node) walkReferences(child, out, parent, key);
    return;
  }
  if (typeof node.type !== 'string') return;

  if (parent?.type === 'JSXAttribute' && key === 'name') return;
  if (parent?.type === 'JSXMemberExpression' && key === 'property') return;

  if (node.type === 'JSXIdentifier') {
    if (typeof node.name === 'string') out.add(node.name);
    return;
  }

  if (node.type === 'Identifier') {
    if (isReference(node, parent, key)) out.add(node.name);
    return;
  }

  for (const k of Object.keys(node)) {
    if (k === 'type' || k === 'start' || k === 'end' || k === 'loc' || k === 'range') continue;
    const value = node[k];
    if (value && typeof value === 'object') walkReferences(value, out, node, k);
  }
}

function isReference(node: any, parent: any, key: string | null): boolean {
  if (!parent) return true;

  if (
    (parent.type === 'VariableDeclarator' && key === 'id') ||
    (parent.type === 'FunctionDeclaration' && key === 'id') ||
    (parent.type === 'FunctionExpression' && key === 'id') ||
    (parent.type === 'ClassDeclaration' && key === 'id') ||
    (parent.type === 'ClassExpression' && key === 'id') ||
    (parent.type === 'ImportDefaultSpecifier' && key === 'local') ||
    (parent.type === 'ImportNamespaceSpecifier' && key === 'local') ||
    (parent.type === 'ImportSpecifier' && key === 'local') ||
    ((parent.type === 'FunctionDeclaration' ||
      parent.type === 'FunctionExpression' ||
      parent.type === 'ArrowFunctionExpression') && key === 'params')
  ) {
    return false;
  }

  if (parent.type === 'Property' && key === 'key' && !parent.computed) return false;
  if (parent.type === 'MemberExpression' && key === 'property' && !parent.computed) return false;
  if (parent.type === 'JSXAttribute' && key === 'name') return false;
  if (
    (parent.type === 'LabeledStatement' ||
      parent.type === 'BreakStatement' ||
      parent.type === 'ContinueStatement') &&
    key === 'label'
  ) return false;

  return true;
}

// ─── HTML Escaping ───────────────────────────────────────────────────────────

function escapeHtmlText(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function escapeHtmlAttr(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function decodeHtmlEntities(str: string): string {
  return str
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

