interface CachedModule {
  mtime: number;
  size: number;
  handler: any;
  error?: Error;
}

type ApiHandlerFn = (
  req: Request,
  ctx: { params: Record<string, string>; searchParams: URLSearchParams },
) => Response | Promise<Response>;

interface LoadedApiModule {
  methods: Partial<Record<ApiMethod, ApiHandlerFn>>;
  defaultExport: unknown;
  allowed: ApiMethod[];
}

function rememberModule(cache: Map<string, CachedModule>, key: string, entry: CachedModule): void {
  if (cache.size >= MODULE_CACHE_MAX && !cache.has(key)) {
    const oldest = cache.keys().next().value;
    if (oldest !== undefined) cache.delete(oldest);
  }
  cache.set(key, entry);
}

async function importHandler(
  server: ViteDevServer | null,
  filePath: string,
  moduleCache: Map<string, CachedModule>,
): Promise<LoadedApiModule | null> {
  let mod: any;

  if (server) {
    mod = await server.ssrLoadModule(filePath);
  } else {
    let stats: fs.Stats;
    try {
      stats = fs.statSync(filePath);
      if (stats.size > MAX_FILE_SIZE) return null;
    } catch {
      return null;
    }

    const cacheKey = filePath;
    const cached = moduleCache.get(cacheKey);
    if (cached && cached.mtime === stats.mtimeMs && cached.size === stats.size) {
      if (cached.error) throw cached.error;
      mod = cached.handler;
    } else {
      try {
        const { pathToFileURL } = await import('url');
        const url = pathToFileURL(filePath).href + '?v=' + stats.mtimeMs;
        mod = await import(url);
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: mod });
      } catch (error) {
        const err = error instanceof Error ? error : new Error(String(error));
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: null, error: err });
        throw err;
      }
    }
  }

  if (!mod || typeof mod !== 'object') return null;

  const methods: Partial<Record<ApiMethod, ApiHandlerFn>> = {};
  const allowed: ApiMethod[] = [];

  for (const m of API_METHODS) {
    const fn = mod[m];
    if (typeof fn === 'function') {
      methods[m] = fn as ApiHandlerFn;
      allowed.push(m);
    }
  }

  const defaultExport = mod.default ?? null;

  return { methods, defaultExport, allowed };
}

type BodyReadResult =
  | { kind: 'ok'; body: Buffer | undefined }
  | { kind: 'timeout' }
  | { kind: 'too-large' };

async function readBodyWithTimeout(
  req: any,
  bodySizeLimit: number,
  timeoutMs = BODY_READ_TIMEOUT_MS,
): Promise<BodyReadResult> {
  let timedOut = false;
  let timer: ReturnType<typeof setTimeout>;

  const timeoutPromise = new Promise<'timeout'>((resolve) => {
    timer = setTimeout(() => {
      timedOut = true;
      resolve('timeout');
    }, timeoutMs);
  });

  const readPromise = (async (): Promise<BodyReadResult> => {
    try {
      const chunks: Buffer[] = [];
      let total = 0;
      for await (const chunk of req) {
        if (timedOut) break;
        const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
        total += buf.length;
        if (total > bodySizeLimit) {
          req.pause();
          return { kind: 'too-large' };
        }
        chunks.push(buf);
      }
      return { kind: 'ok', body: chunks.length > 0 ? Buffer.concat(chunks) : undefined };
    } catch (err) {
      if (timedOut) return { kind: 'timeout' };
      throw err;
    }
  })();

  try {
    const result = await Promise.race([readPromise, timeoutPromise]);
    if (result === 'timeout') {
      req.destroy(new Error('Request body read timeout'));
      readPromise.catch(() => {});
      return { kind: 'timeout' };
    }
    return result;
  } finally {
    clearTimeout(timer!);
  }
}

async function pipeWebResponse(res: any, webRes: Response, method: string): Promise<void> {
  if (method === 'HEAD' || !webRes.body) {
    res.end();
    return;
  }

  const reader = webRes.body.getReader();
  res.on('close', () => {
    reader.cancel().catch(() => {});
  });

  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value || value.byteLength === 0) continue;

      const chunk = Buffer.isBuffer(value) ? value : Buffer.from(value);
      if (!res.write(chunk)) {
        await new Promise<void>((resolve, reject) => {
          const onDrain = () => { res.off('error', onError); resolve(); };
          const onError = (err: Error) => { res.off('drain', onDrain); reject(err); };
          res.once('drain', onDrain);
          res.once('error', onError);
        });
      }
    }
    res.end();
  } catch (err) {
    if (!res.writableEnded) res.destroy(err as Error);
    else res.end();
  }
}

async function sendWebResponse(
  res: any,
  webRes: Response,
  method: string,
  corsConfig: boolean | { origin?: string; methods?: string[]; headers?: string[] },
  allowedMethods: string[],
): Promise<void> {
  if (corsConfig) {
    const headers = new Headers(webRes.headers);
    const corsOptions = typeof corsConfig === 'boolean'
      ? { origin: '*', methods: allowedMethods }
      : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods };

    headers.set('Access-Control-Allow-Origin', corsOptions.origin);
    headers.set('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
    if (corsOptions.origin !== '*') {
      headers.set('Access-Control-Allow-Credentials', 'true');
    }

    webRes = new Response(webRes.body, {
      status: webRes.status,
      statusText: webRes.statusText,
      headers,
    });
  }

  res.statusCode = webRes.status;

  const setCookie =
    typeof (webRes.headers as any).getSetCookie === 'function'
      ? (webRes.headers as any).getSetCookie()
      : [];
  if (setCookie.length > 0) {
    res.setHeader('Set-Cookie', setCookie);
  }

  webRes.headers.forEach((value, key) => {
    if (key.toLowerCase() === 'set-cookie') return;
    res.setHeader(key, value);
  });

  await pipeWebResponse(res, webRes, method);
}

async function handleApiRequest(
  req: any,
  res: any,
  next: any,
  apiDir: string,
  corsConfig: boolean | { origin?: string; methods?: string[]; headers?: string[] },
  bodySizeLimit: number,
  getCache: () => { routes: ApiRoute[] } | null,
  setCache: (v: { routes: ApiRoute[] }) => void,
  moduleCache: Map<string, CachedModule>,
  server: ViteDevServer | null = null,
): Promise<void> {
  res.on('error', () => {});

  try {
    const allowedMethods = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'HEAD'];
    if (!allowedMethods.includes(req.method)) {
      req.resume();
      res.statusCode = 405;
      res.setHeader('Allow', allowedMethods.join(', '));
      res.end();
      return;
    }

    if (
      corsConfig &&
      req.method === 'OPTIONS' &&
      req.headers['access-control-request-method']
    ) {
      req.resume();
      res.statusCode = 204;

      const corsOptions = typeof corsConfig === 'boolean'
        ? { origin: '*', methods: allowedMethods, headers: 'Content-Type, Authorization, X-Requested-With' }
        : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods, headers: corsConfig.headers || 'Content-Type, Authorization, X-Requested-With' };

      res.setHeader('Access-Control-Allow-Origin', corsOptions.origin);
      res.setHeader('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
      res.setHeader('Access-Control-Allow-Headers', corsOptions.headers);
      if (corsOptions.origin !== '*') {
        res.setHeader('Access-Control-Allow-Credentials', 'true');
      }
      res.setHeader('Access-Control-Max-Age', '86400');
      res.end();
      return;
    }

    let cache = getCache();
    if (!cache) {
      const rawRoutes = scanApiRoutes(apiDir, '');
      cache = { routes: rawRoutes };
      setCache(cache);
    }

    const strippedUrl = req.url ?? '/';
    const urlForRequest = buildRequestUrl(req, strippedUrl);

    let pathname: string;
    try {
      pathname = new URL(urlForRequest).pathname;
    } catch {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid URL');
      return;
    }

    if (pathname.includes('..') || pathname.includes('//')) {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid path');
      return;
    }

    const contentLength = Number(req.headers['content-length'] ?? 0);
    if (contentLength > bodySizeLimit) {
      req.resume();
      res.statusCode = 413;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({
        error: 'Payload Too Large',
        message: `Request body exceeds ${bodySizeLimit} bytes limit`,
      }));
      return;
    }

    const bodyResult = await readBodyWithTimeout(req, bodySizeLimit);
    if (bodyResult.kind === 'timeout') {
      res.statusCode = 408;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ error: 'Request Timeout' }));
      return;
    }
    if (bodyResult.kind === 'too-large') {
      const payload = JSON.stringify({
        error: 'Payload Too Large',
        message: `Request body exceeds ${bodySizeLimit} bytes limit`,
      });
      res.statusCode = 413;
      res.setHeader('Content-Type', 'application/json');
      res.setHeader('Content-Length', String(Buffer.byteLength(payload)));
      res.end(payload, () => {
        req.destroy();
      });
      return;
    }
    const body = bodyResult.body;

    const method = req.method;
    const searchParams = new URL(urlForRequest).searchParams;

    const webReq = new Request(urlForRequest, {
      method,
      headers: normalizeHeaders(req.headers),
      body: !['GET', 'HEAD'].includes(method) && body?.length
        ? new Uint8Array(body)
        : undefined,
    });

    for (const route of cache.routes) {
      const params = matchRoute(route.routePath, pathname, {
        enforceNonEmptyCatchAll: true,
        catchallParamName: route.catchallParamName,
      });
      if (params === null) continue;

      let loaded: LoadedApiModule | null;
      try {
        loaded = await importHandler(server, route.filePath, moduleCache);
      } catch (error) {
        viteErrorLog(`Failed to load API handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        res.statusCode = 500;
        res.setHeader('Content-Type', 'application/json');
        res.end(JSON.stringify({ error: 'Internal Server Error' }));
        return;
      }

      if (!loaded) continue;

      const { methods: methodHandlers, defaultExport, allowed } = loaded;

      if (allowed.length > 0) {
        const handlerFn = methodHandlers[method as ApiMethod];

        if (!handlerFn) {
          res.statusCode = 405;
          res.setHeader('Allow', allowed.join(', '));
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'Method Not Allowed', allow: allowed }));
          return;
        }

        let webRes: Response;
        try {
          webRes = await handlerFn(webReq.clone(), { params, searchParams });
        } catch (error) {
          webReq.body?.cancel().catch(() => {});
          viteErrorLog(`Error in ${method} handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
          if (!res.headersSent) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: 'Internal Server Error' }));
          }
          return;
        }

        await sendWebResponse(res, webRes, method, corsConfig, allowedMethods);
        return;
      }

      if (!defaultExport) continue;

      let webRes: Response;
      try {
        if (typeof (defaultExport as any).fetch === 'function') {
          webRes = await (defaultExport as any).fetch(webReq.clone());
        } else if (typeof defaultExport === 'function') {
          webRes = await (defaultExport as ApiHandlerFn)(webReq.clone(), { params, searchParams });
        } else {
          continue;
        }
      } catch (error) {
        webReq.body?.cancel().catch(() => {});
        viteErrorLog(`Error in default handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        if (!res.headersSent) {
          res.statusCode = 500;
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'Internal Server Error' }));
        }
        return;
      }

      await sendWebResponse(res, webRes, method, corsConfig, allowedMethods);
      return;
    }

    res.statusCode = 404;
    res.setHeader('Content-Type', 'application/json');
    res.end(JSON.stringify({
      error: 'Not Found',
      message: `No API handler matched ${req.url}`,
    }));
  } catch (error) {
    viteErrorLog(`API request error: ${error instanceof Error ? error.message : String(error)}`);
    if (!res.headersSent) {
      res.statusCode = 500;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ error: 'Internal Server Error' }));
    }
  }
}

function normalizeHeaders(headers: Record<string, string | string[] | undefined>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers)) {
    if (v === undefined) continue;
    if (HOP_BY_HOP_HEADERS.has(k.toLowerCase())) continue;
    out[k] = Array.isArray(v) ? v.join(', ') : v;
  }
  return out;
}

