const IPV6_HOST_PATTERN = /^\[[0-9a-f:.]+\](?::\d{1,5})?$/i;
const HOSTNAME_HOST_PATTERN = /^[a-z0-9.-]+(?::\d{1,5})?$/;

function isSafeHost(host: string): boolean {
  if (!host || host.length > MAX_HOST_LENGTH) return false;
  if (IPV6_HOST_PATTERN.test(host)) return true;
  const noPort = host.replace(/:\d{1,5}$/, '');
  if (noPort.length === 0 || noPort.length > MAX_HOST_LENGTH) return false;
  return HOSTNAME_HOST_PATTERN.test(noPort);
}

