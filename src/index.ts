  const needsDefault404 = !hasRootCustomNotFound || nfRefs.includes('Default404');
  const globalErrorName = resolveGlobalError(appDir, ctx, lazyImports, importedModules);

  const withParamsFn = generateWithParams(ts);
  const navTrackerFn = NAV_TRACKER;
  const interceptGateFn = hasIntercepts ? INTERCEPT_GATE_COMPONENT : '';
  const slotOutletFn = hasParallelRoutes ? SLOT_OUTLET_COMPONENT : '';
  const spinnerFn = usesDefaultSpinner ? DEFAULT_LOADING_COMPONENT : '';
