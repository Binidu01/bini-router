function injectRootHtml(template: string, inner: string): string {
  const re = /<div\s+id=["']root["'][^>]*>[\s\S]*?<\/div>/;
  if (re.test(template)) return template.replace(re, `<div id="root">${inner}</div>`);
  if (/<\/body>/i.test(template)) return template.replace(/<\/body>/i, `<div id="root">${inner}</div></body>`);
  return template + `<div id="root">${inner}</div>`;
}

