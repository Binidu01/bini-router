export function biniroute(options: BiniPluginOptions = {}): Plugin[] {
  const {
    cors: corsConfig = false,
    strictMode = true,
    bodySizeLimit = DEFAULT_BODY_SIZE_LIMIT,
    document: documentEnabled = true,
  } = options;

  let projectRoot = process.cwd();

  const getAppDir = (): string => path.join(projectRoot, options.appDir ?? 'src/app');
  const getApiDir = (): string => path.join(projectRoot, options.apiDir ?? 'src/app/api');
  const getAutoImportDir = (): string =>
    path.join(projectRoot, options.autoImportDir ?? 'src');

  let debounceTimer: ReturnType<typeof setTimeout> | null = null;
  let lastGeneratedCode = '';
  let apiRouteCache: { routes: ApiRoute[] } | null = null;
  const moduleCache = new Map<string, CachedModule>();
  let isGenerating = false;
  let cachedAppFile: string | null = null;
  let cachedAppFileRoot: string | null = null;

  let isBuild = false;
  let viteBase = '/';

  function getAppFileCached(): string {
    if (cachedAppFile && cachedAppFileRoot === projectRoot) return cachedAppFile;
    cachedAppFile = getAppFile(projectRoot);
    cachedAppFileRoot = projectRoot;
    return cachedAppFile;
  }

  function isPageFile(f: string): boolean {
    const nf = norm(f);
    const base = path.basename(f, path.extname(f));
    const ext = path.extname(f);

    if (!(SUPPORTED_EXTS as readonly string[]).includes(ext)) return false;
    if (!isInDir(nf, norm(getAppDir()))) return false;
    if (isInDir(nf, norm(getApiDir()))) return false;
    if (base.startsWith('_')) return false;

    return true;
  }

  function isApiFile(f: string): boolean {
    const nf = norm(f);
    return isInDir(nf, norm(getApiDir())) &&
      (API_EXTS as readonly string[]).includes(path.extname(f));
  }

  function applyApp(): string | null {
    if (isGenerating) return null;
    isGenerating = true;
    warnedMessages.clear();

    try {
      const dir = getAppDir();
      if (!fs.existsSync(dir)) return null;

      const basename = options.basename
        ? toBasename(options.basename, true)
        : toBasename(viteBase);

      const code = generateApp(dir, getApiDir(), projectRoot, strictMode, basename);
      if (code === lastGeneratedCode) return null;

      const appFile = getAppFileCached();

      let existingCode = '';
      try {
        existingCode = fs.readFileSync(appFile, 'utf8');
      } catch {
        // File doesn't exist yet.
      }

      if (existingCode && !existingCode.includes(GENERATED_HEADER)) {
        const msg = `${path.relative(projectRoot, appFile)} exists but is not bini-generated. ` +
          `Delete it or move it aside to let bini-router manage this file.`;
        if (isBuild) {
          throw new Error(msg);
        }
        viteWarnLog(msg);
        return null;
      }

      if (existingCode === code) {
        lastGeneratedCode = code;
        return null;
      }

      fs.mkdirSync(path.dirname(appFile), { recursive: true });
      fs.writeFileSync(appFile, code, 'utf8');
      lastGeneratedCode = code;

      return code;
    } catch (error) {
      if (isBuild) {
        throw error;
      }
      if (error instanceof RouteConflictError) {
        viteErrorLog(error.message);
        return null;
      }
      viteErrorLog(`Failed to generate app: ${error instanceof Error ? error.message : String(error)}`);
      return null;
    } finally {
      isGenerating = false;
    }
  }

  function scheduleRegen(server: ViteDevServer, delay = DEBOUNCE_MS): void {
    if (debounceTimer) clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      debounceTimer = null;
      if (applyApp() !== null) {
        const mod = server.moduleGraph.getModuleById('\0virtual:bini-routes');
        if (mod) server.moduleGraph.invalidateModule(mod);
        server.ws.send({ type: 'full-reload', path: '*' });
      }
    }, delay);
  }

  function createApiMiddleware(server: ViteDevServer | null) {
    return (req: any, res: any, next: any) => {
      if (!req.url) return next();

      const apiPath = resolveApiPath(req.url, viteBase);
      if (apiPath === null) return next();

      const apiDir = getApiDir();
      if (!fs.existsSync(apiDir)) {
        return next();
      }

      req.url = apiPath;

      handleApiRequest(
        req, res, next, apiDir, corsConfig,
        () => apiRouteCache, (v) => { apiRouteCache = v; },
        moduleCache, bodySizeLimit, server,
      );
    };
  }

  const routerPlugin: Plugin = {
    name: 'bini-router',
    enforce: 'pre',

    config(_, env) {
      isBuild = env.command === 'build';
    },

    configResolved(config) {
      const newRoot = config.root || process.cwd();
      if (newRoot !== projectRoot) {
        cachedAppFile = null;
        cachedAppFileRoot = null;
      }
      projectRoot = newRoot;

      const newBase = config.base || '/';
      viteBase = newBase;

      applyApp();
    },

    transform: {
      filter: {
        id: { include: /\.(tsx|jsx|ts|js|mdx|md)$/ },
      },
      handler(code, id) {
        const nid = norm(id);
        const autoImportDir = getAutoImportDir();
        const appDir = getAppDir();
        const apiDir = getApiDir();

        if (!isInDir(nid, norm(autoImportDir))) return;
        if (isInDir(nid, norm(apiDir))) return;
        if (nid === norm(getAppFileCached())) return;
        if (nid.endsWith('.mdx') || nid.endsWith('.md')) return;

        let result = code;

        if (isInDir(nid, norm(appDir)) &&
            (result.includes('export const metadata') || result.includes('export const document'))) {
          result = stripAppExports(result, id);
        }

        result = injectAutoImports(result, id);

        if (result === code) return;

        return { code: result, map: null };
      },
    },

    buildStart(): void {
      if (!lastGeneratedCode) {
        applyApp();
      }
    },

    buildEnd(): void {
      apiRouteCache = null;
      moduleCache.clear();
      if (debounceTimer) {
        clearTimeout(debounceTimer);
        debounceTimer = null;
      }
    },

    async configureServer(server): Promise<void> {
      const appDir = getAppDir();
      const apiDir = getApiDir();

      if (!fs.existsSync(appDir)) return;

      if (!lastGeneratedCode) {
        applyApp();
      }

      server.watcher.add(appDir);

      const watcherEvents = ['add', 'unlink', 'change'] as const;
      for (const event of watcherEvents) {
        server.watcher.on(event, (f) => {
          try {
            if (isPageFile(f)) {
              scheduleRegen(server, event === 'add' ? 300 : DEBOUNCE_MS);
            }
          } catch (error) {
            viteErrorLog(`Error handling file ${event}: ${error instanceof Error ? error.message : String(error)}`);
          }
        });
      }

      server.watcher.on('change', (f) => {
        try {
          const base = path.basename(f, path.extname(f));
          const inAppRoot = path.resolve(path.dirname(f)) === path.resolve(appDir);
          if (inAppRoot && base === 'layout') {
            server.moduleGraph.invalidateAll();
            server.ws.send({ type: 'full-reload', path: '*' });
          }
        } catch (error) {
          viteErrorLog(`Error handling layout change: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      server.watcher.on('addDir', (d) => {
        try {
          const nd = norm(d);
          if (!isInDir(nd, norm(appDir)) || d.includes('node_modules') || isInDir(nd, norm(apiDir))) return;
          server.watcher.add(d);
          setTimeout(() => {
            if (PAGE_FILES.some(f => fs.existsSync(path.join(d, f)))) {
              scheduleRegen(server, 300);
            }
          }, 300);
        } catch (error) {
          viteErrorLog(`Error handling directory add: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      server.watcher.on('unlinkDir', (d) => {
        try {
          const nd = norm(d);
          if (isInDir(nd, norm(appDir)) && !d.includes('node_modules') && !isInDir(nd, norm(apiDir))) {
            scheduleRegen(server);
          }
        } catch (error) {
          viteErrorLog(`Error handling directory unlink: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      // Watch the parent of apiDir to detect its creation after startup.
      const apiParent = path.dirname(apiDir);
      if (fs.existsSync(apiParent)) {
        server.watcher.add(apiParent);

        server.watcher.on('addDir', (d) => {
          const nd = norm(d);
          if (nd === norm(apiDir)) {
            server.watcher.add(apiDir);
            apiRouteCache = null;
            viteLog(apiDir, 'api directory created');
          }
        });
      }

      if (fs.existsSync(apiDir)) {
        server.watcher.add(apiDir);

        const resetApi = (f?: string, event?: string): void => {
          apiRouteCache = null;
          if (f) moduleCache.delete(f);
          if (f) viteLog(f, event === 'add' ? 'api route added' : event === 'unlink' ? 'api route removed' : 'hmr update');
          if (event === 'add' || event === 'unlink') {
            server.ws.send({ type: 'full-reload', path: '*' });
          }
        };

        server.watcher.on('add', (f) => {
          if (isApiFile(f)) resetApi(f, 'add');
        });

        server.watcher.on('unlink', (f) => {
          if (isApiFile(f)) resetApi(f, 'unlink');
        });

        server.watcher.on('change', (f) => {
          if (isApiFile(f)) resetApi(f, 'change');
        });
      }

      // Always register API middleware, regardless of whether apiDir
      // exists at startup. It checks existence at request time.
      server.middlewares.use(createApiMiddleware(server));
    },

    async configurePreviewServer(server): Promise<void> {
      server.middlewares.use(createApiMiddleware(null));
    },

    transformIndexHtml: {
      order: 'post',
      handler(html, _ctx) {
        try {
          const base = viteBase || '/';
          const appDir = getAppDir();

          if (documentEnabled) {
            const rootLayout = findFile(appDir, LAYOUT_FILES);
            if (rootLayout) {
              const layoutPath = path.join(appDir, rootLayout);
              const doc = parseDocumentExport(layoutPath);
              if (doc) {
                if (doc.html) {
                  html = html.replace(/<html([^>]*)>/i, (_m, existing) =>
                    `<html${mergeAttrs(existing, doc.html)}>`
                  );
                }
                if (doc.body) {
                  html = html.replace(/<body([^>]*)>/i, (_m, existing) =>
                    `<body${mergeAttrs(existing, doc.body)}>`
                  );
                }
                if (doc.head) {
                  if (html.includes('</head>')) {
                    html = html.replace('</head>', () => `${doc.head}</head>`);
                  }
                }
              }
            }
          }

          const meta = parseAppMetadata(appDir);

          if (Object.keys(meta).length > 0) {
            const rawTitle = meta.title;
            const metaTitle =
              typeof rawTitle === 'string'
                ? rawTitle
                : rawTitle && typeof rawTitle === 'object'
                  ? (rawTitle.default ?? '')
                  : '';

            const tags: HtmlTagDescriptor[] = [];

            if (meta.charset) {
              html = html.replace(/<meta\s+charset\s*=\s*['"][^'"]*['"]\s*\/?>/gi, '');
              tags.push(headTag('meta', { charset: meta.charset }));
            }

            if (meta.viewport) {
              html = html.replace(/<meta\s+name=['"]viewport['"][^>]*\/?>/gi, '');
              tags.push(headTag('meta', { name: 'viewport', content: meta.viewport }));
            }

            if (metaTitle) {
              html = html.replace(/<title>[^<]*<\/title>/gi, '');
              tags.push({
                tag: 'title',
                children: escapeHtmlText(metaTitle),
                injectTo: 'head-prepend',
              });
            }

            if (meta.description) {
              html = stripMetaByName(html, 'description');
              tags.push(headTag('meta', { name: 'description', content: meta.description }));
            }
            if (meta.themeColor) {
              html = stripMetaByName(html, 'theme-color');
              tags.push(headTag('meta', { name: 'theme-color', content: meta.themeColor }));
            }
            if (meta.robots) {
              html = stripMetaByName(html, 'robots');
              tags.push(headTag('meta', { name: 'robots', content: meta.robots }));
            }
            if (meta.keywords) {
              html = stripMetaByName(html, 'keywords');
              tags.push(headTag('meta', { name: 'keywords', content: meta.keywords }));
            }
            if (meta.author) {
              html = stripMetaByName(html, 'author');
              tags.push(headTag('meta', { name: 'author', content: meta.author }));
            }

            if (meta.canonical) {
              html = stripLinkByRel(html, 'canonical');
              tags.push(headTag('link', { rel: 'canonical', href: withBase(meta.canonical, base) }));
            }
            if (meta.manifest) {
              html = stripLinkByRel(html, 'manifest');
              tags.push(headTag('link', { rel: 'manifest', href: withBase(meta.manifest, base) }));
            }

            for (const entry of meta.icons?.icon ?? []) {
              const attrs: Record<string, string> = { rel: 'icon', href: withBase(entry.url, base) };
              if (entry.type) attrs.type = entry.type;
              if (entry.sizes) attrs.sizes = entry.sizes;
              tags.push(headTag('link', attrs));
            }

            for (const entry of meta.icons?.shortcut ?? []) {
              tags.push(headTag('link', { rel: 'shortcut icon', href: withBase(entry.url, base) }));
            }

            for (const entry of meta.icons?.apple ?? []) {
              const attrs: Record<string, string> = { rel: 'apple-touch-icon', href: withBase(entry.url, base) };
              if (entry.sizes) attrs.sizes = entry.sizes;
              if (entry.type) attrs.type = entry.type;
              tags.push(headTag('link', attrs));
            }

            if (meta.openGraph?.title) {
              tags.push(headTag('meta', { property: 'og:type', content: meta.openGraph.type ?? 'website' }));
              tags.push(headTag('meta', { property: 'og:title', content: meta.openGraph.title }));
              if (meta.openGraph.description) {
                tags.push(headTag('meta', { property: 'og:description', content: meta.openGraph.description }));
              }
              if (meta.openGraph.url) tags.push(headTag('meta', { property: 'og:url', content: meta.openGraph.url }));
              if (meta.openGraph.image) tags.push(headTag('meta', { property: 'og:image', content: withBase(meta.openGraph.image, base) }));
            }

            if (meta.twitter?.title) {
              tags.push(headTag('meta', { name: 'twitter:card', content: meta.twitter.card ?? 'summary_large_image' }));
              tags.push(headTag('meta', { name: 'twitter:title', content: meta.twitter.title }));
              if (meta.twitter.description) {
                tags.push(headTag('meta', { name: 'twitter:description', content: meta.twitter.description }));
              }
              if (meta.twitter.creator) tags.push(headTag('meta', { name: 'twitter:creator', content: meta.twitter.creator }));
              if (meta.twitter.image) tags.push(headTag('meta', { name: 'twitter:image', content: withBase(meta.twitter.image, base) }));
            }

            return { html, tags };
          }

          return html;
        } catch (error) {
          viteErrorLog(`Error transforming index.html: ${error instanceof Error ? error.message : String(error)}`);
          return html;
        }
      },
    },

    resolveId(id) {
      if (id === 'virtual:bini-routes' || id === '\0virtual:bini-routes') {
        return '\0virtual:bini-routes';
      }
      return null;
    },

    load(id) {
      if (id === '\0virtual:bini-routes') {
        const appDir = getAppDir();
        const apiDir = getApiDir();
        return getRouteManifestModule(appDir, apiDir);
      }
      return null;
    },
  };

  const mdxPlugin = mdx({
    jsxImportSource: 'react',
    mdExtensions: [],
    mdxExtensions: ['.mdx', '.md'],
    ...options.mdx,
  }) as unknown as Plugin;

  return [routerPlugin, mdxPlugin];
}

