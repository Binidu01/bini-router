function resolveGlobalError(
  appDir: string,
  ctx: ImportContext,
  lazyImports: string[],
  importedModules: Set<string>,
): string | null {
  const file = findFile(appDir, GLOBAL_ERROR_FILES);
  if (!file) return null;

  const fullPath = path.join(appDir, file);
  if (!isUsableLayout(fullPath)) return null;

  const importPath = toImportPath(fullPath, ctx.importRoot);
  const name = 'GlobalError';
  if (!importedModules.has(importPath)) {
    lazyImports.push(`const ${name} = React.lazy(() => import('${importPath}'));`);
    importedModules.add(importPath);
  }
  return name;
}

function toImportPath(filePath: string, fromDir: string): string {
  const keepExt = path.extname(filePath) === '.mdx' || path.extname(filePath) === '.md';

  let rel = norm(path.relative(fromDir, filePath));
  if (!rel.startsWith('.')) rel = './' + rel;
  if (!keepExt) rel = rel.replace(/\.(tsx|ts|jsx|js)$/, '');
  return rel;
}

// ─── Route Segments ───────────────────────────────────────────────────────────

function isValidRouteSegment(segment: string): boolean {
  if (!segment || segment.length === 0) return false;
  if (segment.length > MAX_ROUTE_SEGMENT_LENGTH) return false;
  return ALLOWED_ROUTE_PATTERN.test(segment);
}

function isValidParamName(name: string): boolean {
  if (!name || name.length === 0) return false;
  if (name.length > MAX_ROUTE_SEGMENT_LENGTH) return false;
  return ALLOWED_PARAM_PATTERN.test(name);
}

function normalizeRoutePath(routePath: string): string {
  let normalized = routePath.replace(/\/+/g, '/');
  if (normalized === '') return '/';
  if (!normalized.startsWith('/')) normalized = '/' + normalized;
  if (normalized.endsWith('/') && normalized !== '/') normalized = normalized.slice(0, -1);
  return normalized;
}

function isRouteGroup(name: string): boolean {
  return name.startsWith('(') && name.endsWith(')') && !isInterceptingRoute(name);
}

function isInterceptingRoute(name: string): boolean {
  return (
    name.startsWith('(.)') ||
    name.startsWith('(..)') ||
    name.startsWith('(...)')
  );
}

function interceptLevelFromName(name: string): InterceptLevel {
  if (name.startsWith('(...)')) return 'root';
  if (name.startsWith('(..)')) return 'up';
  if (name.startsWith('(.)')) return 'same';
  return 'none';
}

function stripInterceptPrefix(name: string): string {
  if (name.startsWith('(...)')) return name.slice(5);
  if (name.startsWith('(..)')) return name.slice(4);
  if (name.startsWith('(.)')) return name.slice(3);
  return name;
}

function isRouteSlot(name: string): boolean {
  return name.startsWith('@') && name.length > 1;
}

function isGroupNameValid(name: string): boolean {
  return ALLOWED_GROUP_PATTERN.test(name);
}

function isSlotNameValid(name: string): boolean {
  return ALLOWED_SLOT_PATTERN.test(name);
}

function segmentFromName(entryName: string): RouteSegment | null {
  if (isRouteGroup(entryName)) return null;
  if (entryName.startsWith('[[...') && entryName.endsWith(']]')) {
    const name = entryName.slice(5, -2);
    if (!isValidParamName(name)) return null;
    return { kind: 'catchall-optional', value: name };
  }
  if (entryName.startsWith('[...') && entryName.endsWith(']')) {
    const name = entryName.slice(4, -1);
    if (!isValidParamName(name)) return null;
    return { kind: 'catchall', value: name };
  }
  if (entryName.startsWith('[') && entryName.endsWith(']')) {
    const name = entryName.slice(1, -1);
    if (!isValidParamName(name)) return null;
    return { kind: 'dynamic', value: name };
  }
  if (!isValidRouteSegment(entryName)) return null;
  return { kind: 'static', value: entryName };
}

function segmentToRoutePath(segment: RouteSegment): string {
  if (segment.kind === 'dynamic') return `:${segment.value}`;
  if (segment.kind === 'catchall' || segment.kind === 'catchall-optional') return '*';
  return segment.value;
}

function requiredCatchallGuardPath(routePath: string): string | null {
  if (!routePath.endsWith('/*')) return null;
  const parent = routePath.slice(0, -2);
  return parent === '' ? '/' : parent;
}

// ─── Not-Found Boundaries ─────────────────────────────────────────────────────

interface NotFoundBoundary {
  dirRoutePath: string;
  filePath: string;
  layouts: string[];
}

function collectNotFoundBoundaries(
  dir: string,
  appDir: string,
  apiDir: string,
  baseRoute = '',
  depth = 0,
  out: NotFoundBoundary[] = [],
): NotFoundBoundary[] {
  if (depth > MAX_DEPTH) return out;
  if (!fs.existsSync(dir)) return out;

  const nfFile = findFile(dir, NOT_FOUND_FILES);
  if (nfFile) {
    const fullPath = path.join(dir, nfFile);
    const parsed = readAndParse(fullPath);
    if (parsed && hasDefaultExport(parsed)) {
      out.push({
        dirRoutePath: normalizeRoutePath(baseRoute || '/'),
        filePath: fullPath,
        layouts: resolveLayoutChain(dir, appDir).filter(l => isUsableLayout(l)),
      });
    }
  }

  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }

  entries.sort((a, b) => cmpStr(a.name, b.name));

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;

    const fullPath = path.join(dir, entry.name);
    if (path.resolve(fullPath) === path.resolve(apiDir)) continue;
    if (entry.name.startsWith('_')) continue;

    const isGroup = isRouteGroup(entry.name);
    const isSlot = isRouteSlot(entry.name);
    const segment = isSlot ? null : segmentFromName(entry.name);

    if (!segment && !isGroup && !isSlot) continue;

    const nextBase = segment ? `${baseRoute}/${segmentToRoutePath(segment)}` : baseRoute;

    collectNotFoundBoundaries(fullPath, appDir, apiDir, nextBase, depth + 1, out);
  }

  return out;
}

// ─── Route Scanning ───────────────────────────────────────────────────────────

function scanRoutes(
  dir: string,
  appDir: string,
  apiDir: string,
  baseRoute = '',
  baseSegments: RouteSegment[] = [],
  depth = 0,
  currentSlot: string | null = null,
): RouteNode[] {
  if (depth > MAX_DEPTH) {
    viteWarnLog(`Maximum directory depth reached at ${dir}`);
    return [];
  }

  const routes: RouteNode[] = [];
  if (!fs.existsSync(dir)) return routes;

  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (error) {
    viteErrorLog(`Failed to read directory ${dir}: ${error instanceof Error ? error.message : String(error)}`);
    return routes;
  }

  entries.sort((a, b) => cmpStr(a.name, b.name));

  for (const entry of entries) {
    if (!entry.isFile() || entry.name.startsWith('.') || entry.name.startsWith('_')) continue;

    const ext = path.extname(entry.name);
    const base = path.basename(entry.name, ext);

    if (!(SUPPORTED_EXTS as readonly string[]).includes(ext)) continue;
    if (SPECIAL_BASES.has(base)) continue;

    const segment = segmentFromName(base);
    if (!segment) {
      warnOnceMsg(`Invalid route segment name: ${base} in ${dir}`);
      continue;
    }

    const isIndex = segment.kind === 'static' && segment.value === 'index';
    const rawPath = isIndex
      ? baseRoute || '/'
      : `${baseRoute}/${segmentToRoutePath(segment)}`;
    const routePath = normalizeRoutePath(rawPath);
    const fullFilePath = path.join(dir, entry.name);
    const segments = isIndex ? baseSegments : [...baseSegments, segment];

    routes.push({
      routePath,
      filePath: fullFilePath,
      layouts: resolveLayoutChain(dir, appDir),
      template: resolveTemplate(dir, appDir),
      dynamic: segment.kind === 'dynamic' || segment.kind === 'catchall' || segment.kind === 'catchall-optional',
      segments,
      hasRequiredCatchall: segments.some(s => s.kind === 'catchall'),
      hasOptionalCatchall: segments.some(s => s.kind === 'catchall-optional'),
      slotName: currentSlot,
      interceptLevel: 'none',
      interceptSourcePath: null,
    });
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    if (entry.name.startsWith('_')) continue;

    const fullPath = path.join(dir, entry.name);
    if (path.resolve(fullPath) === path.resolve(apiDir)) continue;

    // Parallel route slot: @name — not a URL segment, but children inherit slotName.
    if (isRouteSlot(entry.name)) {
      const slotName = entry.name.slice(1);
      if (!isSlotNameValid(slotName)) {
        warnOnceMsg(`Invalid slot name: ${entry.name} in ${dir}`);
        continue;
      }
      routes.push(...scanRoutes(fullPath, appDir, apiDir, baseRoute, baseSegments, depth + 1, slotName));
      continue;
    }

    // Intercepting route: (.)(..)(...)name — not a URL segment by itself,
    // but the *target* path is derived from the intercept level.
    if (isInterceptingRoute(entry.name)) {
      const level = interceptLevelFromName(entry.name);
      const stripped = stripInterceptPrefix(entry.name);
      if (!stripped) {
        warnOnceMsg(`Invalid intercepting route: ${entry.name} in ${dir}`);
        continue;
      }
      const segment = segmentFromName(stripped);
      if (!segment) {
        warnOnceMsg(`Invalid intercepting route segment: ${entry.name} in ${dir}`);
        continue;
      }

      const nextSegments = [...baseSegments, segment];
      const nextBase = `${baseRoute}/${segmentToRoutePath(segment)}`;
      const interceptSourcePath = computeInterceptSource(baseRoute, level);

      const pageFile = findFile(fullPath, PAGE_FILES);
      if (pageFile) {
        const fullFilePath = path.join(fullPath, pageFile);
        routes.push({
          routePath: normalizeRoutePath(nextBase),
          filePath: fullFilePath,
          layouts: resolveLayoutChain(fullPath, appDir),
          template: resolveTemplate(fullPath, appDir),
          dynamic: nextSegments.some(s => s.kind !== 'static'),
          segments: nextSegments,
          hasRequiredCatchall: nextSegments.some(s => s.kind === 'catchall'),
          hasOptionalCatchall: nextSegments.some(s => s.kind === 'catchall-optional'),
          slotName: currentSlot,
          interceptLevel: level,
          interceptSourcePath,
        });
      }

      const sub = scanRoutes(fullPath, appDir, apiDir, nextBase, nextSegments, depth + 1, currentSlot);
      for (const r of sub) {
        if (r.interceptLevel === 'none') {
          r.interceptLevel = level;
          r.interceptSourcePath = interceptSourcePath;
        }
      }
      routes.push(...sub);
      continue;
    }

    const isGroup = isRouteGroup(entry.name);
    if (isGroup) {
      const groupName = entry.name.slice(1, -1);
      if (!isGroupNameValid(groupName)) {
        warnOnceMsg(`Invalid route group name: ${entry.name} in ${dir}`);
        continue;
      }
    }

    const segment = segmentFromName(entry.name);

    if (!segment && !isGroup) {
      warnOnceMsg(`Skipping directory with invalid route name: ${entry.name}`);
      continue;
    }

    const nextSegments = segment ? [...baseSegments, segment] : baseSegments;
    const nextBase = segment ? `${baseRoute}/${segmentToRoutePath(segment)}` : baseRoute;

    const pageFile = findFile(fullPath, PAGE_FILES);

    if (pageFile) {
      const fullFilePath = path.join(fullPath, pageFile);
      const routePath = normalizeRoutePath(nextBase);
      routes.push({
        routePath,
        filePath: fullFilePath,
        layouts: resolveLayoutChain(fullPath, appDir),
        template: resolveTemplate(fullPath, appDir),
        dynamic: nextSegments.some(s => s.kind === 'dynamic' || s.kind === 'catchall' || s.kind === 'catchall-optional'),
        segments: nextSegments,
        hasRequiredCatchall: nextSegments.some(s => s.kind === 'catchall'),
        hasOptionalCatchall: nextSegments.some(s => s.kind === 'catchall-optional'),
        slotName: currentSlot,
        interceptLevel: 'none',
        interceptSourcePath: null,
      });
    }

    routes.push(...scanRoutes(fullPath, appDir, apiDir, nextBase, nextSegments, depth + 1, currentSlot));
  }

  return routes;
}

/**
 * Compute the URL path an intercepting route intercepts from, given the
 * current base route and the intercept level.
 *   (.)  → same level (base route)
 *   (..) → one level up
 *   (...) → root
 */
function computeInterceptSource(baseRoute: string, level: InterceptLevel): string | null {
  if (level === 'none') return null;
  if (level === 'root') return '/';
  const parts = baseRoute.split('/').filter(Boolean);
  if (level === 'same') return normalizeRoutePath('/' + parts.join('/'));
  if (level === 'up') {
    parts.pop();
    return normalizeRoutePath('/' + parts.join('/'));
  }
  return null;
}

function detectRouteConflicts(routes: RouteNode[]): RouteConflict[] {
  const routeMap = new Map<string, string[]>();

  for (const route of routes) {
    // Intercepting routes are alternate renderings of the same path, not
    // conflicts against the target path. Only compare same intercept level.
    const key = `${route.routePath}::${route.interceptLevel}`;
    const existing = routeMap.get(key) || [];
    existing.push(route.filePath);
    routeMap.set(key, existing);
  }

  const conflicts: RouteConflict[] = [];
  for (const [p, files] of routeMap) {
    if (files.length > 1) {
      const [pathOnly] = p.split('::');
      conflicts.push({ path: pathOnly, files });
    }
  }

  return conflicts;
}

function extensionPriority(filePath: string): number {
  const ext = path.extname(filePath);
  const idx = (SUPPORTED_EXTS as readonly string[]).indexOf(ext);
  return idx === -1 ? SUPPORTED_EXTS.length : idx;
}

/**
 * Route priority for sorting. Lower = higher priority.
 *   0 static
 *   1 dynamic (:param)
 *   2 required catch-all (*)
 *   3 optional catch-all (**)
 */
function routePriority(r: RouteNode): number {
  if (r.hasRequiredCatchall) return 2;
  if (r.hasOptionalCatchall) return 3;
  if (r.dynamic) return 1;
  return 0;
}

function deduplicateRoutes(routes: RouteNode[]): RouteNode[] {
  const seen = new Map<string, RouteNode>();

  for (const route of routes) {
    const key = `${route.routePath}::${route.interceptLevel}`;
    const existing = seen.get(key);
    if (!existing) {
      seen.set(key, route);
    } else if (existing.filePath !== route.filePath) {
      if (route.layouts.length > existing.layouts.length) {
        seen.set(key, route);
      } else if (
        route.layouts.length === existing.layouts.length &&
        extensionPriority(route.filePath) < extensionPriority(existing.filePath)
      ) {
        seen.set(key, route);
      }
    }
  }

  return Array.from(seen.values());
}

// ─── Route Preparation ──────────────────────────────────────────────────────

interface PreparedRoutes {
  validRoutes: RouteNode[];
  notFoundBoundaries: NotFoundBoundary[];
}

function prepareRoutes(appDir: string, apiDir: string, strictMode: boolean): PreparedRoutes {
  let routes = scanRoutes(appDir, appDir, apiDir, '', [], 0, null);

  const rootPage = findFile(appDir, PAGE_FILES);
  if (rootPage) {
    routes.unshift({
      routePath: normalizeRoutePath('/'),
      filePath: path.join(appDir, rootPage),
      layouts: resolveLayoutChain(appDir, appDir),
      template: resolveTemplate(appDir, appDir),
      dynamic: false,
      segments: [],
      hasRequiredCatchall: false,
      hasOptionalCatchall: false,
      slotName: null,
      interceptLevel: 'none',
      interceptSourcePath: null,
    });
  }

  const routesFiltered = routes.map(r => ({
    ...r,
    layouts: r.layouts.filter(l => isUsableLayout(l)),
  }));

  let validRoutes = routesFiltered.filter(r => {
    const parsed = readAndParse(r.filePath);
    return parsed ? hasDefaultExport(parsed) : false;
  });

  const conflicts = detectRouteConflicts(validRoutes);
  if (conflicts.length > 0) {
    if (strictMode) {
      throw new RouteConflictError(conflicts);
    } else {
      viteWarnLog(`Route conflicts detected:\n${conflicts.map(c => `  ${c.path}: ${c.files.join(', ')}`).join('\n')}`);
    }
  }

  validRoutes = deduplicateRoutes(validRoutes);

  const notFoundBoundaries = collectNotFoundBoundaries(appDir, appDir, apiDir, '');

  return { validRoutes, notFoundBoundaries };
}

// ─── JSX Render Helpers (App.tsx codegen) ────────────────────────────────────

function renderChain(
  layouts: string[],
  routesInChain: RouteNode[],
  layoutNames: Map<string, string>,
  pageNames: Map<string, string>,
  pageTitles: Map<string, string | null>,
  layoutLoadingNames: Map<string, string>,
  pageLoadingNames: Map<string, string>,
  layoutErrorNames: Map<string, string>,
  pageErrorNames: Map<string, string>,
  templateNames: Map<string, string>,
  guardPathsByRoute: Map<string, string>,
  indent: number,
): string {
  const pad = ' '.repeat(indent);

  if (layouts.length === 0) {
    return routesInChain.map(r => {
      const pageName = pageNames.get(r.filePath);
      if (!pageName) {
        viteWarnLog(`Skipping ${r.routePath}: page name not resolved (transient)`);
        return '';
      }
      const fallback = pageLoadingNames.get(r.filePath) ?? 'Spinner';
      const errorName = pageErrorNames.get(r.filePath);
      const errorProp = errorName ? ` fallback={${errorName}}` : '';

      const title = pageTitles.get(r.filePath) ?? null;
      const titleSetter = `<TitleSetter title={${JSON.stringify(title)}} />`;

      let pageElement = `<${pageName} />`;

      const tplName = r.template ? templateNames.get(r.template) : null;
      if (tplName) {
        pageElement = `<${tplName}>{${pageElement}}</${tplName}>`;
      }

      const element = `<Suspense fallback={<${fallback} />}><ErrorBoundary${errorProp} resetKey={location.pathname}>${titleSetter}${pageElement}</ErrorBoundary></Suspense>`;

      const guardPath = guardPathsByRoute.get(r.filePath);
      if (guardPath) {
        return `${pad}<Route path="${guardPath}" element={<Default404 />} />\n${pad}<Route path="${r.routePath}" element={${element}} />`;
      }

      return `${pad}<Route path="${r.routePath}" element={${element}} />`;
    }).filter(Boolean).join('\n');
  }

  const [head, ...tail] = layouts;
  const name = layoutNames.get(head);

  if (!name) {
    viteWarnLog(`Skipping layout chain rooted at ${head}: layout name not resolved (transient)`);
    return '';
  }

  const fallback = layoutLoadingNames.get(head) ?? 'Spinner';
  const errorName = layoutErrorNames.get(head);
  const errorProp = errorName ? ` fallback={${errorName}}` : '';

  if (tail.length === 0) {
    const inner = routesInChain.map(r => {
      const pageName = pageNames.get(r.filePath);
      if (!pageName) {
        viteWarnLog(`Skipping ${r.routePath}: page name not resolved (transient)`);
        return '';
      }

      const pageFallback = pageLoadingNames.get(r.filePath) ?? 'Spinner';
      const pageErrorName = pageErrorNames.get(r.filePath);
      const pageErrorProp = pageErrorName ? ` fallback={${pageErrorName}}` : '';

      const title = pageTitles.get(r.filePath) ?? null;
      const titleSetter = `<TitleSetter title={${JSON.stringify(title)}} />`;

      let pageElement = `<${pageName} />`;
      const tplName = r.template ? templateNames.get(r.template) : null;
      if (tplName) {
        pageElement = `<${tplName}>{${pageElement}}</${tplName}>`;
      }

      const element = `<Suspense fallback={<${pageFallback} />}><ErrorBoundary${pageErrorProp} resetKey={location.pathname}>${titleSetter}${pageElement}</ErrorBoundary></Suspense>`;

      const guardPath = guardPathsByRoute.get(r.filePath);
      if (guardPath) {
        return `${pad}  <Route path="${guardPath}" element={<Default404 />} />\n${pad}  <Route path="${r.routePath}" element={${element}} />`;
      }

      return `${pad}  <Route path="${r.routePath}" element={${element}} />`;
    }).filter(Boolean).join('\n');

    if (inner.trim() === '') return '';

    const outer = `<WithParams layout={${name}}><Outlet /></WithParams>`;

    return [
      `${pad}<Route element={<Suspense fallback={<${fallback} />}><ErrorBoundary${errorProp} resetKey={location.pathname}>${outer}</ErrorBoundary></Suspense>}>`,
      inner,
      `${pad}</Route>`,
    ].join('\n');
  }

  const inner = renderChain(
    tail, routesInChain, layoutNames, pageNames, pageTitles,
    layoutLoadingNames, pageLoadingNames, layoutErrorNames, pageErrorNames,
    templateNames, guardPathsByRoute, indent + 2,
  );

  if (inner.trim() === '') return '';

  const outer = `<WithParams layout={${name}}><Outlet /></WithParams>`;

  return [
    `${pad}<Route element={<Suspense fallback={<${fallback} />}><ErrorBoundary${errorProp} resetKey={location.pathname}>${outer}</ErrorBoundary></Suspense>}>`,
    inner,
    `${pad}</Route>`,
  ].join('\n');
}

function renderComponentWithLayouts(
  componentName: string,
  layouts: string[],
  layoutNames: Map<string, string>,
  ownFallback: string,
  ownErrorName: string | null,
): string {
  if (layouts.length === 0) {
    const errorProp = ownErrorName ? ` fallback={${ownErrorName}}` : '';
    return `<Suspense fallback={<${ownFallback} />}><ErrorBoundary${errorProp} resetKey={location.pathname}>${componentName}</ErrorBoundary></Suspense>`;
  }

  const [head, ...tail] = layouts;
  const name = layoutNames.get(head);
  const inner = renderComponentWithLayouts(
    componentName, tail, layoutNames,
    ownFallback, ownErrorName,
  );

  if (!name) return inner;

  return `<WithParams layout={${name}}>${inner}</WithParams>`;
}

/**
 * Wrap a slot's routes in a SlotBoundary that renders its fallback when
 * the current URL doesn't match any child. Uses the `default` file when
 * present in the slot's layout chain, otherwise the built-in fallback.
 */
function renderSlot(
  slotName: string,
  routesInSlot: RouteNode[],
  appDir: string,
  ctx: ImportContext,
  slotDefaultFileToName: Map<string, string>,
  lazyImports: string[],
  importedModules: Set<string>,
  layoutNames: Map<string, string>,
  pageNames: Map<string, string>,
  pageTitles: Map<string, string | null>,
  pageLoadingNames: Map<string, string>,
  pageErrorNames: Map<string, string>,
  templateNames: Map<string, string>,
): string {
  const slotDir = routesInSlot[0] ? path.dirname(routesInSlot[0].filePath) : appDir;
  const fallbackName = resolveSlotDefaultComponent(
    slotDir, appDir, ctx, slotDefaultFileToName, lazyImports, importedModules,
  );

  const innerLines: string[] = [];
  for (const r of routesInSlot) {
    const pageName = pageNames.get(r.filePath);
    if (!pageName) continue;

    const fallback = pageLoadingNames.get(r.filePath) ?? 'Spinner';
    const errorName = pageErrorNames.get(r.filePath);
    const errorProp = errorName ? ` fallback={${errorName}}` : '';

    const title = pageTitles.get(r.filePath) ?? null;
    const titleSetter = `<TitleSetter title={${JSON.stringify(title)}} />`;

    let pageElement = `<${pageName} />`;
    const tplName = r.template ? templateNames.get(r.template) : null;
    if (tplName) {
      pageElement = `<${tplName}>{${pageElement}}</${tplName}>`;
    }

    const element = `<Suspense fallback={<${fallback} />}><ErrorBoundary${errorProp} resetKey={location.pathname}>${titleSetter}${pageElement}</ErrorBoundary></Suspense>`;
    innerLines.push(`        <Route path="${r.routePath}" element={${element}} />`);
  }

  if (innerLines.length === 0) return '';

  return `        <Route path="*" element={<SlotBoundary slot="${slotName}" fallback={<${fallbackName} />}><Routes>${innerLines.join('')}</Routes></SlotBoundary>} />`;
}

