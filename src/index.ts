function scanApiRoutesWithGlob(root: string): ApiRoute[] {
  const files = globSync('src/app/api/**/*.{ts,js}', {
    cwd: root,
    ignore: ['**/node_modules/**', '**/_*/**'],
  });
  const routes: ApiRoute[] = [];
  for (const rel of files) {
    const full = path.join(root, rel);
    const dir = path.dirname(full);
    const ext = path.extname(full);
    const base = path.basename(full, ext);
    if (!(API_EXTS as readonly string[]).includes(ext)) continue;
    if (base.startsWith('_') || base.startsWith('.')) continue;

    let routePath: string;
    const relDir = path.relative(path.join(root, API_DIR), dir).replace(/\\/g, '/');
    const segments = relDir ? relDir.split('/') : [];

    const isRouteFile = base === 'route';
    const isIndexFile = base === 'index';
    const isBareRoute = !isRouteFile && !isIndexFile;

    const isOptionalCatchAll = isBareRoute && base.startsWith('[[...') && base.endsWith(']]');
    const isCatchAll = isBareRoute && !isOptionalCatchAll && base.startsWith('[...') && base.endsWith(']');
    const isDynamic = isBareRoute && !isCatchAll && !isOptionalCatchAll && base.startsWith('[') && base.endsWith(']');

    let catchallParamName: string | undefined;
    let rawPath = '';

    for (const seg of segments) {
      const isGroup = isRouteGroup(seg);
      const isOptCatch = seg.startsWith('[[...') && seg.endsWith(']]');
      const isCatch = !isOptCatch && seg.startsWith('[...') && seg.endsWith(']');
      const isDyn = !isCatch && !isOptCatch && seg.startsWith('[') && seg.endsWith(']');

      if (isGroup) continue;
      if (isOptCatch) { const name = seg.slice(5, -2); catchallParamName = name; rawPath += '/**'; }
      else if (isCatch) { const name = seg.slice(4, -1); catchallParamName = name; rawPath += '/*'; }
      else if (isDyn) { const name = seg.slice(1, -1); rawPath += `/:${name}`; }
      else rawPath += `/${seg}`;
    }

    if (isRouteFile || isIndexFile) routePath = normalizeRoutePath(rawPath || '/');
    else if (isOptionalCatchAll) { const name = base.slice(5, -2); catchallParamName = name; routePath = normalizeRoutePath(`${rawPath}/**`); }
    else if (isCatchAll) { const name = base.slice(4, -1); catchallParamName = name; routePath = normalizeRoutePath(`${rawPath}/*`); }
    else if (isDynamic) { const name = base.slice(1, -1); routePath = normalizeRoutePath(`${rawPath}/:${name}`); }
    else routePath = normalizeRoutePath(`${rawPath}/${base}`);

    routes.push({ routePath, filePath: full, catchallParamName });
  }

  routes.sort((a, b) => {
    const aCatch = a.routePath.includes('*') ? 1 : 0;
    const bCatch = b.routePath.includes('*') ? 1 : 0;
    if (aCatch !== bCatch) return aCatch - bCatch;
    const aDyn = a.routePath.includes(':') ? 1 : 0;
    const bDyn = b.routePath.includes(':') ? 1 : 0;
    if (aDyn !== bDyn) return aDyn - bDyn;
    return b.routePath.length - a.routePath.length;
  });

  return routes;
}

function scanApiRoutes(dir: string, _baseRoute = '', _depth = 0): ApiRoute[] {
  const root = path.resolve(dir, '../../..');
  return scanApiRoutesWithGlob(root);
}

