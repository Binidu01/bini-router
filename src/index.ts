type DiagCode = keyof typeof DIAG_CODES;
export type Severity = 'error' | 'warn';

export function report(
  severity: Severity,
  code: DiagCode,
  file?: string,
  detail?: string,
  st: RouterState = S,
): void {
  const message = detail ?? DIAG_CODES[code];
  const key = `${code}|${norm(file ?? '')}|${message}`;
  if (st.warned.has(key)) return;
  st.warned.add(key);

  const located = file ? locateInFile(file, detail) : null;
  const err = makeViteError(code, message, {
    file,
    line: located?.line,
    column: located?.column,
    frame: located?.frame,
  });

  if (severity === 'error') {
    if (st.isBuild) {
      st.errors.push(err);
      return;
    }
    (st.logger as unknown as ViteLoggerWithError | null)?.error(message, { timestamp: true, error: err });
    return;
  }
  st.logger?.warn(message, { timestamp: true });
}

function flushErrors(): void {
  if (S.errors.length === 0) return;
  const errors = S.errors.splice(0);
  const message = errors.length === 1
    ? errors[0].message
    : `${errors.length} errors\n${errors.map(e => `  ${e.message}`).join('\n')}`;
  const err = makeViteError('BINI_AGGREGATE', message, { meta: { errors } });
  throw err;
}

