function collectPatternNames(node: any, out: Set<string>): void {
  if (!node) return;
  switch (node.type) {
    case 'Identifier': out.add(node.name); break;
    case 'ObjectPattern': for (const prop of node.properties ?? []) { if (prop.type === 'RestElement') collectPatternNames(prop.argument, out); else collectPatternNames(prop.value, out); } break;
    case 'ArrayPattern': for (const el of node.elements ?? []) collectPatternNames(el, out); break;
    case 'AssignmentPattern': collectPatternNames(node.left, out); break;
    case 'RestElement': collectPatternNames(node.argument, out); break;
  }
}

