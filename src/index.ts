/**
 * Statically evaluate an expression to a plain value.
 *
 * `program` is optional, but when supplied it lets us resolve top-level
 * `const X = <expr>` bindings so `JSON.stringify(jsonLd)` works inside the
 * `document.head` tree. Without it, only literal-shaped expressions resolve.
 */
function nodeToValue(node: any, program?: any): unknown {
  if (!node || typeof node !== 'object') return undefined;
  switch (node.type) {
    case 'Identifier': {
      if (!program) return undefined;
      for (const stmt of program.body ?? []) {
        const decl = stmt.type === 'ExportNamedDeclaration' || stmt.type === 'ExportDefaultDeclaration'
          ? stmt.declaration
          : stmt.type === 'VariableDeclaration' ? stmt : null;
        if (!decl || decl.type !== 'VariableDeclaration') continue;
        for (const d of decl.declarations ?? []) {
          if (d.id?.type !== 'Identifier' || d.id.name !== node.name) continue;
          return nodeToValue(d.init, program);
        }
      }
      return undefined;
    }
    case 'Literal': return node.value;
    case 'TemplateLiteral': {
      const quasis = node.quasis ?? [];
      const exprs = node.expressions ?? [];
      if (exprs.length === 0) {
        return quasis.map((q: any) => q.value?.cooked ?? q.value?.raw ?? '').join('');
      }
      const parts: string[] = [];
      for (let i = 0; i < quasis.length; i++) {
        parts.push(quasis[i].value?.cooked ?? quasis[i].value?.raw ?? '');
        if (i < exprs.length) {
          const v = nodeToValue(exprs[i], program);
          if (v === undefined) return undefined;
          parts.push(String(v));
        }
      }
      return parts.join('');
    }
    case 'ArrayExpression': {
      const out: unknown[] = [];
      for (const el of node.elements ?? []) {
        if (!el) continue;
        if (el.type === 'SpreadElement') return undefined;
        const v = nodeToValue(el, program);
        if (v === undefined) return undefined;
        out.push(v);
      }
      return out;
    }
    case 'ObjectExpression': {
      const obj: Record<string, unknown> = {};
      for (const prop of node.properties ?? []) {
        if (prop.type !== 'Property') return undefined;
        if (prop.computed) return undefined;
        const key = prop.key?.type === 'Identifier' ? prop.key.name
          : prop.key?.type === 'Literal' ? String(prop.key.value) : undefined;
        if (key === undefined) return undefined;
        if (key === '__proto__' || key === 'constructor' || key === 'prototype') return undefined;
        const v = nodeToValue(prop.value, program);
        if (v === undefined) return undefined;
        obj[key] = v;
      }
      return obj;
    }
    case 'TSAsExpression': case 'TSSatisfiesExpression': case 'TSTypeAssertion':
    case 'TSNonNullExpression': case 'ParenthesizedExpression':
      return nodeToValue(node.expression, program);
    // JSON.stringify(<static value>) → serialized JSON string. Used by
    // document.head for JSON-LD script bodies.
    case 'CallExpression': {
      const callee = unwrapExpression(node.callee);
      if (
        callee?.type === 'MemberExpression' &&
        !callee.computed &&
        callee.object?.type === 'Identifier' &&
        callee.object.name === 'JSON' &&
        callee.property?.name === 'stringify' &&
        Array.isArray(node.arguments) &&
        node.arguments.length >= 1
      ) {
        const value = nodeToValue(node.arguments[0], program);
        if (value !== undefined) return JSON.stringify(value);
      }
      return undefined;
    }
    default: return undefined;
  }
}

function getNamedExportObject(parsed: ParsedFile, name: string): Record<string, unknown> | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (decl && decl.type === 'VariableDeclaration') {
      for (const d of decl.declarations ?? []) {
        if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
        const value = nodeToValue(d.init, parsed.program);
        if (value && typeof value === 'object' && !Array.isArray(value)) return value as Record<string, unknown>;
        return null;
      }
    }
    if (Array.isArray(stmt.specifiers)) {
      for (const spec of stmt.specifiers) {
        if (spec.exported?.name !== name) continue;
        const local = spec.local?.name;
        if (!local) continue;
        const resolved = findLocalBindingObject(parsed, local);
        if (resolved) return resolved;
      }
    }
  }
  return null;
}

