function matchRouteForEntry(
  manifest: RouteManifest,
  pattern: string,
  pathname: string,
): Record<string, string> | null {
  const entry = manifest.metadata[pattern];
  const opts = {
    enforceNonEmptyCatchAll: entry?.catchallKind === 'required',
    catchallParamName: entry?.catchallParamName,
  };
  return matchRoute(pattern, pathname, opts);
}

export function getMetadataForRoute(
  manifest: RouteManifest,
  pathname: string,
): RouteManifestEntry | null {
  const exact = manifest.metadata[pathname];
  if (exact) return exact;

  for (const pattern of manifest.dynamic) {
    if (matchRouteForEntry(manifest, pattern, pathname)) {
      const entry = manifest.metadata[pattern];
      if (entry) return entry;
    }
  }

  return null;
}

export function getCssForRoute(
  manifest: RouteManifest,
  pathname: string,
): string[] | null {
  const entry = getMetadataForRoute(manifest, pathname);
  return entry?.css ?? null;
}

export function matchRoute(
  pattern: string,
  pathname: string,
  options: {
    enforceNonEmptyCatchAll?: boolean;
    catchallParamName?: string;
  } = {},
): Record<string, string> | null {
  const { enforceNonEmptyCatchAll = false, catchallParamName } = options;

  const patParts = pattern.split('/').filter(Boolean);
  const urlParts = pathname.split('/').filter(Boolean);

  const lastPat = patParts[patParts.length - 1];
  const isOptionalCatchAll = lastPat === '**';
  const isRequiredCatchAll = lastPat === '*';

  if (isOptionalCatchAll || isRequiredCatchAll) {
    const prefix = patParts.slice(0, -1);
    if (urlParts.length < prefix.length) return null;

    if (
      isRequiredCatchAll &&
      enforceNonEmptyCatchAll &&
      urlParts.length === prefix.length
    ) {
      return null;
    }

    const params: Record<string, string> = {};
    for (let i = 0; i < prefix.length; i++) {
      if (prefix[i].startsWith(':')) {
        let value: string;
        try {
          value = decodeURIComponent(urlParts[i]);
        } catch {
          return null;
        }
        if (
          value.includes('/') ||
          value.includes('\\') ||
          value.includes('..') ||
          value.includes('\0')
        ) return null;
        params[prefix[i].slice(1)] = value;
      } else if (prefix[i] !== urlParts[i]) {
        return null;
      }
    }

    const rawTail = urlParts.slice(prefix.length);
    const decodedTail: string[] = [];
    for (const seg of rawTail) {
      let decoded: string;
      try {
        decoded = decodeURIComponent(seg);
      } catch {
        return null;
      }
      if (
        decoded === '.' ||
        decoded === '..' ||
        decoded.includes('/') ||
        decoded.includes('\\') ||
        decoded.includes('\0')
      ) {
        return null;
      }
      decodedTail.push(decoded);
    }

    const tail = decodedTail.join('/');
    params['*'] = tail;
    if (catchallParamName) {
      params[catchallParamName] = tail;
    }
    return params;
  }

  if (patParts.length !== urlParts.length) return null;

  const params: Record<string, string> = {};
  for (let i = 0; i < patParts.length; i++) {
    if (patParts[i].startsWith(':')) {
      let value: string;
      try {
        value = decodeURIComponent(urlParts[i]);
      } catch {
        return null;
      }
      if (
        value.includes('/') ||
        value.includes('\\') ||
        value.includes('..') ||
        value.includes('\0')
      ) return null;
      params[patParts[i].slice(1)] = value;
    } else if (patParts[i] !== urlParts[i]) {
      return null;
    }
  }
  return params;
}

export function matchManifestRoute(
  manifest: RouteManifest,
  pathname: string,
): RouteMatchResult {
  const exact = manifest.metadata[pathname];
  if (exact) {
    return {
      type: exact.dynamic ? 'dynamic' : 'static',
      routePath: pathname,
    };
  }

  for (const pattern of manifest.dynamic) {
    const params = matchRouteForEntry(manifest, pattern, pathname);
    if (params) {
      return {
        type: 'dynamic',
        routePath: pattern,
        params,
      };
    }
  }

  return { type: 'not_found' };
}

