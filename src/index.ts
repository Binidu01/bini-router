type ViteShapedError = RolldownError & { pluginCode: string };

function makeViteError(code: string, message: string, extra: ViteErrorExtra = {}): ViteShapedError {
  const err = new Error(message) as ViteShapedError;
  err.plugin = PLUGIN_NAME;
  err.pluginCode = code;
  if (extra.file) {
    err.id = extra.file;
    err.loc = {
      file: extra.file,
      line: extra.line ?? 1,
      column: extra.column ?? 1,
    };
  }
  if (extra.frame) err.frame = extra.frame;
  if (extra.cause) (err as any).cause = extra.cause;
  if (extra.meta) (err as any).meta = extra.meta;
  return err;
}

function makeCodeFrame(source: string, line: number, column: number): string {
  const lines = source.split('\n');
  const start = Math.max(0, line - 3);
  const end = Math.min(lines.length, line + 2);
  const width = String(end).length;
  const out: string[] = [];
  for (let i = start; i < end; i++) {
    const n = i + 1;
    const marker = n === line ? '>' : ' ';
    out.push(`${marker} ${String(n).padStart(width)} | ${lines[i]}`);
    if (n === line && column > 0) {
      out.push(`  ${' '.repeat(width)} | ${' '.repeat(column - 1)}^`);
    }
  }
  return out.join('\n');
}

function locateInFile(file: string, needle?: string): { line: number; column: number; frame: string } | null {
  try {
    const src = fs.readFileSync(file, 'utf8');
    if (!needle) {
      return { line: 1, column: 1, frame: makeCodeFrame(src, 1, 1) };
    }
    const idx = src.indexOf(needle);
    if (idx < 0) return { line: 1, column: 1, frame: makeCodeFrame(src, 1, 1) };
    const before = src.slice(0, idx);
    const line = before.split('\n').length;
    const column = idx - before.lastIndexOf('\n');
    return { line, column, frame: makeCodeFrame(src, line, column) };
  } catch {
    return null;
  }
}

