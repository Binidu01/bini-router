interface CachedModule { mtime: number; size: number; handler: any; error?: Error }
type ApiHandlerFn = (req: Request, ctx: { params: Record<string, string>; searchParams: URLSearchParams }) => Response | Promise<Response>;
interface LoadedApiModule { methods: Partial<Record<ApiMethod, ApiHandlerFn>>; defaultExport: unknown; allowed: ApiMethod[] }

function rememberModule(cache: Map<string, CachedModule>, key: string, entry: CachedModule): void {
  if (cache.size >= MODULE_CACHE_MAX && !cache.has(key)) { const oldest = cache.keys().next().value; if (oldest !== undefined) cache.delete(oldest); }
  cache.set(key, entry);
}

async function importHandler(server: ViteDevServer | null, filePath: string, moduleCache: Map<string, CachedModule>): Promise<LoadedApiModule | null> {
  let mod: any;
  if (server) mod = await server.ssrLoadModule(filePath);
  else {
    let stats: fs.Stats;
    try { stats = fs.statSync(filePath); if (stats.size > MAX_FILE_SIZE) return null; } catch { return null; }
    const cacheKey = filePath;
    const cached = moduleCache.get(cacheKey);
    if (cached && cached.mtime === stats.mtimeMs && cached.size === stats.size) { if (cached.error) throw cached.error; mod = cached.handler; }
    else {
      try {
        const { pathToFileURL } = await import('url');
        const url = pathToFileURL(filePath).href + '?v=' + stats.mtimeMs;
        mod = await import(url);
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: mod });
      } catch (error) {
        const err = error instanceof Error ? error : new Error(String(error));
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: null, error: err });
        throw err;
      }
    }
  }
  if (!mod || typeof mod !== 'object') return null;
  const methods: Partial<Record<ApiMethod, ApiHandlerFn>> = {};
  const allowed: ApiMethod[] = [];
  for (const m of API_METHODS) { const fn = mod[m]; if (typeof fn === 'function') { methods[m] = fn as ApiHandlerFn; allowed.push(m); } }
  return { methods, defaultExport: mod.default ?? null, allowed };
}

function rou3Path(routePath: string): string {
  if (routePath.endsWith('/**')) return routePath;
  if (routePath.endsWith('/*')) return routePath.slice(0, -1) + '**';
  return routePath;
}

interface ApiContext {
  st: RouterState;
  apiDir: string;
  cors: CorsOption;
  trustProxy: boolean;
  allowedHosts: string[] | true | undefined;
  getRouter: () => ReturnType<typeof createRouter> | null;
  setRouter: (v: ReturnType<typeof createRouter>) => void;
  moduleCache: Map<string, CachedModule>;
  server: ViteDevServer | null;
}

function sendJson(res: any, status: number, body: unknown, extraHeaders: Record<string, string> = {}): void {
  res.statusCode = status;
  res.setHeader('Content-Type', 'application/json');
  for (const [k, v] of Object.entries(extraHeaders)) res.setHeader(k, v);
  res.end(JSON.stringify(body));
}

async function handleApiRequest(req: any, res: any, ctx: ApiContext): Promise<void> {
  const { st, apiDir, getRouter, setRouter, moduleCache, server } = ctx;
  res.on('error', () => {});
  try {
    let router = getRouter();
    if (!router) {
      const rawRoutes = withState(st, () => scanApiRoutes(apiDir, ''));
      router = createRouter();
      for (const route of rawRoutes) {
        for (const method of route.allowedMethods ?? API_METHODS) {
          addRoute(router, method, rou3Path(route.routePath), { filePath: route.filePath, catchallParamName: route.catchallParamName });
        }
      }
      setRouter(router);
    }

    const strippedUrl = req.url ?? '/';
    const urlForRequest = new URL(`http://localhost${strippedUrl}`);
    const pathname = urlForRequest.pathname;
    const method = req.method ?? 'GET';
    const searchParams = urlForRequest.searchParams;

    const match = findRoute(router, method, pathname);
    if (!match) {
      sendJson(res, 404, { error: 'Not Found', message: `No API handler matched ${req.url}` });
      return;
    }

    const data = match.data as { filePath: string; catchallParamName?: string };
    const params: Record<string, string> = { ...(match.params ?? {}) };
    if (data.catchallParamName && params['*'] !== undefined) {
      params[data.catchallParamName] = params['*'];
    }

    let loaded: LoadedApiModule | null;
    try {
      loaded = await importHandler(server, data.filePath, moduleCache);
    } catch (error) {
      viteErrorLog(`Failed to load API handler: ${error instanceof Error ? error.message : String(error)}`, st, error, data.filePath);
      sendJson(res, 500, { error: 'Internal Server Error' });
      return;
    }
    if (!loaded) { sendJson(res, 404, { error: 'Not Found' }); return; }

    const { methods: methodHandlers, defaultExport, allowed } = loaded;

    if (allowed.length > 0) {
      const handlerFn = methodHandlers[method as ApiMethod] ?? (method === 'HEAD' ? methodHandlers.GET : undefined);
      if (!handlerFn) {
        const allow = [...allowed];
        if (methodHandlers.GET && !methodHandlers.HEAD) allow.push('HEAD');
        sendJson(res, 405, { error: 'Method Not Allowed', allow }, { Allow: allow.join(', ') });
        return;
      }
      const webReq = new Request(`http://localhost${req.url}`, { method, headers: req.headers as any });
      let webRes: Response;
      try { webRes = await handlerFn(webReq, { params, searchParams }); }
      catch (error) { viteErrorLog(`Error in ${method} handler: ${error instanceof Error ? error.message : String(error)}`, st, error, data.filePath); if (!res.headersSent) sendJson(res, 500, { error: 'Internal Server Error' }); return; }
      await sendWebResponse(res, webRes, method);
      return;
    }

    if (!defaultExport) { sendJson(res, 404, { error: 'Not Found' }); return; }

    const webReq = new Request(`http://localhost${req.url}`, { method, headers: req.headers as any });
    let webRes: Response;
    try {
      if (typeof (defaultExport as any).fetch === 'function') webRes = await (defaultExport as any).fetch(webReq);
      else if (typeof defaultExport === 'function') webRes = await (defaultExport as ApiHandlerFn)(webReq, { params, searchParams });
      else { sendJson(res, 404, { error: 'Not Found' }); return; }
    } catch (error) {
      viteErrorLog(`Error in default handler: ${error instanceof Error ? error.message : String(error)}`, st, error, data.filePath);
      if (!res.headersSent) sendJson(res, 500, { error: 'Internal Server Error' });
      return;
    }
    await sendWebResponse(res, webRes, method);
  } catch (error) {
    viteErrorLog(`API request error: ${error instanceof Error ? error.message : String(error)}`, st, error);
    if (!res.headersSent) sendJson(res, 500, { error: 'Internal Server Error' });
  }
}

async function sendWebResponse(res: any, webRes: Response, method: string): Promise<void> {
  if (method === 'HEAD' || !webRes.body) { res.end(); return; }
  res.statusCode = webRes.status;
  const setCookie = typeof (webRes.headers as any).getSetCookie === 'function' ? (webRes.headers as any).getSetCookie() : [];
  if (setCookie.length > 0) res.setHeader('Set-Cookie', setCookie);
  webRes.headers.forEach((value, key) => { if (key.toLowerCase() === 'set-cookie') return; res.setHeader(key, value); });
  const reader = webRes.body.getReader();
  res.on('close', () => { reader.cancel().catch(() => {}); });
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value || value.byteLength === 0) continue;
      const chunk = Buffer.isBuffer(value) ? value : Buffer.from(value);
      if (!res.write(chunk)) {
        await new Promise<void>((resolve, reject) => {
          const onDrain = () => { res.off('error', onError); resolve(); };
          const onError = (err: Error) => { res.off('drain', onDrain); reject(err); };
          res.once('drain', onDrain);
          res.once('error', onError);
        });
      }
    }
    res.end();
  } catch (err) {
    if (!res.writableEnded) res.destroy(err as Error);
    else res.end();
  }
}

