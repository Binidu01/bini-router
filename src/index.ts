interface RenderCtx {
  layoutNames: Map<string, string>; pageNames: Map<string, string>;
  layoutLoadingNames: Map<string, string>; pageLoadingNames: Map<string, string>;
  layoutErrorNames: Map<string, string>; pageErrorNames: Map<string, string>;
  templateNames: Map<string, string>; layoutSlotExprs: Map<string, string>;
  guardPathsByRoute: Map<string, string>; layoutExtras: Map<string, string>; pageExtras: Map<string, string>;
  interceptsByTarget: Map<string, RouteNode[]>; orphanTargets: Set<string>; rootNotFoundEl: string;
}

function renderPageElement(r: RouteNode, rc: RenderCtx): string | null {
  const pageName = rc.pageNames.get(r.filePath);
  if (!pageName) return null;
  const fallback = rc.pageLoadingNames.get(r.filePath) ?? 'Spinner';
  const errorName = rc.pageErrorNames.get(r.filePath);
  const errorProp = errorName ? ` FallbackComponent={${errorName}}` : ' FallbackComponent={DefaultError}';
  let pageElement = `<${pageName} />`;
  const tplName = r.template ? rc.templateNames.get(r.template) : null;
  if (tplName) pageElement = `<${tplName}>{${pageElement}}</${tplName}>`;
  return `<Suspense fallback={<${fallback} />}><PathBoundary${errorProp}>${pageElement}</PathBoundary></Suspense>`;
}

function renderPageRoute(r: RouteNode, rc: RenderCtx, pad: string): string {
  let element = renderPageElement(r, rc);
  if (element === null) return '';
  const gateNodes = rc.interceptsByTarget.get(r.routePath);
  if (gateNodes) {
    const entries: string[] = [];
    for (const n of gateNodes) {
      const el = renderPageElement(n, rc);
      if (el && n.interceptSourcePath) entries.push(`{ from: ${JSON.stringify(n.interceptSourcePath)}, element: ${el} }`);
    }
    if (entries.length > 0) {
      const real = rc.orphanTargets.has(r.routePath) ? rc.rootNotFoundEl : element;
      element = `<InterceptGate entries={[${entries.join(', ')}]}>${real}</InterceptGate>`;
    }
  }
  const extras = rc.pageExtras.get(r.filePath) ?? '';
  const line = `${pad}<Route path="${r.routePath}"${extras} element={${element}} />`;
  const guardPath = rc.guardPathsByRoute.get(r.filePath);
  if (guardPath) return `${pad}<Route path="${guardPath}" element={${rc.rootNotFoundEl}} />\n${line}`;
  return line;
}

function renderChain(layouts: string[], routesInChain: RouteNode[], rc: RenderCtx, indent: number): string {
  const pad = ' '.repeat(indent);
  if (layouts.length === 0) return routesInChain.map(r => renderPageRoute(r, rc, pad)).filter(Boolean).join('\n');
  const [head, ...tail] = layouts;
  const name = rc.layoutNames.get(head);
  if (!name) return '';
  const fallback = rc.layoutLoadingNames.get(head) ?? 'Spinner';
  const errorName = rc.layoutErrorNames.get(head);
  const errorProp = errorName ? ` FallbackComponent={${errorName}}` : ' FallbackComponent={DefaultError}';
  const slotExpr = rc.layoutSlotExprs.get(path.resolve(head));
  const slotsAttr = slotExpr ? ` slots=${slotExpr}` : '';
  const inner = tail.length === 0
    ? routesInChain.map(r => renderPageRoute(r, rc, pad + '  ')).filter(Boolean).join('\n')
    : renderChain(tail, routesInChain, rc, indent + 2);
  if (inner.trim() === '') return '';
  const outer = `<WithParams layout={${name}}${slotsAttr}><Outlet /></WithParams>`;
  const extras = rc.layoutExtras.get(head) ?? '';
  return [
    `${pad}<Route${extras} element={<Suspense fallback={<${fallback} />}><PathBoundary${errorProp}>${outer}</PathBoundary></Suspense>}>`,
    inner,
    `${pad}</Route>`,
  ].join('\n');
}

function renderComponentWithLayouts(componentName: string, layouts: string[], layoutNames: Map<string, string>, ownFallback: string, ownErrorName: string | null): string {
  if (layouts.length === 0) {
    const errorProp = ownErrorName ? ` FallbackComponent={${ownErrorName}}` : ' FallbackComponent={DefaultError}';
    return `<Suspense fallback={<${ownFallback} />}><PathBoundary${errorProp}>${componentName}</PathBoundary></Suspense>`;
  }
  const [head, ...tail] = layouts;
  const name = layoutNames.get(head);
  const inner = renderComponentWithLayouts(componentName, tail, layoutNames, ownFallback, ownErrorName);
  if (!name) return inner;
  return `<WithParams layout={${name}}>${inner}</WithParams>`;
}

function renderSlotsProp(
  slotMap: Map<string, RouteNode[]>, ctx: ImportContext, slotDefaultFileToName: Map<string, string>,
  lazyImports: string[], importedModules: Set<string>, layoutNames: Map<string, string>,
  pageNames: Map<string, string>, pageLoadingNames: Map<string, string>, pageErrorNames: Map<string, string>,
  templateNames: Map<string, string>,
): string {
  const props: string[] = [];
  for (const [slotName, routesInSlot] of slotMap) {
    const ownerDir = routesInSlot[0]?.slotOwnerDir;
    if (!ownerDir) continue;
    const slotRoot = path.join(ownerDir, '@' + slotName);
    const fallbackName = resolveSlotDefaultComponent(slotRoot, ctx, slotDefaultFileToName, lazyImports, importedModules);
    const entries: string[] = [];
    for (const r of routesInSlot) {
      const pageName = pageNames.get(r.filePath);
      if (!pageName) continue;
      const pageFallback = pageLoadingNames.get(r.filePath) ?? 'Spinner';
      const errorName = pageErrorNames.get(r.filePath);
      const errorProp = errorName ? ` FallbackComponent={${errorName}}` : ' FallbackComponent={DefaultError}';
      let pageElement = `<${pageName} params={params} />`;
      const tplName = r.template ? templateNames.get(r.template) : null;
      if (tplName) pageElement = `<${tplName}>${pageElement}</${tplName}>`;
      for (let i = r.layouts.length - 1; i >= 0; i--) {
        const ln = layoutNames.get(r.layouts[i]);
        if (ln) pageElement = `<WithParams layout={${ln}}>${pageElement}</WithParams>`;
      }
      const element = `<Suspense fallback={<${pageFallback} />}><PathBoundary${errorProp}>${pageElement}</PathBoundary></Suspense>`;
      const from = r.interceptLevel !== 'none' && r.interceptSourcePath ? JSON.stringify(r.interceptSourcePath) : 'null';
      entries.push(`{ path: ${JSON.stringify(r.routePath)}, from: ${from}, render: (params) => (${element}) }`);
    }
    if (entries.length === 0) continue;
    props.push(`${JSON.stringify(slotName)}: <SlotOutlet slot=${JSON.stringify(slotName)} fallback={<${fallbackName} />} entries={[${entries.join(', ')}]} />`);
  }
  return props.length > 0 ? `{{ ${props.join(', ')} }}` : '';
}

function generateWithParams(ts: boolean): string {
  return ts ? `
function WithParams({ layout: Layout, slots, children }: { layout: React.ComponentType<any>; slots?: Record<string, React.ReactNode>; children: React.ReactNode }) {
  const params = useParams();
  return <Layout params={params} {...(slots || {})}>{children}</Layout>;
}` : `
function WithParams({ layout: Layout, slots, children }) {
  const params = useParams();
  return <Layout params={params} {...(slots || {})}>{children}</Layout>;
}`;
}

const SLOT_OUTLET_COMPONENT = `
function SlotOutlet({ slot, entries, fallback }) {
  const { pathname } = useLocation();
  for (const entry of entries) {
    const m = matchPath({ path: entry.path, end: true }, pathname);
    if (!m) continue;
    if (entry.from) {
      const prev = navState.prev;
      if (prev === null || !matchPath({ path: entry.from, end: true }, prev)) continue;
    }
    return <React.Fragment key={slot + ':' + entry.path}>{entry.render(m.params)}</React.Fragment>;
  }
  return <Suspense fallback={null}>{fallback}</Suspense>;
}`;

