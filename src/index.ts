const OXC_LANG_BY_EXT: Record<string, 'js' | 'jsx' | 'ts' | 'tsx'> = {
  '.js': 'js',
  '.jsx': 'jsx',
  '.ts': 'ts',
  '.tsx': 'tsx',
  '.mdx': 'tsx',
  '.md': 'tsx',
};

interface ParsedFile {
  program: any;
  comments: any[];
}

function isFatalError(err: any): boolean {
  if (!err || typeof err !== 'object') return true;
  if ('severity' in err && err.severity !== undefined) {
    const sev = String(err.severity).toLowerCase();
    return sev === 'error' || sev === '1';
  }
  return true;
}

function parseFile(source: string, filePath: string): ParsedFile | null {
  const ext = path.extname(filePath);
  const lang = OXC_LANG_BY_EXT[ext] ?? 'tsx';
  try {
    const result = parseSync(filePath, source, {
      lang,
      sourceType: 'module',
    });
    if (!result) return null;

    const errors = (result.errors ?? []).filter(isFatalError);
    if (errors.length > 0) {
      let mtimeMs = 0;
      try { mtimeMs = fs.statSync(filePath).mtimeMs; } catch {}
      warnOnce(
        filePath,
        mtimeMs,
        `Oxc parse errors in ${filePath}: ${errors
          .slice(0, 3)
          .map((e: any) => e.message ?? String(e))
          .join('; ')}`
      );
      return null;
    }
    if (!result.program) return null;
    return {
      program: result.program,
      comments: result.comments ?? [],
    };
  } catch (error) {
    let mtimeMs = 0;
    try { mtimeMs = fs.statSync(filePath).mtimeMs; } catch {}
    warnOnce(
      filePath,
      mtimeMs,
      `Oxc parse failed for ${filePath}: ${error instanceof Error ? error.message : String(error)}`
    );
    return null;
  }
}

function walk(node: any, visit: (n: any) => boolean | void): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const child of node) walk(child, visit);
    return;
  }
  if (typeof node.type === 'string') {
    const result = visit(node);
    if (result === false) return;
  }
  for (const key of Object.keys(node)) {
    if (key === 'type' || key === 'start' || key === 'end' || key === 'loc' || key === 'range') continue;
    const value = node[key];
    if (value && typeof value === 'object') walk(value, visit);
  }
}

function nodeToValue(node: any): unknown {
  if (!node || typeof node !== 'object') return undefined;
  switch (node.type) {
    case 'Literal':
      return node.value;
    case 'TemplateLiteral': {
      if (node.expressions && node.expressions.length > 0) return undefined;
      return (node.quasis ?? []).map((q: any) => q.value?.cooked ?? q.value?.raw ?? '').join('');
    }
    case 'ArrayExpression':
      return (node.elements ?? [])
        .map((el: any) => (el && el.type !== 'SpreadElement' ? nodeToValue(el) : undefined))
        .filter((v: unknown) => v !== undefined);
    case 'ObjectExpression': {
      const obj: Record<string, unknown> = {};
      for (const prop of node.properties ?? []) {
        if (prop.type !== 'Property') continue;
        if (prop.computed) continue;
        const key = prop.key?.type === 'Identifier'
          ? prop.key.name
          : prop.key?.type === 'Literal'
            ? String(prop.key.value)
            : undefined;
        if (key === undefined) continue;
        obj[key] = nodeToValue(prop.value);
      }
      return obj;
    }
    case 'TSAsExpression':
    case 'TSSatisfiesExpression':
    case 'TSTypeAssertion':
    case 'TSNonNullExpression':
      return nodeToValue(node.expression);
    case 'ParenthesizedExpression':
      return nodeToValue(node.expression);
    default:
      return undefined;
  }
}

function getNamedExportObject(parsed: ParsedFile, name: string): Record<string, unknown> | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;
    for (const d of decl.declarations ?? []) {
      if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
      const value = nodeToValue(d.init);
      if (value && typeof value === 'object' && !Array.isArray(value)) {
        return value as Record<string, unknown>;
      }
      return null;
    }
  }
  return null;
}

function getExportRange(parsed: ParsedFile, name: string): { start: number; end: number } | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;
    for (const d of decl.declarations ?? []) {
      if (d.id?.type === 'Identifier' && d.id.name === name) {
        return { start: stmt.start, end: stmt.end };
      }
    }
  }
  return null;
}

function getJsxPropertySource(
  parsed: ParsedFile,
  name: string,
  propertyName: string,
): string | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;

    for (const d of decl.declarations ?? []) {
      if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
      if (!d.init || d.init.type !== 'ObjectExpression') return null;

      for (const prop of d.init.properties ?? []) {
        if (prop.type !== 'Property') continue;
        if (prop.computed) continue;

        const key = prop.key?.type === 'Identifier'
          ? prop.key.name
          : prop.key?.type === 'Literal'
            ? String(prop.key.value)
            : undefined;

        if (key !== propertyName) continue;

        return jsxNodeToHtml(unwrapExpression(prop.value));
      }
      return null;
    }
  }
  return null;
}

function unwrapExpression(node: any): any {
  if (!node) return node;
  switch (node.type) {
    case 'ParenthesizedExpression':
    case 'TSAsExpression':
    case 'TSSatisfiesExpression':
    case 'TSTypeAssertion':
    case 'TSNonNullExpression':
      return unwrapExpression(node.expression);
    default:
      return node;
  }
}

function jsxNodeToHtml(node: any): string | null {
  if (!node) return null;

  switch (node.type) {
    case 'JSXFragment': {
      return (node.children ?? [])
        .map((c: any) => jsxNodeToHtml(c))
        .filter((s: string | null): s is string => s !== null)
        .filter((s: string) => s.trim() !== '')
        .join('\n');
    }
    case 'JSXElement': {
      const opening = node.openingElement;
      const closing = node.closingElement;
      const tag = opening?.name?.name;
      if (!tag) return null;

      const attrs = (opening?.attributes ?? [])
        .map((a: any) => jsxAttrToHtml(a))
        .filter((s: string | null): s is string => s !== null)
        .join(' ');

      const attrBlock = attrs ? ` ${attrs}` : '';
      const isVoid = VOID_ELEMENTS.has(tag.toLowerCase());

      if (isVoid) {
        return `<${tag}${attrBlock}>`;
      }

      const children = (node.children ?? [])
        .map((c: any) => jsxNodeToHtml(c))
        .filter((s: string | null): s is string => s !== null)
        .join('');

      return `<${tag}${attrBlock}>${children}</${tag}>`;
    }
    case 'JSXText': {
      const raw = node.value ?? '';
      if (!raw.trim()) return '';
      return raw;
    }
    case 'JSXExpressionContainer': {
      const expr = node.expression;
      if (!expr) return '';
      if (expr.type === 'Literal' && typeof expr.value === 'string') return expr.value;
      if (expr.type === 'TemplateLiteral' && (!expr.expressions || expr.expressions.length === 0)) {
        return (expr.quasis ?? []).map((q: any) => q.value?.cooked ?? q.value?.raw ?? '').join('');
      }
      return '';
    }
    case 'Literal':
      return typeof node.value === 'string' ? node.value : null;
    default:
      return null;
  }
}

function jsxAttrToHtml(attr: any): string | null {
  if (!attr || attr.type !== 'JSXAttribute') return null;
  const name = attr.name?.name;
  if (!name) return null;

  const htmlName = JSX_ATTR_TO_HTML[name] ?? name;
  const isBoolean = BOOLEAN_ATTRS.has(htmlName.toLowerCase());

  if (!attr.value) return htmlName;

  if (attr.value.type === 'Literal') {
    if (isBoolean && attr.value.value === false) return null;
    if (isBoolean && (attr.value.value === true || attr.value.value === '')) return htmlName;
    return `${htmlName}="${escapeHtmlAttr(String(attr.value.value))}"`;
  }

  if (attr.value.type === 'JSXExpressionContainer') {
    const expr = attr.value.expression;
    if (expr?.type === 'Literal') {
      if (isBoolean && expr.value === false) return null;
      if (isBoolean && (expr.value === true || expr.value === '')) return htmlName;
      return `${htmlName}="${escapeHtmlAttr(String(expr.value))}"`;
    }
  }
  return null;
}

