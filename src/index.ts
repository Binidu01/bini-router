function staticString(node: any): string | null {
  node = unwrapExpression(node);
  if (!node) return null;
  if (node.type === 'Literal') return typeof node.value === 'string' ? node.value : null;
  if (node.type === 'TemplateLiteral' && (!node.expressions || node.expressions.length === 0)) {
    return (node.quasis ?? []).map((q: any) => q.value?.cooked ?? q.value?.raw ?? '').join('');
  }
  return null;
}

function staticScalar(node: any): string | null {
  node = unwrapExpression(node);
  if (!node) return null;
  if (node.type === 'Literal') { if (node.regex) return null; const v = node.value; return typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean' ? String(v) : null; }
  return staticString(node);
}

function factsPropKeyName(prop: any): string | null {
  if (!prop || prop.computed) return null;
  if (prop.key?.type === 'Identifier') return prop.key.name;
  if (prop.key?.type === 'Literal') return String(prop.key.value);
  return null;
}

function chainOf(node: any): string | null {
  node = unwrapExpression(node);
  if (!node) return null;
  switch (node.type) {
    case 'ChainExpression': return chainOf(node.expression);
    case 'Identifier': return node.name;
    case 'ThisExpression': return 'this';
    case 'MemberExpression': {
      const obj = chainOf(node.object);
      if (obj === null) return null;
      if (!node.computed) { const name = node.property?.name; return typeof name === 'string' ? `${obj}.${name}` : null; }
      const prop = staticString(node.property);
      return prop === null ? null : `${obj}.${prop}`;
    }
    default: return null;
  }
}

function jsxTagName(node: any): string | null {
  if (!node) return null;
  if (node.type === 'JSXIdentifier') return node.name;
  if (node.type === 'JSXNamespacedName') return `${node.namespace?.name}:${node.name?.name}`;
  if (node.type === 'JSXMemberExpression') { const obj = jsxTagName(node.object); return obj && node.property?.name ? `${obj}.${node.property.name}` : null; }
  return null;
}

function walkFacts(node: any, visit: (n: any, parent: any, key: string | null) => boolean | void, parent: any = null, key: string | null = null): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) { for (const child of node) walkFacts(child, visit, parent, key); return; }
  if (typeof node.type !== 'string') return;
  if (FACTS_SKIP_NODES.has(node.type)) return;
  if (visit(node, parent, key) === false) return;
  for (const k of Object.keys(node)) {
    if (FACTS_SKIP_KEYS.has(k)) continue;
    if (node.type === 'VariableDeclarator' && k === 'id') continue;
    const v = node[k];
    if (v && typeof v === 'object') walkFacts(v, visit, node, k);
  }
}

function isFactReference(node: any, parent: any, key: string | null): boolean {
  if (!isReference(node, parent, key)) return false;
  if (!parent) return true;
  if ((parent.type === 'MethodDefinition' || parent.type === 'PropertyDefinition' || parent.type === 'AccessorProperty') && key === 'key' && !parent.computed) return false;
  if (parent.type === 'ExportSpecifier' && key === 'exported') return false;
  if (parent.type === 'TSEnumMember' && key === 'id') return false;
  if (parent.type === 'CatchClause' && key === 'param') return false;
  if (parent.type === 'AssignmentPattern' && key === 'left') return false;
  return true;
}

function findGeneratedRegion(comments: any[]): { start: number; end: number } | null {
  let start = -1;
  for (const c of comments) {
    const v = String(c?.value ?? '');
    if (start < 0) { if (v.includes(GENERATED_START)) start = c.start; }
    else if (v.includes(GENERATED_END)) return { start, end: c.end };
  }
  return null;
}

function collectSourceFacts(parsed: ParsedFile): SourceFacts {
  const facts = emptySourceFacts();
  const { imports, refs, calls, callArgKeys, news, jsxAttrs, props } = facts;
  const region = findGeneratedRegion(parsed.comments ?? []);

  const onCall = (n: any): void => {
    const callee = unwrapExpression(n.callee);
    const args: any[] = n.arguments ?? [];
    const first = args[0] ? unwrapExpression(args[0]) : undefined;
    if (callee?.type === 'Import') { const s = staticString(first); if (s !== null) imports.add(s); return; }
    const chain = chainOf(callee);
    if (!chain) return;
    let list = calls.get(chain);
    if (!list) { list = []; calls.set(chain, list); }
    const str = first ? staticString(first) : null;
    if (str !== null) { list.push(str); if (chain === 'require') imports.add(str); }
    if (first && !NON_OBJECT_ARG_TYPES.has(first.type)) {
      const keys = callArgKeys.get(chain) ?? new Set<string>();
      if (first.type === 'ObjectExpression') { for (const prop of first.properties ?? []) { const name = prop.type === 'Property' ? factsPropKeyName(prop) : null; keys.add(name ?? '*'); } }
      else keys.add('*');
      callArgKeys.set(chain, keys);
    }
  };

  const onJsxOpening = (n: any): void => {
    const tag = jsxTagName(n.name);
    if (!tag) return;
    for (const attr of n.attributes ?? []) {
      if (attr.type !== 'JSXAttribute') continue;
      const an = attr.name;
      const name = an?.type === 'JSXNamespacedName' ? `${an.namespace?.name}:${an.name?.name}` : an?.name;
      if (typeof name !== 'string') continue;
      jsxAttrs.add(`${tag}:${name}`);
      const value = attr.value?.type === 'JSXExpressionContainer' ? staticScalar(attr.value.expression) : attr.value ? staticScalar(attr.value) : null;
      if (value !== null) jsxAttrs.add(`${tag}:${name}=${value}`);
    }
  };

  const visit = (n: any, parent: any, key: string | null): boolean | void => {
    if (region && typeof n.start === 'number' && n.start >= region.start && n.end <= region.end) return false;
    switch (n.type) {
      case 'ImportDeclaration': case 'ExportAllDeclaration': { const s = staticString(n.source); if (s !== null) imports.add(s); return false; }
      case 'ExportNamedDeclaration': { if (n.source) { const s = staticString(n.source); if (s !== null) imports.add(s); return false; } return; }
      case 'ImportExpression': { const s = staticString(n.source); if (s !== null) imports.add(s); return; }
      case 'TSExternalModuleReference': { const s = staticString(n.expression); if (s !== null) imports.add(s); return; }
      case 'Identifier': { if (isFactReference(n, parent, key)) refs.add(n.name); return; }
      case 'MemberExpression': { const chain = chainOf(n); if (chain) refs.add(chain); return; }
      case 'CallExpression': onCall(n); return;
      case 'NewExpression': { const chain = chainOf(n.callee); if (chain) news.add(chain); return; }
      case 'JSXOpeningElement': onJsxOpening(n); return;
      case 'Property': { if (parent?.type !== 'ObjectExpression') return; const name = factsPropKeyName(n); const value = name === null ? null : staticScalar(n.value); if (name !== null && value !== null) props.add(`${name}=${value}`); return; }
      case 'AssignmentExpression': {
        if (n.operator !== '=') return;
        const left = unwrapExpression(n.left);
        if (left?.type !== 'MemberExpression') return;
        const name = left.computed ? staticString(left.property) : left.property?.name;
        const value = staticScalar(n.right);
        if (typeof name === 'string' && value !== null) props.add(`${name}=${value}`);
        return;
      }
    }
  };

  walkFacts(parsed.program, visit);

  const declared = collectModuleScopeNames(parsed.program);
  if (declared.size > 0) {
    const shadowed = (k: string): boolean => declared.has(k.split('.')[0]);
    for (const k of [...refs]) if (shadowed(k)) refs.delete(k);
    for (const k of [...news]) if (shadowed(k)) news.delete(k);
    for (const k of [...calls.keys()]) if (shadowed(k)) calls.delete(k);
    for (const k of [...callArgKeys.keys()]) if (shadowed(k)) callArgKeys.delete(k);
  }
  return facts;
}

export function getSourceFacts(filePath: string): SourceFacts | null {
  const parsed = readAndParse(filePath);
  if (!parsed) {
    try { if (fs.statSync(filePath).size === 0) return emptySourceFacts(); } catch { /* ignore */ }
    return null;
  }
  if (parsed.synthetic) return emptySourceFacts();
  const cached = sourceFactsCache.get(parsed);
  if (cached) return cached;
  const facts = collectSourceFacts(parsed);
  sourceFactsCache.set(parsed, facts);
  return facts;
}

export function isSourceFile(name: string): boolean {
  if (/\.d\.[cm]?ts$/.test(name)) return false;
  return SOURCE_FILE_EXTS.has(path.extname(name));
}

export function isClientSourceFile(projectRoot: string, file: string): boolean {
  const abs = path.resolve(projectRoot, file);
  const rel = norm(path.relative(path.join(projectRoot, 'src'), abs));
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) return false;
  const parts = rel.split('/');
  const name = parts[parts.length - 1];
  if (name.startsWith('.')) return false;
  for (const dir of parts.slice(0, -1)) { if (dir.startsWith('.') || FACTS_IGNORED_DIRS.has(dir)) return false; }
  if (isInDir(norm(abs), norm(path.join(projectRoot, API_DIR)))) return false;
  return isSourceFile(name);
}

export function scanSourceFacts(projectRoot: string): Map<string, SourceFacts> {
  const out = new Map<string, SourceFacts>();
  const apiDir = path.resolve(projectRoot, API_DIR);
  const visit = (dir: string, depth: number): void => {
    if (depth > MAX_DEPTH) return;
    let entries: fs.Dirent[];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    entries.sort((a, b) => cmpStr(a.name, b.name));
    for (const entry of entries) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name.startsWith('.') || FACTS_IGNORED_DIRS.has(entry.name)) continue;
        if (path.resolve(full) === apiDir) continue;
        visit(full, depth + 1);
      } else if (entry.isFile()) {
        if (entry.name.startsWith('.') || !isSourceFile(entry.name)) continue;
        const facts = getSourceFacts(full);
        if (facts) out.set(full, facts);
      }
    }
  };
  visit(path.join(projectRoot, 'src'), 0);
  return out;
}

function collectModuleScopeNames(program: any): Set<string> {
  const names = new Set<string>();
  for (const stmt of program.body ?? []) {
    const target = stmt.type === 'ExportNamedDeclaration' || stmt.type === 'ExportDefaultDeclaration' ? stmt.declaration ?? stmt : stmt;
    if (target.type === 'VariableDeclaration') { for (const d of target.declarations ?? []) collectPatternNames(d.id, names); }
    else if (target.type === 'FunctionDeclaration' || target.type === 'ClassDeclaration') { if (target.id?.name) names.add(target.id.name); }
    if (stmt.type === 'ImportDeclaration') { for (const spec of stmt.specifiers ?? []) { if (spec.local?.name) names.add(spec.local.name); } }
  }
  const FUNCTION_BOUNDARIES = new Set(['FunctionDeclaration', 'FunctionExpression', 'ArrowFunctionExpression', 'ClassDeclaration', 'ClassExpression', 'StaticBlock']);
  const walkVar = (node: any): void => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) { for (const child of node) walkVar(child); return; }
    if (typeof node.type !== 'string') return;
    if (FUNCTION_BOUNDARIES.has(node.type)) return;
    if (node.type === 'VariableDeclaration' && node.kind === 'var') { for (const d of node.declarations ?? []) collectPatternNames(d.id, names); }
    for (const key of Object.keys(node)) {
      if (key === 'type' || key === 'start' || key === 'end' || key === 'loc' || key === 'range') continue;
      if (key === 'params') continue;
      const v = node[key];
      if (v && typeof v === 'object') walkVar(v);
    }
  };
  walkVar(program);
  return names;
}

function isReference(node: any, parent: any, key: string | null): boolean {
  if (!parent) return true;
  if (
    (parent.type === 'VariableDeclarator' && key === 'id') ||
    (parent.type === 'FunctionDeclaration' && key === 'id') ||
    (parent.type === 'FunctionExpression' && key === 'id') ||
    (parent.type === 'ClassDeclaration' && key === 'id') ||
    (parent.type === 'ClassExpression' && key === 'id') ||
    (parent.type === 'ImportDefaultSpecifier' && key === 'local') ||
    (parent.type === 'ImportNamespaceSpecifier' && key === 'local') ||
    (parent.type === 'ImportSpecifier' && key === 'local') ||
    ((parent.type === 'FunctionDeclaration' || parent.type === 'FunctionExpression' || parent.type === 'ArrowFunctionExpression') && key === 'params')
  ) return false;
  if (parent.type === 'Property' && key === 'key' && !parent.computed) return false;
  if (parent.type === 'MemberExpression' && key === 'property' && !parent.computed) return false;
  if (parent.type === 'JSXAttribute' && key === 'name') return false;
  if ((parent.type === 'LabeledStatement' || parent.type === 'BreakStatement' || parent.type === 'ContinueStatement') && key === 'label') return false;
  return true;
}

function stripAppExports(source: string, parsed: ParsedFile): MagicString | null {
  const ranges: { start: number; end: number }[] = [];
  for (const name of ['metadata', 'document'] as const) {
    const r = getExportRange(parsed, name);
    if (r) ranges.push(r);
  }
  if (ranges.length === 0) return null;
  ranges.sort((a, b) => b.start - a.start);
  const ms = new MagicString(source);
  for (const r of ranges) ms.overwrite(r.start, r.end, '');
  return ms;
}

