const ROUTER_EXPORTS = [
  'Link', 'NavLink', 'useNavigate', 'useParams', 'useLocation',
  'useSearchParams', 'Outlet',
] as const;

const REACT_EXPORTS = [
  'useState', 'useEffect', 'useRef', 'useMemo', 'useCallback',
  'useContext', 'createContext', 'useReducer', 'useId',
  'useTransition', 'useDeferredValue',
] as const;

const ENV_EXPORTS = ['getEnv', 'requireEnv'] as const;

interface AutoImportSpec {
  module: 'react-router-dom' | 'react' | 'bini-env';
  names: readonly string[];
}

const AUTO_IMPORTS: AutoImportSpec[] = [
  { module: 'react-router-dom', names: ROUTER_EXPORTS },
  { module: 'react', names: REACT_EXPORTS },
  { module: 'bini-env', names: ENV_EXPORTS },
];

function collectModuleScopeNames(program: any): Set<string> {
  const names = new Set<string>();

  for (const stmt of program.body ?? []) {
    const target =
      stmt.type === 'ExportNamedDeclaration' || stmt.type === 'ExportDefaultDeclaration'
        ? stmt.declaration ?? stmt
        : stmt;

    if (target.type === 'VariableDeclaration') {
      for (const d of target.declarations ?? []) collectPatternNames(d.id, names);
    } else if (target.type === 'FunctionDeclaration' || target.type === 'ClassDeclaration') {
      if (target.id?.name) names.add(target.id.name);
    }

    if (stmt.type === 'ImportDeclaration') {
      for (const spec of stmt.specifiers ?? []) {
        if (spec.local?.name) names.add(spec.local.name);
      }
    }
  }

  const FUNCTION_BOUNDARIES = new Set([
    'FunctionDeclaration', 'FunctionExpression', 'ArrowFunctionExpression',
    'ClassDeclaration', 'ClassExpression', 'StaticBlock',
  ]);

  const walkVar = (node: any): void => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) {
      for (const child of node) walkVar(child);
      return;
    }
    if (typeof node.type !== 'string') return;
    if (FUNCTION_BOUNDARIES.has(node.type)) return;

    if (node.type === 'VariableDeclaration' && node.kind === 'var') {
      for (const d of node.declarations ?? []) collectPatternNames(d.id, names);
    }

    for (const key of Object.keys(node)) {
      if (key === 'type' || key === 'start' || key === 'end' || key === 'loc' || key === 'range') continue;
      if (key === 'params') continue;
      const v = node[key];
      if (v && typeof v === 'object') walkVar(v);
    }
  };
  walkVar(program);

  return names;
}

function injectAutoImports(parsed: ParsedFile, source: string): string {
  const existingImports = new Map<string, Set<string>>();

  walk(parsed.program, (node) => {
    if (node.type === 'ImportDeclaration') {
      const mod = node.source?.value;
      if (typeof mod === 'string') {
        const set = existingImports.get(mod) ?? new Set<string>();
        for (const spec of node.specifiers ?? []) {
          if (spec.imported?.name) set.add(spec.imported.name);
        }
        existingImports.set(mod, set);
      }
      return false;
    }
    return undefined;
  });

  const declared = collectModuleScopeNames(parsed.program);

  const referenced = new Set<string>();
  walkReferences(parsed.program, referenced);

  const injected: string[] = [];
  for (const { module, names } of AUTO_IMPORTS) {
    const already = existingImports.get(module) ?? new Set<string>();
    const needed = names.filter(
      (n) => referenced.has(n) && !declared.has(n) && !already.has(n),
    );
    if (needed.length) {
      injected.push(`import { ${needed.join(', ')} } from '${module}';`);
    }
  }

  if (injected.length === 0) return source;

  const blockEnd = findDirectiveBlockEnd(parsed, source);
  const prefix = source.slice(0, blockEnd);
  const rest = source.slice(blockEnd);

  const needsNewline = prefix.length > 0 && !prefix.endsWith('\n');
  return `${prefix}${needsNewline ? '\n' : ''}${injected.join('\n')}\n${rest}`;
}

function collectPatternNames(node: any, out: Set<string>): void {
  if (!node) return;
  switch (node.type) {
    case 'Identifier':
      out.add(node.name);
      break;
    case 'ObjectPattern':
      for (const prop of node.properties ?? []) {
        if (prop.type === 'RestElement') collectPatternNames(prop.argument, out);
        else collectPatternNames(prop.value, out);
      }
      break;
    case 'ArrayPattern':
      for (const el of node.elements ?? []) collectPatternNames(el, out);
      break;
    case 'AssignmentPattern':
      collectPatternNames(node.left, out);
      break;
    case 'RestElement':
      collectPatternNames(node.argument, out);
      break;
  }
}

function walkReferences(
  node: any,
  out: Set<string>,
  parent: any = null,
  key: string | null = null,
): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const child of node) walkReferences(child, out, parent, key);
    return;
  }
  if (typeof node.type !== 'string') return;

  if (parent?.type === 'JSXAttribute' && key === 'name') return;
  if (parent?.type === 'JSXMemberExpression' && key === 'property') return;

  if (node.type === 'JSXIdentifier') {
    if (typeof node.name === 'string') out.add(node.name);
    return;
  }

  if (node.type === 'Identifier') {
    if (isReference(node, parent, key)) out.add(node.name);
    return;
  }

  for (const k of Object.keys(node)) {
    if (k === 'type' || k === 'start' || k === 'end' || k === 'loc' || k === 'range') continue;
    if (k === 'params') continue;
    const value = node[k];
    if (value && typeof value === 'object') walkReferences(value, out, node, k);
  }
}

function isReference(node: any, parent: any, key: string | null): boolean {
  if (!parent) return true;

  if (
    (parent.type === 'VariableDeclarator' && key === 'id') ||
    (parent.type === 'FunctionDeclaration' && key === 'id') ||
    (parent.type === 'FunctionExpression' && key === 'id') ||
    (parent.type === 'ClassDeclaration' && key === 'id') ||
    (parent.type === 'ClassExpression' && key === 'id') ||
    (parent.type === 'ImportDefaultSpecifier' && key === 'local') ||
    (parent.type === 'ImportNamespaceSpecifier' && key === 'local') ||
    (parent.type === 'ImportSpecifier' && key === 'local') ||
    ((parent.type === 'FunctionDeclaration' ||
      parent.type === 'FunctionExpression' ||
      parent.type === 'ArrowFunctionExpression') && key === 'params')
  ) {
    return false;
  }

  if (parent.type === 'Property' && key === 'key' && !parent.computed) return false;
  if (parent.type === 'MemberExpression' && key === 'property' && !parent.computed) return false;
  if (parent.type === 'JSXAttribute' && key === 'name') return false;
  if (
    (parent.type === 'LabeledStatement' ||
      parent.type === 'BreakStatement' ||
      parent.type === 'ContinueStatement') &&
    key === 'label'
  ) return false;

  return true;
}

// ─── Export stripping (AST ranges, no regex) ────────────────────────────────

function stripAppExports(source: string, parsed: ParsedFile): string {
  const ranges: { start: number; end: number }[] = [];
  for (const name of ['metadata', 'document'] as const) {
    const r = getExportRange(parsed, name);
    if (r) ranges.push(r);
  }
  if (ranges.length === 0) return source;

  ranges.sort((a, b) => b.start - a.start);

  let result = source;
  for (const r of ranges) {
    const newlineCount = countNewlines(result, r.start, r.end);
    result = result.slice(0, r.start) + '\n'.repeat(newlineCount) + result.slice(r.end);
  }
  return result;
}

// ─── API Route Scanner ───────────────────────────────────────────────────────

function apiCatchallDirHasNestedRoutes(dir: string): boolean {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return false;
  }
  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (apiCatchallDirHasNestedRoutes(fullPath)) return true;
    } else {
      const ext = path.extname(entry.name);
      if (!(API_EXTS as readonly string[]).includes(ext)) continue;
      const base = path.basename(entry.name, ext);
      if (base === 'index' || base === 'route') continue;
      return true;
    }
  }
  return false;
}

function scanApiRoutes(dir: string, baseRoute = '', depth = 0): ApiRoute[] {
  if (depth > MAX_DEPTH) {
    viteWarnLog(`Maximum API directory depth reached at ${dir}`);
    return [];
  }

  const routes: ApiRoute[] = [];
  if (!fs.existsSync(dir)) return routes;

  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (error) {
    viteErrorLog(`Failed to read API directory ${dir}: ${error instanceof Error ? error.message : String(error)}`);
    return routes;
  }

  entries.sort((a, b) => cmpStr(a.name, b.name));

  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      const isGroup = isRouteGroup(entry.name);
      const isOptionalCatchAll = entry.name.startsWith('[[...') && entry.name.endsWith(']]');
      const isCatchAll = !isOptionalCatchAll && entry.name.startsWith('[...') && entry.name.endsWith(']');
      const isDynamic = !isCatchAll && !isOptionalCatchAll && entry.name.startsWith('[') && entry.name.endsWith(']');

      let segment: string;
      let dirCatchallParamName: string | undefined;

      if (isGroup) {
        segment = '';
      } else if (isOptionalCatchAll) {
        const name = entry.name.slice(5, -2);
        if (!isValidParamName(name)) {
          viteWarnLog(`Invalid API parameter name: ${name}`);
          continue;
        }
        dirCatchallParamName = name;
        segment = '**';
      } else if (isCatchAll) {
        const name = entry.name.slice(4, -1);
        if (!isValidParamName(name)) {
          viteWarnLog(`Invalid API parameter name: ${name}`);
          continue;
        }
        dirCatchallParamName = name;
        segment = '*';
      } else if (isDynamic) {
        const paramName = entry.name.slice(1, -1);
        if (!isValidParamName(paramName)) {
          viteWarnLog(`Invalid API parameter name: ${paramName}`);
          continue;
        }
        segment = `:${paramName}`;
      } else {
        if (!isValidRouteSegment(entry.name)) {
          viteWarnLog(`Invalid API directory name: ${entry.name}`);
          continue;
        }
        segment = entry.name;
      }

      const nextBase = segment ? `${baseRoute}/${segment}` : baseRoute;

      if (dirCatchallParamName && apiCatchallDirHasNestedRoutes(fullPath)) {
        viteWarnLog(
          `Skipping nested routes under catch-all directory ${entry.name} in ${dir}: ` +
          `a catch-all segment must be the last path segment. Move these files out ` +
          `of the catch-all directory, or rename the directory to a non-catch-all.`
        );
        continue;
      }

      const childRoutes = scanApiRoutes(fullPath, nextBase, depth + 1);

      if (dirCatchallParamName) {
        for (const cr of childRoutes) {
          if (!cr.catchallParamName && cr.routePath.includes('*')) {
            routes.push({ ...cr, catchallParamName: dirCatchallParamName });
          } else {
            routes.push(cr);
          }
        }
      } else {
        routes.push(...childRoutes);
      }
      continue;
    }

    const ext = path.extname(entry.name);
    const base = path.basename(entry.name, ext);
    if (!(API_EXTS as readonly string[]).includes(ext)) continue;

    const isRouteFile = base === 'route';
    const isIndexFile = base === 'index';
    const isBareRoute = !isRouteFile && !isIndexFile;

    if (isRouteFile) {
      const sibling = (API_EXTS as readonly string[]).find(
        e => fs.existsSync(path.join(dir, `index${e}`))
      );
      if (sibling) {
        warnOnceMsg(`Both route.* and index.* found in ${dir}; using route.*`);
      }
    }

    const isOptionalCatchAll = isBareRoute && base.startsWith('[[...') && base.endsWith(']]');
    const isCatchAll = isBareRoute && !isOptionalCatchAll && base.startsWith('[...') && base.endsWith(']');
    const isDynamic = isBareRoute && !isCatchAll && !isOptionalCatchAll && base.startsWith('[') && base.endsWith(']');

    let catchallParamName: string | undefined;
    let rawRoutePath: string;

    if (isRouteFile || isIndexFile) {
      rawRoutePath = baseRoute || '/';
    } else if (isOptionalCatchAll) {
      const name = base.slice(5, -2);
      if (!isValidParamName(name)) {
        viteWarnLog(`Invalid API parameter name: ${name}`);
        continue;
      }
      catchallParamName = name;
      rawRoutePath = `${baseRoute}/**`;
    } else if (isCatchAll) {
      const name = base.slice(4, -1);
      if (!isValidParamName(name)) {
        viteWarnLog(`Invalid API parameter name: ${name}`);
        continue;
      }
      catchallParamName = name;
      rawRoutePath = `${baseRoute}/*`;
    } else if (isDynamic) {
      const paramName = base.slice(1, -1);
      if (!isValidParamName(paramName)) {
        viteWarnLog(`Invalid API parameter name: ${paramName}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/:${paramName}`;
    } else {
      if (!isValidRouteSegment(base)) {
        viteWarnLog(`Invalid API route name: ${base}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/${base}`;
    }

    const routePath = normalizeRoutePath(rawRoutePath);
    routes.push({ routePath, filePath: fullPath, catchallParamName });
  }

  routes.sort((a, b) => {
    const aCatch = a.routePath.includes('*') ? 1 : 0;
    const bCatch = b.routePath.includes('*') ? 1 : 0;
    if (aCatch !== bCatch) return aCatch - bCatch;
    const aDyn = a.routePath.includes(':') ? 1 : 0;
    const bDyn = b.routePath.includes(':') ? 1 : 0;
    if (aDyn !== bDyn) return aDyn - bDyn;
    return b.routePath.length - a.routePath.length;
  });

  return routes;
}

// ─── API Server ─────────────────────────────────────────────────────────────

interface CachedModule {
  mtime: number;
  size: number;
  handler: any;
  error?: Error;
}

type ApiHandlerFn = (
  req: Request,
  ctx: { params: Record<string, string>; searchParams: URLSearchParams },
) => Response | Promise<Response>;

interface LoadedApiModule {
  methods: Partial<Record<ApiMethod, ApiHandlerFn>>;
  defaultExport: unknown;
  allowed: ApiMethod[];
}

function rememberModule(cache: Map<string, CachedModule>, key: string, entry: CachedModule): void {
  if (cache.size >= MODULE_CACHE_MAX && !cache.has(key)) {
    const oldest = cache.keys().next().value;
    if (oldest !== undefined) cache.delete(oldest);
  }
  cache.set(key, entry);
}

async function importHandler(
  server: ViteDevServer | null,
  filePath: string,
  moduleCache: Map<string, CachedModule>,
): Promise<LoadedApiModule | null> {
  let mod: any;

  if (server) {
    mod = await server.ssrLoadModule(filePath);
  } else {
    let stats: fs.Stats;
    try {
      stats = fs.statSync(filePath);
      if (stats.size > MAX_FILE_SIZE) return null;
    } catch {
      return null;
    }

    const cacheKey = filePath;
    const cached = moduleCache.get(cacheKey);
    if (cached && cached.mtime === stats.mtimeMs && cached.size === stats.size) {
      if (cached.error) throw cached.error;
      mod = cached.handler;
    } else {
      try {
        const { pathToFileURL } = await import('url');
        // mtime-derived query: identical (path, mtime) pairs reuse the same
        // Node ESM registry entry instead of accumulating per-edit nonces.
        const url = pathToFileURL(filePath).href + '?v=' + stats.mtimeMs;
        mod = await import(url);
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: mod });
      } catch (error) {
        const err = error instanceof Error ? error : new Error(String(error));
        rememberModule(moduleCache, cacheKey, { mtime: stats.mtimeMs, size: stats.size, handler: null, error: err });
        throw err;
      }
    }
  }

  if (!mod || typeof mod !== 'object') return null;

  const methods: Partial<Record<ApiMethod, ApiHandlerFn>> = {};
  const allowed: ApiMethod[] = [];

  for (const m of API_METHODS) {
    const fn = mod[m];
    if (typeof fn === 'function') {
      methods[m] = fn as ApiHandlerFn;
      allowed.push(m);
    }
  }

  const defaultExport = mod.default ?? null;

  return { methods, defaultExport, allowed };
}

type BodyReadResult =
  | { kind: 'ok'; body: Buffer | undefined }
  | { kind: 'timeout' }
  | { kind: 'too-large' };

async function readBodyWithTimeout(
  req: any,
  bodySizeLimit: number,
  timeoutMs = BODY_READ_TIMEOUT_MS,
): Promise<BodyReadResult> {
  let timedOut = false;
  let timer: ReturnType<typeof setTimeout>;

  const timeoutPromise = new Promise<'timeout'>((resolve) => {
    timer = setTimeout(() => {
      timedOut = true;
      resolve('timeout');
    }, timeoutMs);
  });

  const readPromise = (async (): Promise<BodyReadResult> => {
    try {
      const chunks: Buffer[] = [];
      let total = 0;
      for await (const chunk of req) {
        if (timedOut) break;
        const buf = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
        total += buf.length;
        if (total > bodySizeLimit) {
          req.pause();
          return { kind: 'too-large' };
        }
        chunks.push(buf);
      }
      return { kind: 'ok', body: chunks.length > 0 ? Buffer.concat(chunks) : undefined };
    } catch (err) {
      if (timedOut) return { kind: 'timeout' };
      throw err;
    }
  })();

  try {
    const result = await Promise.race([readPromise, timeoutPromise]);
    if (result === 'timeout') {
      req.destroy(new Error('Request body read timeout'));
      readPromise.catch(() => {});
      return { kind: 'timeout' };
    }
    return result;
  } finally {
    clearTimeout(timer!);
  }
}

async function pipeWebResponse(res: any, webRes: Response, method: string): Promise<void> {
  if (method === 'HEAD' || !webRes.body) {
    res.end();
    return;
  }

  const reader = webRes.body.getReader();
  res.on('close', () => {
    reader.cancel().catch(() => {});
  });

  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value || value.byteLength === 0) continue;

      const chunk = Buffer.isBuffer(value) ? value : Buffer.from(value);
      if (!res.write(chunk)) {
        await new Promise<void>((resolve, reject) => {
          const onDrain = () => { res.off('error', onError); resolve(); };
          const onError = (err: Error) => { res.off('drain', onDrain); reject(err); };
          res.once('drain', onDrain);
          res.once('error', onError);
        });
      }
    }
    res.end();
  } catch (err) {
    if (!res.writableEnded) res.destroy(err as Error);
    else res.end();
  }
}

async function sendWebResponse(
  res: any,
  webRes: Response,
  method: string,
  corsConfig: boolean | { origin?: string; methods?: string[]; headers?: string[] },
  allowedMethods: string[],
): Promise<void> {
  if (corsConfig) {
    const headers = new Headers(webRes.headers);
    const corsOptions = typeof corsConfig === 'boolean'
      ? { origin: '*', methods: allowedMethods }
      : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods };

    headers.set('Access-Control-Allow-Origin', corsOptions.origin);
    headers.set('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
    if (corsOptions.origin !== '*') {
      headers.set('Access-Control-Allow-Credentials', 'true');
    }

    webRes = new Response(webRes.body, {
      status: webRes.status,
      statusText: webRes.statusText,
      headers,
    });
  }

  res.statusCode = webRes.status;

  const setCookie =
    typeof (webRes.headers as any).getSetCookie === 'function'
      ? (webRes.headers as any).getSetCookie()
      : [];
  if (setCookie.length > 0) {
    res.setHeader('Set-Cookie', setCookie);
  }

  webRes.headers.forEach((value, key) => {
    if (key.toLowerCase() === 'set-cookie') return;
    res.setHeader(key, value);
  });

  await pipeWebResponse(res, webRes, method);
}

async function handleApiRequest(
  req: any,
  res: any,
  next: any,
  apiDir: string,
  corsConfig: boolean | { origin?: string; methods?: string[]; headers?: string[] },
  getCache: () => { routes: ApiRoute[] } | null,
  setCache: (v: { routes: ApiRoute[] }) => void,
  moduleCache: Map<string, CachedModule>,
  bodySizeLimit: number = DEFAULT_BODY_SIZE_LIMIT,
  server: ViteDevServer | null = null,
): Promise<void> {
  res.on('error', () => {});

  try {
    const allowedMethods = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'HEAD'];
    if (!allowedMethods.includes(req.method)) {
      req.resume();
      res.statusCode = 405;
      res.setHeader('Allow', allowedMethods.join(', '));
      res.end();
      return;
    }

    if (
      corsConfig &&
      req.method === 'OPTIONS' &&
      req.headers['access-control-request-method']
    ) {
      req.resume();
      res.statusCode = 204;

      const corsOptions = typeof corsConfig === 'boolean'
        ? { origin: '*', methods: allowedMethods, headers: 'Content-Type, Authorization, X-Requested-With' }
        : { origin: corsConfig.origin || '*', methods: corsConfig.methods || allowedMethods, headers: corsConfig.headers || 'Content-Type, Authorization, X-Requested-With' };

      res.setHeader('Access-Control-Allow-Origin', corsOptions.origin);
      res.setHeader('Access-Control-Allow-Methods', corsOptions.methods.join(', '));
      res.setHeader('Access-Control-Allow-Headers', corsOptions.headers);
      if (corsOptions.origin !== '*') {
        res.setHeader('Access-Control-Allow-Credentials', 'true');
      }
      res.setHeader('Access-Control-Max-Age', '86400');
      res.end();
      return;
    }

    let cache = getCache();
    if (!cache) {
      const rawRoutes = scanApiRoutes(apiDir, '');
      cache = { routes: rawRoutes };
      setCache(cache);
    }

    const strippedUrl = req.url ?? '/';
    const urlForRequest = buildRequestUrl(req, strippedUrl);

    let pathname: string;
    try {
      pathname = new URL(urlForRequest).pathname;
    } catch {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid URL');
      return;
    }

    if (pathname.includes('..') || pathname.includes('//')) {
      req.resume();
      res.statusCode = 400;
      res.end('Invalid path');
      return;
    }

    const contentLength = Number(req.headers['content-length'] ?? 0);
    if (contentLength > bodySizeLimit) {
      req.resume();
      res.statusCode = 413;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({
        error: 'Payload Too Large',
        message: `Request body exceeds ${bodySizeLimit} bytes limit`,
      }));
      return;
    }

    const bodyResult = await readBodyWithTimeout(req, bodySizeLimit);
    if (bodyResult.kind === 'timeout') {
      res.statusCode = 408;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ error: 'Request Timeout' }));
      return;
    }
    if (bodyResult.kind === 'too-large') {
      const payload = JSON.stringify({
        error: 'Payload Too Large',
        message: `Request body exceeds ${bodySizeLimit} bytes limit`,
      });
      res.statusCode = 413;
      res.setHeader('Content-Type', 'application/json');
      res.setHeader('Content-Length', String(Buffer.byteLength(payload)));
      res.end(payload, () => {
        req.destroy();
      });
      return;
    }
    const body = bodyResult.body;

    const method = req.method;
    const searchParams = new URL(urlForRequest).searchParams;

    const webReq = new Request(urlForRequest, {
      method,
      headers: normalizeHeaders(req.headers),
      body: !['GET', 'HEAD'].includes(method) && body?.length
        ? new Uint8Array(body)
        : undefined,
    });

    for (const route of cache.routes) {
      const params = matchRoute(route.routePath, pathname, {
        enforceNonEmptyCatchAll: true,
        catchallParamName: route.catchallParamName,
      });
      if (params === null) continue;

      let loaded: LoadedApiModule | null;
      try {
        loaded = await importHandler(server, route.filePath, moduleCache);
      } catch (error) {
        viteErrorLog(`Failed to load API handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        res.statusCode = 500;
        res.setHeader('Content-Type', 'application/json');
        res.end(JSON.stringify({ error: 'Internal Server Error' }));
        return;
      }

      if (!loaded) continue;

      const { methods: methodHandlers, defaultExport, allowed } = loaded;

      if (allowed.length > 0) {
        const handlerFn = methodHandlers[method as ApiMethod];

        if (!handlerFn) {
          res.statusCode = 405;
          res.setHeader('Allow', allowed.join(', '));
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'Method Not Allowed', allow: allowed }));
          return;
        }

        let webRes: Response;
        try {
          webRes = await handlerFn(webReq.clone(), { params, searchParams });
        } catch (error) {
          webReq.body?.cancel().catch(() => {});
          viteErrorLog(`Error in ${method} handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
          if (!res.headersSent) {
            res.statusCode = 500;
            res.setHeader('Content-Type', 'application/json');
            res.end(JSON.stringify({ error: 'Internal Server Error' }));
          }
          return;
        }

        await sendWebResponse(res, webRes, method, corsConfig, allowedMethods);
        return;
      }

      if (!defaultExport) continue;

      let webRes: Response;
      try {
        if (typeof (defaultExport as any).fetch === 'function') {
          webRes = await (defaultExport as any).fetch(webReq.clone());
        } else if (typeof defaultExport === 'function') {
          webRes = await (defaultExport as ApiHandlerFn)(webReq.clone(), { params, searchParams });
        } else {
          continue;
        }
      } catch (error) {
        webReq.body?.cancel().catch(() => {});
        viteErrorLog(`Error in default handler ${route.filePath}: ${error instanceof Error ? error.message : String(error)}`);
        if (!res.headersSent) {
          res.statusCode = 500;
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'Internal Server Error' }));
        }
        return;
      }

      await sendWebResponse(res, webRes, method, corsConfig, allowedMethods);
      return;
    }

    res.statusCode = 404;
    res.setHeader('Content-Type', 'application/json');
    res.end(JSON.stringify({
      error: 'Not Found',
      message: `No API handler matched ${req.url}`,
    }));
  } catch (error) {
    viteErrorLog(`API request error: ${error instanceof Error ? error.message : String(error)}`);
    if (!res.headersSent) {
      res.statusCode = 500;
      res.setHeader('Content-Type', 'application/json');
      res.end(JSON.stringify({ error: 'Internal Server Error' }));
    }
  }
}

function normalizeHeaders(headers: Record<string, string | string[] | undefined>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers)) {
    if (v === undefined) continue;
    if (HOP_BY_HOP_HEADERS.has(k.toLowerCase())) continue;
    out[k] = Array.isArray(v) ? v.join(', ') : v;
  }
  return out;
}

// ─── Plugin ───────────────────────────────────────────────────────────────────

export function biniroute(options: BiniPluginOptions = {}): Plugin[] {
  const {
    cors: corsConfig = false,
    strictMode = true,
    bodySizeLimit = DEFAULT_BODY_SIZE_LIMIT,
  } = options;

  let projectRoot = process.cwd();

  const getAppDir = (): string => path.join(projectRoot, options.appDir ?? 'src/app');
  const getApiDir = (): string => path.join(projectRoot, options.apiDir ?? 'src/app/api');
  const getAutoImportDir = (): string =>
    path.join(projectRoot, options.autoImportDir ?? 'src');

  let debounceTimer: ReturnType<typeof setTimeout> | null = null;
  let lastGeneratedCode = '';
  let apiRouteCache: { routes: ApiRoute[] } | null = null;
  const moduleCache = new Map<string, CachedModule>();
  let isGenerating = false;
  let cachedAppFile: string | null = null;
  let cachedAppFileRoot: string | null = null;
  let cachedIsTs: boolean | null = null;
  let cachedIsTsRoot: string | null = null;
  let cachedApiDirExists: boolean | null = null;

  let isBuild = false;
  let viteBase = '/';

  function getIsTypeScriptCached(): boolean {
    if (cachedIsTs !== null && cachedIsTsRoot === projectRoot) return cachedIsTs;
    cachedIsTs = isTypeScriptProject(projectRoot);
    cachedIsTsRoot = projectRoot;
    return cachedIsTs;
  }

  function getAppFileCached(): string {
    if (cachedAppFile && cachedAppFileRoot === projectRoot) return cachedAppFile;
    cachedAppFile = getAppFile(projectRoot, getIsTypeScriptCached());
    cachedAppFileRoot = projectRoot;
    return cachedAppFile;
  }

  function getApiDirExistsCached(): boolean {
    if (cachedApiDirExists === null) {
      cachedApiDirExists = fs.existsSync(getApiDir());
    }
    return cachedApiDirExists;
  }

  function isPageFile(f: string): boolean {
    const nf = norm(f);
    const base = path.basename(f, path.extname(f));
    const ext = path.extname(f);

    if (!(SUPPORTED_EXTS as readonly string[]).includes(ext)) return false;
    if (!isInDir(nf, norm(getAppDir()))) return false;
    if (isInDir(nf, norm(getApiDir()))) return false;
    if (base.startsWith('_')) return false;

    return true;
  }

  function isApiFile(f: string): boolean {
    const nf = norm(f);
    return isInDir(nf, norm(getApiDir())) &&
      (API_EXTS as readonly string[]).includes(path.extname(f));
  }

  function applyApp(): string | null {
    if (isGenerating) return null;
    isGenerating = true;
    warnedMessages.clear();

    try {
      const dir = getAppDir();
      if (!fs.existsSync(dir)) return null;

      const basename = toBasename(viteBase);
      const isTs = getIsTypeScriptCached();

      const code = generateApp(dir, getApiDir(), projectRoot, strictMode, basename, isTs);
      if (code === lastGeneratedCode) return null;

      const appFile = getAppFileCached();

      let existingCode = '';
      try {
        existingCode = fs.readFileSync(appFile, 'utf8');
      } catch {
        // File doesn't exist yet.
      }

      if (existingCode && !existingCode.includes(GENERATED_HEADER)) {
        const msg = `${path.relative(projectRoot, appFile)} exists but is not bini-generated. ` +
          `Delete it or move it aside to let bini-router manage this file.`;
        if (isBuild) {
          throw new Error(msg);
        }
        viteWarnLog(msg);
        return null;
      }

      if (existingCode === code) {
        lastGeneratedCode = code;
        return null;
      }

      fs.mkdirSync(path.dirname(appFile), { recursive: true });
      fs.writeFileSync(appFile, code, 'utf8');
      lastGeneratedCode = code;

      return code;
    } catch (error) {
      if (isBuild) {
        throw error;
      }
      if (error instanceof RouteConflictError) {
        viteErrorLog(error.message);
        return null;
      }
      viteErrorLog(`Failed to generate app: ${error instanceof Error ? error.message : String(error)}`);
      return null;
    } finally {
      isGenerating = false;
    }
  }

  function scheduleRegen(server: ViteDevServer, delay = DEBOUNCE_MS): void {
    if (debounceTimer) clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      debounceTimer = null;
      if (applyApp() !== null) {
        const mod = server.moduleGraph.getModuleById(RESOLVED_VIRTUAL_ROUTES_ID);
        if (mod) server.moduleGraph.invalidateModule(mod);
        server.ws.send({ type: 'full-reload', path: '*' });
      }
    }, delay);
  }

  function createApiMiddleware(server: ViteDevServer | null) {
    return (req: any, res: any, next: any) => {
      if (!req.url) return next();

      const originalUrl = req.url;
      const apiPath = resolveApiPath(req.url, viteBase);
      if (apiPath === null) return next();

      if (!getApiDirExistsCached()) {
        return next();
      }

      req.url = apiPath;

      handleApiRequest(
        req, res, next, getApiDir(), corsConfig,
        () => apiRouteCache, (v) => { apiRouteCache = v; },
        moduleCache, bodySizeLimit, server,
      ).catch((error) => {
        req.url = originalUrl;
        viteErrorLog(`Unhandled API middleware error: ${error instanceof Error ? error.message : String(error)}`);
        if (!res.headersSent) {
          res.statusCode = 500;
          res.setHeader('Content-Type', 'application/json');
          res.end(JSON.stringify({ error: 'Internal Server Error' }));
        }
      });
    };
  }

  const routerPlugin: Plugin = {
    name: 'bini-router',
    enforce: 'pre',

    config(_, env) {
      isBuild = env.command === 'build';
    },

    configResolved(config) {
      const newRoot = config.root || process.cwd();
      if (newRoot !== projectRoot) {
        cachedAppFile = null;
        cachedAppFileRoot = null;
        cachedIsTs = null;
        cachedIsTsRoot = null;
        cachedApiDirExists = null;
      }
      projectRoot = newRoot;

      const newBase = config.base || '/';
      viteBase = newBase;

      applyApp();
    },

    transform: {
      filter: {
        id: { include: /\.(tsx|jsx|ts|js|mdx|md)$/ },
      },
      handler(code, id) {
        const nid = norm(id);
        const autoImportDir = getAutoImportDir();
        const appDir = getAppDir();
        const apiDir = getApiDir();

        if (!isInDir(nid, norm(autoImportDir))) return;
        if (isInDir(nid, norm(apiDir))) return;
        if (nid === norm(getAppFileCached())) return;
        if (nid.endsWith('.mdx') || nid.endsWith('.md')) return;
        if (nid.endsWith('.d.ts') || nid.endsWith('.d.mts') || nid.endsWith('.d.cts')) return;

        const parsed = parseFile(code, id);
        if (!parsed) return;

        let result = code;

        if (isInDir(nid, norm(appDir)) &&
            (getExportRange(parsed, 'metadata') || getExportRange(parsed, 'document'))) {
          result = stripAppExports(result, parsed);
        }

        result = injectAutoImports(parsed, result);

        if (result === code) return;

        return { code: result, map: null };
      },
    },

    buildStart(): void {
      if (!lastGeneratedCode) {
        applyApp();
      }
    },

    buildEnd(): void {
      apiRouteCache = null;
      moduleCache.clear();
      clearBuildCaches();
      if (debounceTimer) {
        clearTimeout(debounceTimer);
        debounceTimer = null;
      }
    },

    async configureServer(server): Promise<void> {
      const appDir = getAppDir();
      const apiDir = getApiDir();

      cachedApiDirExists = fs.existsSync(apiDir);

      if (!fs.existsSync(appDir)) return;

      if (!lastGeneratedCode) {
        applyApp();
      }

      server.watcher.add(appDir);

      const watcherEvents = ['add', 'unlink', 'change'] as const;
      for (const event of watcherEvents) {
        server.watcher.on(event, (f) => {
          try {
            if (isPageFile(f)) {
              scheduleRegen(server, event === 'add' ? 300 : DEBOUNCE_MS);
            }
          } catch (error) {
            viteErrorLog(`Error handling file ${event}: ${error instanceof Error ? error.message : String(error)}`);
          }
        });
      }

      server.watcher.on('change', (f) => {
        try {
          const base = path.basename(f, path.extname(f));
          const inAppRoot = path.resolve(path.dirname(f)) === path.resolve(appDir);
          if (inAppRoot && base === 'layout') {
            server.moduleGraph.invalidateAll();
            server.ws.send({ type: 'full-reload', path: '*' });
          }
        } catch (error) {
          viteErrorLog(`Error handling layout change: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      server.watcher.on('addDir', (d) => {
        try {
          const nd = norm(d);
          if (nd === norm(apiDir)) {
            cachedApiDirExists = true;
          }
          if (!isInDir(nd, norm(appDir)) || d.includes('node_modules') || isInDir(nd, norm(apiDir))) return;
          server.watcher.add(d);
          setTimeout(() => {
            if (PAGE_FILES.some(f => fs.existsSync(path.join(d, f)))) {
              scheduleRegen(server, 300);
            }
          }, 300);
        } catch (error) {
          viteErrorLog(`Error handling directory add: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      server.watcher.on('unlinkDir', (d) => {
        try {
          const nd = norm(d);
          if (nd === norm(apiDir)) {
            cachedApiDirExists = false;
            apiRouteCache = null;
            return;
          }
          if (isInDir(nd, norm(appDir)) && !d.includes('node_modules') && !isInDir(nd, norm(apiDir))) {
            scheduleRegen(server);
          }
        } catch (error) {
          viteErrorLog(`Error handling directory unlink: ${error instanceof Error ? error.message : String(error)}`);
        }
      });

      const apiParent = path.dirname(apiDir);
      if (fs.existsSync(apiParent)) {
        server.watcher.add(apiParent);

        server.watcher.on('addDir', (d) => {
          const nd = norm(d);
          if (nd === norm(apiDir)) {
            server.watcher.add(apiDir);
            apiRouteCache = null;
            cachedApiDirExists = true;
            viteLog(apiDir, 'api directory created');
          }
        });
      }

      if (fs.existsSync(apiDir)) {
        server.watcher.add(apiDir);

        const resetApi = (f?: string, event?: string): void => {
          apiRouteCache = null;
          if (f) moduleCache.delete(f);
          if (f) viteLog(f, event === 'add' ? 'api route added' : event === 'unlink' ? 'api route removed' : 'hmr update');
          if (event === 'add' || event === 'unlink') {
            server.ws.send({ type: 'full-reload', path: '*' });
          }
        };

        server.watcher.on('add', (f) => {
          if (isApiFile(f)) resetApi(f, 'add');
        });

        server.watcher.on('unlink', (f) => {
          if (isApiFile(f)) resetApi(f, 'unlink');
        });

        server.watcher.on('change', (f) => {
          if (isApiFile(f)) resetApi(f, 'change');
        });
      }

      server.middlewares.use(createApiMiddleware(server));
    },

    async configurePreviewServer(server): Promise<void> {
      cachedApiDirExists = fs.existsSync(getApiDir());
      server.middlewares.use(createApiMiddleware(null));
    },

    resolveId(id) {
      if (id === VIRTUAL_ROUTES_ID || id === RESOLVED_VIRTUAL_ROUTES_ID) {
        return RESOLVED_VIRTUAL_ROUTES_ID;
      }
      return null;
    },

    load(id) {
      if (id === RESOLVED_VIRTUAL_ROUTES_ID) {
        const appDir = getAppDir();
        const apiDir = getApiDir();
        return getRouteManifestModule(appDir, apiDir, strictMode);
      }
      return null;
    },
  };

  const mdxPlugin = mdx({
    jsxImportSource: 'react',
    mdExtensions: [],
    mdxExtensions: ['.mdx', '.md'],
    ...options.mdx,
  }) as unknown as Plugin;

  return [routerPlugin, mdxPlugin];
}

