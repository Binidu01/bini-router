export function deriveBase(configBase: string, command: 'serve' | 'build'): {
  raw: string; assetBase: string; routerBasename: string; apiPrefix: string; runtimeBasename: boolean;
} {
  const raw = configBase ?? '/';
  if (raw === '' || raw === './' || raw === '.') {
    return { raw, assetBase: './', routerBasename: '/', apiPrefix: '/', runtimeBasename: true };
  }
  if (/^https?:\/\//i.test(raw)) {
    try {
      const u = new URL(raw);
      const pathname = u.pathname.replace(/\/+$/, '') || '/';
      const assetBase = command === 'build' ? raw.replace(/\/?$/, '/') : (pathname.endsWith('/') ? pathname : pathname + '/');
      return {
        raw, assetBase,
        routerBasename: pathname === '/' ? '/' : pathname.replace(/\/$/, ''),
        apiPrefix: pathname === '/' ? '/' : pathname.replace(/\/$/, ''),
        runtimeBasename: false,
      };
    } catch { /* fall through */ }
  }
  let pathname = raw.startsWith('/') ? raw : '/' + raw;
  pathname = pathname.replace(/\/+$/, '') || '/';
  const withSlash = pathname.endsWith('/') ? pathname : pathname + '/';
  return { raw, assetBase: withSlash, routerBasename: pathname, apiPrefix: pathname, runtimeBasename: false };
}

