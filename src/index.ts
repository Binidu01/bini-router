function hashSource(source: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < source.length; i++) {
    h ^= source.charCodeAt(i);
    h = (h * 0x01000193) >>> 0;
  }
  return h.toString(36) + ':' + source.length.toString(36);
}

