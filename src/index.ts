const LOG_PREFIX = '\x1b[36m[bini-router]\x1b[0m';

const warnedFiles = new Map<string, number>();

function warnOnce(filePath: string, mtimeMs: number, message: string): void {
  if (warnedFiles.get(filePath) === mtimeMs) return;
  warnedFiles.set(filePath, mtimeMs);
  viteWarnLog(message);
}

const warnedMessages = new Set<string>();

function warnOnceMsg(message: string): void {
  if (warnedMessages.has(message)) return;
  warnedMessages.add(message);
  viteWarnLog(message);
}

function viteLog(filePath: string, event = 'hmr update'): void {
  const time = new Date().toLocaleTimeString();
  const relativePath = toPosixPath(path.relative(process.cwd(), filePath));
  console.log(`\x1b[90m${time}\x1b[0m ${LOG_PREFIX} \x1b[32m${event}\x1b[0m \x1b[90m${relativePath}\x1b[0m`);
}

function viteErrorLog(message: string): void {
  const time = new Date().toLocaleTimeString();
  console.error(`\x1b[90m${time}\x1b[0m ${LOG_PREFIX} \x1b[31m${message}\x1b[0m`);
}

function viteWarnLog(message: string): void {
  const time = new Date().toLocaleTimeString();
  console.warn(`\x1b[90m${time}\x1b[0m ${LOG_PREFIX} \x1b[33m${message}\x1b[0m`);
}

// ─── Utilities ────────────────────────────────────────────────────────────────

function toPosixPath(filePath: string): string {
  return filePath.replace(/\\/g, '/');
}

function norm(p: string): string {
  return p.replace(/\\/g, '/');
}

function isInDir(file: string, dir: string): boolean {
  const nFile = norm(file);
  const nDir = norm(dir).replace(/\/$/, '');
  return nFile.startsWith(nDir + '/') || nFile === nDir;
}

function withBase(url: string, base: string): string {
  if (!url) return url;
  if (/^([a-z][a-z0-9+.-]*:)?\/\//i.test(url) || url.startsWith('data:')) return url;
  if (!url.startsWith('/')) return url;
  const b = base.endsWith('/') ? base.slice(0, -1) : base;
  return `${b}${url}`;
}

function cmpStr(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function toBasename(base: string | undefined, isOption = false): string {
  if (!base || base === '.' || base === './') return '/';

  if (!isOption) {
    if (!base.startsWith('/') || base.startsWith('//')) return '/';
  }

  const p = base.startsWith('/') ? base : '/' + base;
  return p.length > 1 && p.endsWith('/') ? p.slice(0, -1) : p;
}

function basePrefixOf(base: string): string {
  if (!base || base === '/' || base === '.' || base === './') return '';
  if (!base.startsWith('/') || base.startsWith('//')) return '';
  return base.endsWith('/') ? base.slice(0, -1) : base;
}

function isApiPath(url: string): boolean {
  return /^\/api(?=[/?]|$)/.test(url);
}

function stripApiPrefix(url: string): string {
  const rest = url.replace(/^\/api(?=[/?]|$)/, '');
  if (rest === '') return '/';
  if (rest.startsWith('?')) return '/' + rest;
  return rest;
}

