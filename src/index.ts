function collectModuleScopeNames(program: any): Set<string> {
  const names = new Set<string>();

  for (const stmt of program.body ?? []) {
    const target =
      stmt.type === 'ExportNamedDeclaration' || stmt.type === 'ExportDefaultDeclaration'
        ? stmt.declaration ?? stmt
        : stmt;

    if (target.type === 'VariableDeclaration') {
      for (const d of target.declarations ?? []) collectPatternNames(d.id, names);
    } else if (target.type === 'FunctionDeclaration' || target.type === 'ClassDeclaration') {
      if (target.id?.name) names.add(target.id.name);
    }

    if (stmt.type === 'ImportDeclaration') {
      for (const spec of stmt.specifiers ?? []) {
        if (spec.local?.name) names.add(spec.local.name);
      }
    }
  }

  const FUNCTION_BOUNDARIES = new Set([
    'FunctionDeclaration', 'FunctionExpression', 'ArrowFunctionExpression',
    'ClassDeclaration', 'ClassExpression', 'StaticBlock',
  ]);

  const walkVar = (node: any): void => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) {
      for (const child of node) walkVar(child);
      return;
    }
    if (typeof node.type !== 'string') return;
    if (FUNCTION_BOUNDARIES.has(node.type)) return;

    if (node.type === 'VariableDeclaration' && node.kind === 'var') {
      for (const d of node.declarations ?? []) collectPatternNames(d.id, names);
    }

    for (const key of Object.keys(node)) {
      if (key === 'type' || key === 'start' || key === 'end' || key === 'loc' || key === 'range') continue;
      if (key === 'params') continue;
      const v = node[key];
      if (v && typeof v === 'object') walkVar(v);
    }
  };
  walkVar(program);

  return names;
}

function injectAutoImports(parsed: ParsedFile, source: string): string {
  const existingImports = new Map<string, Set<string>>();

  walk(parsed.program, (node) => {
    if (node.type === 'ImportDeclaration') {
      const mod = node.source?.value;
      if (typeof mod === 'string') {
        const set = existingImports.get(mod) ?? new Set<string>();
        for (const spec of node.specifiers ?? []) {
          if (spec.imported?.name) set.add(spec.imported.name);
        }
        existingImports.set(mod, set);
      }
      return false;
    }
    return undefined;
  });

  const declared = collectModuleScopeNames(parsed.program);

  const referenced = new Set<string>();
  walkReferences(parsed.program, referenced);

  const injected: string[] = [];
  for (const { module, names } of getAutoImports()) {
    const already = existingImports.get(module) ?? new Set<string>();
    const needed = names.filter(
      (n) => referenced.has(n) && !declared.has(n) && !already.has(n),
    );
    if (needed.length) {
      injected.push(`import { ${needed.join(', ')} } from '${module}';`);
    }
  }

  if (injected.length === 0) return source;

  const blockEnd = findDirectiveBlockEnd(parsed, source);
  const prefix = source.slice(0, blockEnd);
  const rest = source.slice(blockEnd);

  const needsNewline = prefix.length > 0 && !prefix.endsWith('\n');
  return `${prefix}${needsNewline ? '\n' : ''}${injected.join('\n')}\n${rest}`;
}

function collectPatternNames(node: any, out: Set<string>): void {
  if (!node) return;
  switch (node.type) {
    case 'Identifier':
      out.add(node.name);
      break;
    case 'ObjectPattern':
      for (const prop of node.properties ?? []) {
        if (prop.type === 'RestElement') collectPatternNames(prop.argument, out);
        else collectPatternNames(prop.value, out);
      }
      break;
    case 'ArrayPattern':
      for (const el of node.elements ?? []) collectPatternNames(el, out);
      break;
    case 'AssignmentPattern':
      collectPatternNames(node.left, out);
      break;
    case 'RestElement':
      collectPatternNames(node.argument, out);
      break;
  }
}

function walkReferences(
  node: any,
  out: Set<string>,
  parent: any = null,
  key: string | null = null,
): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (const child of node) walkReferences(child, out, parent, key);
    return;
  }
  if (typeof node.type !== 'string') return;

  if (parent?.type === 'JSXAttribute' && key === 'name') return;
  if (parent?.type === 'JSXMemberExpression' && key === 'property') return;

  if (node.type === 'JSXIdentifier') {
    if (typeof node.name === 'string') out.add(node.name);
    return;
  }

  if (node.type === 'Identifier') {
    if (isReference(node, parent, key)) out.add(node.name);
    return;
  }

  for (const k of Object.keys(node)) {
    if (k === 'type' || k === 'start' || k === 'end' || k === 'loc' || k === 'range') continue;
    if (k === 'params') continue;
    const value = node[k];
    if (value && typeof value === 'object') walkReferences(value, out, node, k);
  }
}

function isReference(node: any, parent: any, key: string | null): boolean {
  if (!parent) return true;

  if (
    (parent.type === 'VariableDeclarator' && key === 'id') ||
    (parent.type === 'FunctionDeclaration' && key === 'id') ||
    (parent.type === 'FunctionExpression' && key === 'id') ||
    (parent.type === 'ClassDeclaration' && key === 'id') ||
    (parent.type === 'ClassExpression' && key === 'id') ||
    (parent.type === 'ImportDefaultSpecifier' && key === 'local') ||
    (parent.type === 'ImportNamespaceSpecifier' && key === 'local') ||
    (parent.type === 'ImportSpecifier' && key === 'local') ||
    ((parent.type === 'FunctionDeclaration' ||
      parent.type === 'FunctionExpression' ||
      parent.type === 'ArrowFunctionExpression') && key === 'params')
  ) {
    return false;
  }

  if (parent.type === 'Property' && key === 'key' && !parent.computed) return false;
  if (parent.type === 'MemberExpression' && key === 'property' && !parent.computed) return false;
  if (parent.type === 'JSXAttribute' && key === 'name') return false;
  if (
    (parent.type === 'LabeledStatement' ||
      parent.type === 'BreakStatement' ||
      parent.type === 'ContinueStatement') &&
    key === 'label'
  ) return false;

  return true;
}

function stripAppExports(source: string, parsed: ParsedFile): string {
  const ranges: { start: number; end: number }[] = [];
  for (const name of ['metadata', 'document'] as const) {
    const r = getExportRange(parsed, name);
    if (r) ranges.push(r);
  }
  if (ranges.length === 0) return source;

  ranges.sort((a, b) => b.start - a.start);

  let result = source;
  for (const r of ranges) {
    const newlineCount = countNewlines(result, r.start, r.end);
    result = result.slice(0, r.start) + '\n'.repeat(newlineCount) + result.slice(r.end);
  }
  return result;
}

// ─── API route scanning ────────────────────────────────────────────────────

function apiCatchallDirHasNestedRoutes(dir: string): boolean {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return false;
  }
  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (apiCatchallDirHasNestedRoutes(fullPath)) return true;
    } else {
      const ext = path.extname(entry.name);
      if (!(API_EXTS as readonly string[]).includes(ext)) continue;
      const base = path.basename(entry.name, ext);
      if (base === 'index' || base === 'route') continue;
      return true;
    }
  }
  return false;
}

function scanApiRoutes(dir: string, baseRoute = '', depth = 0): ApiRoute[] {
  if (depth > MAX_DEPTH) {
    viteWarnLog(`Maximum API directory depth reached at ${dir}`);
    return [];
  }

  const routes: ApiRoute[] = [];
  if (!fs.existsSync(dir)) return routes;

  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (error) {
    viteErrorLog(`Failed to read API directory ${dir}: ${error instanceof Error ? error.message : String(error)}`);
    return routes;
  }

  entries.sort((a, b) => cmpStr(a.name, b.name));

  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      const isGroup = isRouteGroup(entry.name);
      const isOptionalCatchAll = entry.name.startsWith('[[...') && entry.name.endsWith(']]');
      const isCatchAll = !isOptionalCatchAll && entry.name.startsWith('[...') && entry.name.endsWith(']');
      const isDynamic = !isCatchAll && !isOptionalCatchAll && entry.name.startsWith('[') && entry.name.endsWith(']');

      let segment: string;
      let dirCatchallParamName: string | undefined;

      if (isGroup) {
        segment = '';
      } else if (isOptionalCatchAll) {
        const name = entry.name.slice(5, -2);
        if (!isValidParamName(name)) {
          viteWarnLog(`Invalid API parameter name: ${name}`);
          continue;
        }
        dirCatchallParamName = name;
        segment = '**';
      } else if (isCatchAll) {
        const name = entry.name.slice(4, -1);
        if (!isValidParamName(name)) {
          viteWarnLog(`Invalid API parameter name: ${name}`);
          continue;
        }
        dirCatchallParamName = name;
        segment = '*';
      } else if (isDynamic) {
        const paramName = entry.name.slice(1, -1);
        if (!isValidParamName(paramName)) {
          viteWarnLog(`Invalid API parameter name: ${paramName}`);
          continue;
        }
        segment = `:${paramName}`;
      } else {
        if (!isValidRouteSegment(entry.name)) {
          viteWarnLog(`Invalid API directory name: ${entry.name}`);
          continue;
        }
        segment = entry.name;
      }

      const nextBase = segment ? `${baseRoute}/${segment}` : baseRoute;

      if (dirCatchallParamName && apiCatchallDirHasNestedRoutes(fullPath)) {
        viteWarnLog(
          `Skipping nested routes under catch-all directory ${entry.name} in ${dir}: ` +
          `a catch-all segment must be the last path segment. Move these files out ` +
          `of the catch-all directory, or rename the directory to a non-catch-all.`
        );
        continue;
      }

      const childRoutes = scanApiRoutes(fullPath, nextBase, depth + 1);

      if (dirCatchallParamName) {
        for (const cr of childRoutes) {
          if (!cr.catchallParamName && cr.routePath.includes('*')) {
            routes.push({ ...cr, catchallParamName: dirCatchallParamName });
          } else {
            routes.push(cr);
          }
        }
      } else {
        routes.push(...childRoutes);
      }
      continue;
    }

    const ext = path.extname(entry.name);
    const base = path.basename(entry.name, ext);
    if (!(API_EXTS as readonly string[]).includes(ext)) continue;

    const isRouteFile = base === 'route';
    const isIndexFile = base === 'index';
    const isBareRoute = !isRouteFile && !isIndexFile;

    if (isRouteFile) {
      const sibling = (API_EXTS as readonly string[]).find(
        e => fs.existsSync(path.join(dir, `index${e}`))
      );
      if (sibling) {
        warnOnceMsg(`Both route.* and index.* found in ${dir}; using route.*`);
      }
    }

    const isOptionalCatchAll = isBareRoute && base.startsWith('[[...') && base.endsWith(']]');
    const isCatchAll = isBareRoute && !isOptionalCatchAll && base.startsWith('[...') && base.endsWith(']');
    const isDynamic = isBareRoute && !isCatchAll && !isOptionalCatchAll && base.startsWith('[') && base.endsWith(']');

    let catchallParamName: string | undefined;
    let rawRoutePath: string;

    if (isRouteFile || isIndexFile) {
      rawRoutePath = baseRoute || '/';
    } else if (isOptionalCatchAll) {
      const name = base.slice(5, -2);
      if (!isValidParamName(name)) {
        viteWarnLog(`Invalid API parameter name: ${name}`);
        continue;
      }
      catchallParamName = name;
      rawRoutePath = `${baseRoute}/**`;
    } else if (isCatchAll) {
      const name = base.slice(4, -1);
      if (!isValidParamName(name)) {
        viteWarnLog(`Invalid API parameter name: ${name}`);
        continue;
      }
      catchallParamName = name;
      rawRoutePath = `${baseRoute}/*`;
    } else if (isDynamic) {
      const paramName = base.slice(1, -1);
      if (!isValidParamName(paramName)) {
        viteWarnLog(`Invalid API parameter name: ${paramName}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/:${paramName}`;
    } else {
      if (!isValidRouteSegment(base)) {
        viteWarnLog(`Invalid API route name: ${base}`);
        continue;
      }
      rawRoutePath = `${baseRoute}/${base}`;
    }

    const routePath = normalizeRoutePath(rawRoutePath);
    routes.push({ routePath, filePath: fullPath, catchallParamName });
  }

  routes.sort((a, b) => {
    const aCatch = a.routePath.includes('*') ? 1 : 0;
    const bCatch = b.routePath.includes('*') ? 1 : 0;
    if (aCatch !== bCatch) return aCatch - bCatch;
    const aDyn = a.routePath.includes(':') ? 1 : 0;
    const bDyn = b.routePath.includes(':') ? 1 : 0;
    if (aDyn !== bDyn) return aDyn - bDyn;
    return b.routePath.length - a.routePath.length;
  });

  return routes;
}

