function mergeAttrs(
  existingAttrs: string,
  newAttrs: Record<string, unknown> | undefined,
): string {
  if (!newAttrs || Object.keys(newAttrs).length === 0) return existingAttrs;

  const parsed = new Map<string, string>();
  const re = /([a-zA-Z_:][-a-zA-Z0-9_:.]*)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(existingAttrs)) !== null) {
    const name = m[1].toLowerCase();
    const value = m[2] ?? m[3] ?? m[4] ?? '';
    parsed.set(name, decodeHtmlEntities(value));
  }

  for (const [k, v] of Object.entries(newAttrs)) {
    const key = k.toLowerCase();
    if (v === false || v === null || v === undefined) {
      parsed.delete(key);
      continue;
    }
    if (v === true) {
      parsed.set(key, '');
      continue;
    }

    const strVal = typeof v === 'string' ? v : String(v);

    if (key === 'class' && parsed.has('class') && strVal) {
      const existing = parsed.get('class') ?? '';
      parsed.set('class', existing ? `${existing} ${strVal}` : strVal);
    } else {
      parsed.set(key, strVal);
    }
  }

  const out: string[] = [];
  for (const [k, v] of parsed) {
    if (v === '') out.push(k);
    else out.push(`${k}="${escapeHtmlAttr(v)}"`);
  }
  return out.length ? ' ' + out.join(' ') : '';
}

function headTag(
  tag: string,
  attrs: Record<string, string>,
  injectTo: 'head' | 'head-prepend' | 'body' | 'body-prepend' = 'head-prepend',
): HtmlTagDescriptor {
  const escaped: Record<string, string> = {};
  for (const [k, v] of Object.entries(attrs)) {
    escaped[k] = escapeHtmlAttr(v);
  }
  return { tag, attrs: escaped, injectTo };
}

function stripMetaByName(html: string, name: string): string {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`<meta\\s+[^>]*name\\s*=\\s*['"]${escaped}['"][^>]*\\/?>`, 'gi');
  return html.replace(re, '');
}

function stripLinkByRel(html: string, rel: string): string {
  const escaped = rel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`<link\\s+[^>]*rel\\s*=\\s*['"]${escaped}['"][^>]*\\/?>`, 'gi');
  return html.replace(re, '');
}

/**
 * Given an incoming request URL and Vite's base, determines whether the
 * request is for the API and strips both prefixes so the router sees a
 * path relative to `apiDir`.
 */
function resolveApiPath(reqUrl: string, base: string): string | null {
  const basePrefix = basePrefixOf(base);

  if (isApiPath(reqUrl)) {
    return stripApiPrefix(reqUrl);
  }

  if (basePrefix && reqUrl.startsWith(basePrefix + '/api')) {
    const afterBase = reqUrl.slice(basePrefix.length);
    if (isApiPath(afterBase)) {
      return stripApiPrefix(afterBase);
    }
  }

  return null;
}

