function getRouteManifestModule(appDir: string, apiDir: string): string {
  const full = buildRouteManifestInternal(appDir, apiDir);
  const safeMetadata: Record<string, any> = {};
  for (const [k, v] of Object.entries(full.metadata)) {
    safeMetadata[k] = {
      title: v.title, dynamic: v.dynamic,
      ...(v.catchallParamName ? { catchallParamName: v.catchallParamName } : {}),
      ...(v.loader ? { loader: true } : {}), ...(v.action ? { action: true } : {}),
      ...(v.shouldRevalidate ? { shouldRevalidate: true } : {}), ...(v.errorBoundary ? { errorBoundary: true } : {}),
      ...(v.hydrateFallback ? { hydrateFallback: true } : {}), ...(v.handle ? { handle: true } : {}),
    };
  }
  const manifest = { static: full.static, dynamic: full.dynamic, all: full.all, metadata: safeMetadata };
  return `
    export const staticRoutes = ${JSON.stringify(manifest.static)};
    export const dynamicRoutes = ${JSON.stringify(manifest.dynamic)};
    export const allRoutes = ${JSON.stringify(manifest.all)};
    export const routeMetadata = ${JSON.stringify(manifest.metadata)};
    export default ${JSON.stringify(manifest)};
  `;
}

