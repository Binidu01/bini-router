// ─── Transform Helpers ───────────────────────────────────────────────────────

function findDirectiveBlockEnd(parsed: ParsedFile, source: string): number {
  let insertAt = 0;

  if (source.startsWith('#!')) {
    const nl = source.indexOf('\n');
    insertAt = nl === -1 ? source.length : nl + 1;
  }

  const body: any[] = parsed.program.body ?? [];
  let lastDirectiveEnd = insertAt;
  let sawDirective = false;

  for (const stmt of body) {
    if (
      stmt.type === 'ExpressionStatement' &&
      stmt.expression?.type === 'Literal' &&
      typeof stmt.expression.value === 'string'
    ) {
      lastDirectiveEnd = Math.max(lastDirectiveEnd, stmt.end);
      sawDirective = true;
      continue;
    }
    break;
  }

  if (!sawDirective) return insertAt;

  insertAt = lastDirectiveEnd;
  const nextStmtStart = body.find(s => s.start >= insertAt)?.start ?? source.length;
  const comments: any[] = parsed.comments ?? [];

  let changed = true;
  while (changed) {
    changed = false;
    for (const c of comments) {
      if (c.start < insertAt) continue;
      if (c.start > nextStmtStart) continue;
      let onlyWs = true;
      for (let i = insertAt; i < c.start; i++) {
        const ch = source[i];
        if (ch !== ' ' && ch !== '\t' && ch !== '\n' && ch !== '\r') { onlyWs = false; break; }
      }
      if (onlyWs) {
        insertAt = Math.max(insertAt, c.end);
        changed = true;
      }
    }
  }

  while (insertAt < source.length) {
    const ch = source[insertAt];
    if (ch === ' ' || ch === '\t' || ch === '\n' || ch === '\r') insertAt++;
    else break;
  }

  return insertAt;
}

