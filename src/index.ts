function warnFileTooLarge(filePath: string): void {
  warnOnceMsg(
    `Skipping ${toPosixPath(path.relative(process.cwd(), filePath))}: file exceeds ${MAX_FILE_SIZE / 1024 / 1024}MB limit`
  );
}

function warnDynamicHeadContent(filePath: string, context: string): void {
  const key = `${filePath}::dynamic-head`;
  if (dynamicHeadWarned.has(key)) return;
  dynamicHeadWarned.add(key);
  viteWarnLog(
    `bini-router: dynamic value in \`export const document.head\` (${context}) in ${toPosixPath(path.relative(process.cwd(), filePath))} was dropped during metadata extraction. Only literal strings and template literals without expressions are supported.`
  );
}

// ─── Parser ────────────────────────────────────────────────────────────────

const OXC_LANG_BY_EXT: Record<string, 'js' | 'jsx' | 'ts' | 'tsx'> = {
  '.js': 'js',
  '.jsx': 'jsx',
  '.ts': 'ts',
  '.tsx': 'tsx',
  '.mdx': 'tsx',
  '.md': 'tsx',
};

interface ParsedFile {
  program: any;
  comments: any[];
  synthetic?: boolean;
}

function isFatalError(err: any): boolean {
  if (!err || typeof err !== 'object') return true;
  if ('severity' in err && err.severity !== undefined) {
    const sev = String(err.severity).toLowerCase();
    return sev === 'error' || sev === '1';
  }
  return true;
}

function parseFile(source: string, filePath: string): ParsedFile | null {
  const hash = hashSource(source);
  const hit = parsedFileCache.get(filePath);
  if (hit && hit.hash === hash) return hit.parsed;

  const ext = path.extname(filePath);
  const lang = OXC_LANG_BY_EXT[ext] ?? 'tsx';
  let result: ParsedFile | null = null;

  try {
    const parsed = parseSync(filePath, source, { lang, sourceType: 'module' });
    if (parsed) {
      const errors = (parsed.errors ?? []).filter(isFatalError);
      if (errors.length > 0) {
        let mtimeMs = 0;
        try { mtimeMs = fs.statSync(filePath).mtimeMs; } catch {}
        warnOnce(filePath, mtimeMs,
          `Oxc parse errors in ${filePath}: ${errors.slice(0, 3).map((e: any) => e.message ?? String(e)).join('; ')}`);
      } else if (parsed.program) {
        result = { program: parsed.program, comments: parsed.comments ?? [] };
      }
    }
  } catch (error) {
    let mtimeMs = 0;
    try { mtimeMs = fs.statSync(filePath).mtimeMs; } catch {}
    warnOnce(filePath, mtimeMs,
      `Oxc parse failed for ${filePath}: ${error instanceof Error ? error.message : String(error)}`);
  }

  if (parsedFileCache.size >= PARSED_CACHE_MAX) parsedFileCache.clear();
  parsedFileCache.set(filePath, { hash, parsed: result });
  return result;
}

// ─── AST walkers ───────────────────────────────────────────────────────────

function walk(
  node: any,
  enter: (n: any, parent: any, key: string | null) => boolean | void,
  parent: any = null,
  key: string | null = null,
): void {
  if (!node || typeof node !== 'object') return;
  if (Array.isArray(node)) {
    for (let i = 0; i < node.length; i++) walk(node[i], enter, parent, String(i));
    return;
  }
  if (typeof node.type === 'string') {
    const result = enter(node, parent, key);
    if (result === false) return;
  }
  for (const k of Object.keys(node)) {
    if (k === 'type' || k === 'start' || k === 'end' || k === 'loc' || k === 'range') continue;
    const v = node[k];
    if (v && typeof v === 'object') walk(v, enter, node, k);
  }
}

function nodeToValue(node: any): unknown {
  if (!node || typeof node !== 'object') return undefined;
  switch (node.type) {
    case 'Literal': return node.value;
    case 'TemplateLiteral': {
      if (node.expressions && node.expressions.length > 0) return undefined;
      return (node.quasis ?? []).map((q: any) => q.value?.cooked ?? q.value?.raw ?? '').join('');
    }
    case 'ArrayExpression':
      return (node.elements ?? [])
        .map((el: any) => (el && el.type !== 'SpreadElement' ? nodeToValue(el) : undefined))
        .filter((v: unknown) => v !== undefined);
    case 'ObjectExpression': {
      const obj: Record<string, unknown> = {};
      for (const prop of node.properties ?? []) {
        if (prop.type !== 'Property') continue;
        if (prop.computed) continue;
        const key = prop.key?.type === 'Identifier'
          ? prop.key.name
          : prop.key?.type === 'Literal'
            ? String(prop.key.value)
            : undefined;
        if (key === undefined) continue;
        if (key === '__proto__' || key === 'constructor' || key === 'prototype') continue;
        obj[key] = nodeToValue(prop.value);
      }
      return obj;
    }
    case 'TSAsExpression':
    case 'TSSatisfiesExpression':
    case 'TSTypeAssertion':
    case 'TSNonNullExpression':
    case 'ParenthesizedExpression':
      return nodeToValue(node.expression);
    default: return undefined;
  }
}

function getNamedExportObject(parsed: ParsedFile, name: string): Record<string, unknown> | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (decl && decl.type === 'VariableDeclaration') {
      for (const d of decl.declarations ?? []) {
        if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
        const value = nodeToValue(d.init);
        if (value && typeof value === 'object' && !Array.isArray(value)) {
          return value as Record<string, unknown>;
        }
        return null;
      }
    }
    if (Array.isArray(stmt.specifiers)) {
      for (const spec of stmt.specifiers) {
        if (spec.exported?.name !== name) continue;
        const local = spec.local?.name;
        if (!local) continue;
        const resolved = findLocalBindingObject(parsed, local);
        if (resolved) return resolved;
      }
    }
  }
  return null;
}

function getExportLiteral(parsed: ParsedFile, name: string): unknown {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;
    for (const d of decl.declarations ?? []) {
      if (d.id?.type === 'Identifier' && d.id.name === name) return nodeToValue(d.init);
    }
  }
  return undefined;
}

function findLocalBindingObject(parsed: ParsedFile, local: string): Record<string, unknown> | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'VariableDeclaration') continue;
    for (const d of stmt.declarations ?? []) {
      if (d.id?.type !== 'Identifier' || d.id.name !== local) continue;
      const value = nodeToValue(d.init);
      if (value && typeof value === 'object' && !Array.isArray(value)) {
        return value as Record<string, unknown>;
      }
      return null;
    }
  }
  return null;
}

function getExportRange(parsed: ParsedFile, name: string): { start: number; end: number } | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;
    for (const d of decl.declarations ?? []) {
      if (d.id?.type === 'Identifier' && d.id.name === name) {
        return { start: stmt.start, end: stmt.end };
      }
    }
  }
  return null;
}

function unwrapExpression(node: any): any {
  if (!node) return node;
  switch (node.type) {
    case 'ParenthesizedExpression':
    case 'TSAsExpression':
    case 'TSSatisfiesExpression':
    case 'TSTypeAssertion':
    case 'TSNonNullExpression':
      return unwrapExpression(node.expression);
    default: return node;
  }
}

function jsxAttrToEntry(attr: any, filePath: string): [string, string] | null {
  if (!attr || attr.type !== 'JSXAttribute') return null;
  const name = attr.name?.name;
  if (!name) return null;

  const htmlName = JSX_ATTR_TO_HTML[name] ?? name;

  if (!attr.value) return [htmlName, ''];

  if (attr.value.type === 'Literal') {
    if (attr.value.value === true) return [htmlName, ''];
    if (attr.value.value === false || attr.value.value == null) return null;
    return [htmlName, String(attr.value.value)];
  }

  if (attr.value.type === 'JSXExpressionContainer') {
    const expr = attr.value.expression;
    if (expr?.type === 'Literal') {
      if (expr.value === true) return [htmlName, ''];
      if (expr.value === false || expr.value == null) return null;
      return [htmlName, String(expr.value)];
    }
    if (expr?.type === 'TemplateLiteral' && (!expr.expressions || expr.expressions.length === 0)) {
      const value = (expr.quasis ?? [])
        .map((q: any) => q.value?.cooked ?? q.value?.raw ?? '')
        .join('');
      return [htmlName, value];
    }
    warnDynamicHeadContent(filePath, `attribute \`${htmlName}\``);
    return null;
  }

  return null;
}

function jsxNodeToStructure(node: any, filePath: string): HeadNode[] {
  if (!node) return [];

  switch (node.type) {
    case 'JSXFragment': {
      return (node.children ?? []).flatMap((c: any) => jsxNodeToStructure(c, filePath));
    }
    case 'JSXElement': {
      const opening = node.openingElement;
      const tag = opening?.name?.name;
      if (!tag) return [];

      const attrs: Record<string, string> = {};
      for (const a of opening?.attributes ?? []) {
        const entry = jsxAttrToEntry(a, filePath);
        if (entry) attrs[entry[0]] = entry[1];
      }

      const children = (node.children ?? []).flatMap((c: any) => jsxNodeToStructure(c, filePath));
      return [{ t: 'element', tag, attrs, children }];
    }
    case 'JSXText': {
      const raw = node.value ?? '';
      if (!raw.trim()) return [];
      return [{ t: 'text', value: raw }];
    }
    case 'JSXExpressionContainer': {
      const expr = node.expression;
      if (!expr) return [];
      if (expr.type === 'Literal' && typeof expr.value === 'string') {
        return [{ t: 'text', value: expr.value }];
      }
      if (expr.type === 'TemplateLiteral' && (!expr.expressions || expr.expressions.length === 0)) {
        const value = (expr.quasis ?? [])
          .map((q: any) => q.value?.cooked ?? q.value?.raw ?? '')
          .join('');
        return [{ t: 'text', value }];
      }
      warnDynamicHeadContent(filePath, 'child expression');
      return [];
    }
    case 'Literal':
      return typeof node.value === 'string' ? [{ t: 'text', value: node.value }] : [];
    default:
      return [];
  }
}

function getJsxPropertyStructure(
  parsed: ParsedFile,
  name: string,
  propertyName: string,
  filePath: string,
): HeadNode[] | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;

    for (const d of decl.declarations ?? []) {
      if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
      if (!d.init || d.init.type !== 'ObjectExpression') return null;

      for (const prop of d.init.properties ?? []) {
        if (prop.type !== 'Property') continue;
        if (prop.computed) continue;

        const key = prop.key?.type === 'Identifier'
          ? prop.key.name
          : prop.key?.type === 'Literal'
            ? String(prop.key.value)
            : undefined;

        if (key !== propertyName) continue;

        return jsxNodeToStructure(unwrapExpression(prop.value), filePath);
      }
      return null;
    }
  }
  return null;
}

function extractMetadataFromParsed(parsed: ParsedFile): Record<string, unknown> | null {
  if (parsed.synthetic) return null;
  return getNamedExportObject(parsed, 'metadata');
}

function extractDocumentFromParsed(
  filePath: string,
  parsed: ParsedFile,
): RouteDocument | null {
  const ext = path.extname(filePath);
  if (ext === '.mdx' || ext === '.md') return null;
  if (parsed.synthetic) return null;

  const raw = getNamedExportObject(parsed, 'document');
  if (!raw) return null;

  const head = getJsxPropertyStructure(parsed, 'document', 'head', filePath);

  const html = (raw.html && typeof raw.html === 'object' && !Array.isArray(raw.html))
    ? raw.html as Record<string, string>
    : undefined;
  const body = (raw.body && typeof raw.body === 'object' && !Array.isArray(raw.body))
    ? raw.body as Record<string, string>
    : undefined;

  return { html, body, head: head ?? undefined };
}

function extractCssFromParsed(filePath: string, parsed: ParsedFile): string[] {
  const ext = path.extname(filePath);
  if (ext === '.mdx' || ext === '.md') return [];
  if (parsed.synthetic) return [];

  const css: string[] = [];
  const seen = new Set<string>();

  walk(parsed.program, (node) => {
    if (node.type !== 'ImportDeclaration') return;
    const source = node.source?.value;
    if (typeof source !== 'string') return;
    if (!CSS_EXT_PATTERN.test(source)) return;

    const resolved = path.resolve(path.dirname(filePath), source);
    if (!seen.has(resolved)) {
      seen.add(resolved);
      css.push(resolved);
    }
  });

  return css;
}

function resolveTitleFromChain(
  pageMeta: Record<string, unknown> | null,
  layoutMetas: (Record<string, unknown> | null)[],
): string | null {
  const pageTitle = pageMeta?.title;

  let template: string | null = null;
  for (let i = layoutMetas.length - 1; i >= 0; i--) {
    const t = layoutMetas[i]?.title;
    if (t && typeof t === 'object' && !Array.isArray(t)) {
      const obj = t as any;
      if (typeof obj.template === 'string') {
        template = obj.template;
        break;
      }
    }
  }

  if (typeof pageTitle === 'string') {
    if (template && template.includes('%s')) {
      return template.replace('%s', () => pageTitle);
    }
    return pageTitle;
  }

  for (let i = layoutMetas.length - 1; i >= 0; i--) {
    const t = layoutMetas[i]?.title;
    if (typeof t === 'string') return t;
    if (t && typeof t === 'object' && !Array.isArray(t)) {
      const def = (t as any).default;
      if (typeof def === 'string') return def;
    }
  }

  return null;
}

function mergeMetadataChain(
  pageMeta: Record<string, unknown> | null,
  layoutMetas: (Record<string, unknown> | null)[],
): Record<string, unknown> {
  const merged: Record<string, unknown> = {};

  const sources: (Record<string, unknown> | null)[] = [...layoutMetas, pageMeta];

  for (const src of sources) {
    if (!src) continue;
    for (const [key, value] of Object.entries(src)) {
      if (key === 'title') continue;
      if (
        value &&
        typeof value === 'object' &&
        !Array.isArray(value) &&
        merged[key] &&
        typeof merged[key] === 'object' &&
        !Array.isArray(merged[key])
      ) {
        merged[key] = { ...(merged[key] as object), ...(value as object) };
      } else {
        merged[key] = value;
      }
    }
  }

  const title = resolveTitleFromChain(pageMeta, layoutMetas);
  if (title !== null) merged.title = title;

  return merged;
}

interface FileFacts {
  hasDefaultExport: boolean;
  isHtmlShell: boolean;
  exports: Set<string>;
  prerender: PrerenderMode | undefined;
}

const fileFactsCache = new WeakMap<ParsedFile, FileFacts>();

function getFileFacts(parsed: ParsedFile): FileFacts {
  const cached = fileFactsCache.get(parsed);
  if (cached) return cached;

  const facts: FileFacts = {
    hasDefaultExport: false,
    isHtmlShell: false,
    exports: new Set<string>(),
    prerender: undefined,
  };

  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (decl) {
      if ((decl.type === 'FunctionDeclaration' || decl.type === 'ClassDeclaration') && decl.id?.name) {
        facts.exports.add(decl.id.name);
      } else if (decl.type === 'VariableDeclaration') {
        for (const d of decl.declarations ?? []) collectPatternNames(d.id, facts.exports);
      }
    }
    for (const spec of stmt.specifiers ?? []) {
      const exportedName = spec.exported?.name ?? spec.exported?.value;
      if (typeof exportedName === 'string') facts.exports.add(exportedName);
    }
  }

  const prerender = getExportLiteral(parsed, 'prerender');
  if (prerender === 'strict' || prerender === 'fallback') facts.prerender = prerender;
  else if (prerender === false) facts.prerender = false;

  walk(parsed.program, (node) => {
    if (node.type === 'ExportDefaultDeclaration') {
      facts.hasDefaultExport = true;
    } else if (node.type === 'ExportNamedDeclaration' && Array.isArray(node.specifiers)) {
      for (const spec of node.specifiers) {
        if (spec.exported?.name === 'default') facts.hasDefaultExport = true;
      }
    } else if (node.type === 'JSXElement' && node.openingElement?.name?.name === 'html') {
      facts.isHtmlShell = true;
    }
    return undefined;
  });

  fileFactsCache.set(parsed, facts);
  return facts;
}

function hasDefaultExport(parsed: ParsedFile): boolean {
  return getFileFacts(parsed).hasDefaultExport;
}

function isHtmlShellLayout(parsed: ParsedFile): boolean {
  return getFileFacts(parsed).isHtmlShell;
}

function moduleData(filePath: string): DataFlags | null {
  const parsed = readAndParse(filePath);
  if (!parsed) return null;
  const { exports } = getFileFacts(parsed);

  const flags = {} as DataFlags;
  let any = false;
  for (const k of DATA_EXPORTS) {
    const has = exports.has(k);
    flags[k] = has;
    if (has) any = true;
  }
  return any ? flags : null;
}

function dataSignature(parsed: ParsedFile | null): string {
  if (!parsed) return 'invalid';
  const f = getFileFacts(parsed);
  const data = DATA_EXPORTS.filter(k => f.exports.has(k)).join(',');
  return `${f.hasDefaultExport ? 1 : 0}:${data}`;
}

function readAndParse(filePath: string): ParsedFile | null {
  const ext = path.extname(filePath);

  if (ext === '.mdx' || ext === '.md') {
    const cached = mdxAstCache.get(filePath);
    if (cached) return cached;

    const synthetic: ParsedFile = {
      program: {
        body: [{
          type: 'ExportDefaultDeclaration',
          start: 0,
          end: 0,
          declaration: { type: 'Identifier', name: '__mdx_default', start: 0, end: 0 },
        }],
      },
      comments: [],
      synthetic: true,
    };
    mdxAstCache.set(filePath, synthetic);
    return synthetic;
  }

  try {
    const stats = fs.statSync(filePath);

    const hit = fileParseCache.get(filePath);
    if (hit && hit.mtimeMs === stats.mtimeMs && hit.size === stats.size) return hit.parsed;

    if (stats.size > MAX_FILE_SIZE) {
      warnFileTooLarge(filePath);
      return null;
    }
    if (stats.size === 0) return null;

    const source = fs.readFileSync(filePath, 'utf8');
    const parsed = parseFile(source, filePath);

    if (fileParseCache.size >= FILE_CACHE_MAX) fileParseCache.clear();
    fileParseCache.set(filePath, { mtimeMs: stats.mtimeMs, size: stats.size, parsed });
    return parsed;
  } catch {
    return null;
  }
}

function isUsableLayout(filePath: string): boolean {
  const cached = isUsableLayoutCache.get(filePath);
  if (cached !== undefined) return cached;

  const parsed = readAndParse(filePath);
  const result = parsed !== null && hasDefaultExport(parsed) && !isHtmlShellLayout(parsed);
  isUsableLayoutCache.set(filePath, result);
  return result;
}

function listDirNames(dir: string): Set<string> {
  const cached = dirListingCache.get(dir);
  if (cached) return cached;
  let names: Set<string>;
  try {
    names = new Set(fs.readdirSync(dir));
  } catch {
    names = new Set();
  }
  dirListingCache.set(dir, names);
  return names;
}

function findFile(dir: string, candidates: readonly string[]): string | null {
  const names = listDirNames(dir);
  for (const candidate of candidates) {
    if (names.has(candidate)) return candidate;
  }
  return null;
}

function isTypeScriptProject(root: string): boolean {
  const mainEntries = ['src/main.tsx', 'src/main.ts', 'src/main.jsx', 'src/main.js'];
  for (const entry of mainEntries) {
    if (fs.existsSync(path.join(root, entry))) {
      return entry.includes('.ts');
    }
  }

  if (fs.existsSync(path.join(root, 'tsconfig.json'))) return true;

  const appDir = path.join(root, APP_DIR);
  if (fs.existsSync(appDir)) {
    const hasTsFile = (dir: string, depth = 0): boolean => {
      if (depth > 5) return false;
      let entries: fs.Dirent[];
      try {
        entries = fs.readdirSync(dir, { withFileTypes: true });
      } catch {
        return false;
      }
      for (const entry of entries) {
        if (entry.isDirectory()) {
          if (hasTsFile(path.join(dir, entry.name), depth + 1)) return true;
        } else {
          const ext = path.extname(entry.name);
          if (ext === '.tsx' || ext === '.ts') return true;
        }
      }
      return false;
    };
    if (hasTsFile(appDir)) return true;
  }

  return false;
}

function getAppFile(root: string, isTs: boolean): string {
  const tsPath = path.join(root, 'src/App.tsx');
  const jsxPath = path.join(root, 'src/App.jsx');

  if (fs.existsSync(tsPath)) return tsPath;
  if (fs.existsSync(jsxPath)) return jsxPath;

  return isTs ? tsPath : jsxPath;
}

function resolveLayoutChain(pageDir: string, appDir: string): string[] {
  const cacheKey = `${pageDir}::${appDir}`;
  const cached = layoutChainCache.get(cacheKey);
  if (cached) return cached;

  const chain: string[] = [];
  let current = pageDir;
  const visited = new Set<string>();

  while (true) {
    if (visited.has(current)) {
      viteWarnLog(`Circular layout chain detected at ${current}; stopping.`);
      break;
    }
    visited.add(current);

    const layout = findFile(current, LAYOUT_FILES);
    if (layout) chain.unshift(path.join(current, layout));

    if (path.resolve(current) === path.resolve(appDir)) break;

    const parent = path.dirname(current);
    if (parent === current || chain.length > MAX_DEPTH) break;
    current = parent;
  }

  layoutChainCache.set(cacheKey, chain);
  return chain;
}

function resolveTemplate(pageDir: string, appDir: string): string | null {
  const cacheKey = `${pageDir}::${appDir}`;
  if (templateCache.has(cacheKey)) return templateCache.get(cacheKey)!;

  let current = pageDir;
  const visited = new Set<string>();
  let depth = 0;
  let result: string | null = null;

  while (depth++ < MAX_DEPTH) {
    if (visited.has(current)) break;
    visited.add(current);

    const template = findFile(current, TEMPLATE_FILES);
    if (template) {
      const fullPath = path.join(current, template);
      if (isUsableLayout(fullPath)) {
        result = fullPath;
        break;
      }
    }

    if (path.resolve(current) === path.resolve(appDir)) break;

    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }

  templateCache.set(cacheKey, result);
  return result;
}

function layoutsFor(dir: string, appDir: string, slotRoot: string | null): string[] {
  const chain = resolveLayoutChain(dir, appDir);
  return slotRoot ? chain.filter(l => isInDir(l, slotRoot)) : chain;
}

function templateFor(dir: string, appDir: string, slotRoot: string | null): string | null {
  const t = resolveTemplate(dir, appDir);
  if (slotRoot && t && !isInDir(t, slotRoot)) return null;
  return t;
}

function resolveNearestFile(
  startDir: string,
  appDir: string,
  candidates: readonly string[],
): string | null {
  const cacheKey = `${startDir}::${appDir}::${candidates.join(',')}`;
  if (nearestFileCache.has(cacheKey)) {
    return nearestFileCache.get(cacheKey)!;
  }

  let current = startDir;
  const visited = new Set<string>();
  let depth = 0;
  const appDirResolved = path.resolve(appDir);
  let result: string | null = null;

  while (true) {
    if (visited.has(current) || depth > MAX_DEPTH) break;
    visited.add(current);
    depth++;

    const found = findFile(current, candidates);
    if (found) {
      const fullPath = path.join(current, found);
      if (isUsableLayout(fullPath)) {
        result = fullPath;
        break;
      }
    }

    if (path.resolve(current) === appDirResolved) break;

    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }

  nearestFileCache.set(cacheKey, result);
  return result;
}

interface ImportContext {
  importRoot: string;
}

function resolveLoadingComponentName(
  dir: string,
  appDir: string,
  ctx: ImportContext,
  loadingFileToName: Map<string, string>,
  lazyImports: string[],
  importedModules: Set<string>,
): string {
  const nearest = resolveNearestFile(dir, appDir, LOADING_FILES);
  if (!nearest) return 'Spinner';

  const existing = loadingFileToName.get(nearest);
  if (existing) return existing;

  const name = `Loading${loadingFileToName.size}`;
  loadingFileToName.set(nearest, name);

  const importPath = toImportPath(nearest, ctx.importRoot);
  if (!importedModules.has(importPath)) {
    lazyImports.push(`const ${name} = React.lazy(() => import('${importPath}'));`);
    importedModules.add(importPath);
  }

  return name;
}

