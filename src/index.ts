function unwrapExpression(node: any): any {
  if (!node) return node;
  switch (node.type) {
    case 'ParenthesizedExpression': case 'TSAsExpression': case 'TSSatisfiesExpression':
    case 'TSTypeAssertion': case 'TSNonNullExpression':
      return unwrapExpression(node.expression);
    default: return node;
  }
}

function jsxAttrToEntry(attr: any, filePath: string, program?: any): [string, string] | null {
  if (!attr || attr.type !== 'JSXAttribute') return null;
  const name = attr.name?.name;
  if (!name) return null;

  // `dangerouslySetInnerHTML={{ __html: <static> }}` is how JSON-LD and other
  // script bodies arrive. The special key `__html` signals to the caller that
  // the value becomes a raw text child of the element.
  if (name === 'dangerouslySetInnerHTML') {
    const valueNode = attr.value?.type === 'JSXExpressionContainer'
      ? unwrapExpression(attr.value.expression)
      : null;
    if (valueNode?.type === 'ObjectExpression') {
      for (const prop of valueNode.properties ?? []) {
        if (prop.type !== 'Property' || prop.computed) continue;
        const key = prop.key?.type === 'Identifier' ? prop.key.name
          : prop.key?.type === 'Literal' ? String(prop.key.value) : undefined;
        if (key !== '__html') continue;
        const html = nodeToValue(prop.value, program);
        if (typeof html === 'string') return ['__html', html];
      }
    }
    warnDynamicHeadContent(filePath, 'dangerouslySetInnerHTML');
    return null;
  }

  const htmlName = JSX_ATTR_TO_HTML[name] ?? name;
  if (!attr.value) return [htmlName, ''];
  if (attr.value.type === 'Literal') {
    if (attr.value.value === true) return [htmlName, ''];
    if (attr.value.value === false || attr.value.value == null) return null;
    return [htmlName, String(attr.value.value)];
  }
  if (attr.value.type === 'JSXExpressionContainer') {
    const expr = attr.value.expression;
    // Prefer static evaluation so `content={description}` works when
    // `description` is a module-scope const.
    const scalar = nodeToValue(expr, program);
    if (typeof scalar === 'string' || typeof scalar === 'number' || typeof scalar === 'boolean') {
      return [htmlName, String(scalar)];
    }
    warnDynamicHeadContent(filePath, `attribute \`${htmlName}\``);
    return null;
  }
  return null;
}

function jsxNodeToStructure(node: any, filePath: string, program?: any): HeadNode[] {
  if (!node) return [];
  switch (node.type) {
    case 'JSXFragment':
      return (node.children ?? []).flatMap((c: any) => jsxNodeToStructure(c, filePath, program));
    case 'JSXElement': {
      const opening = node.openingElement;
      const tag = opening?.name?.name;
      if (!tag) return [];
      const attrs: Record<string, string> = {};
      let innerHtml: string | null = null;
      for (const a of opening?.attributes ?? []) {
        const entry = jsxAttrToEntry(a, filePath, program);
        if (!entry) continue;
        if (entry[0] === '__html') innerHtml = entry[1];
        else attrs[entry[0]] = entry[1];
      }
      const children: HeadNode[] = innerHtml !== null
        ? [{ t: 'raw', value: innerHtml }]
        : (node.children ?? []).flatMap((c: any) => jsxNodeToStructure(c, filePath, program));
      return [{ t: 'element', tag, attrs, children }];
    }
    case 'JSXText': {
      const raw = node.value ?? '';
      return raw.trim() ? [{ t: 'text', value: raw }] : [];
    }
    case 'JSXExpressionContainer': {
      const expr = node.expression;
      if (!expr) return [];
      const value = nodeToValue(expr, program);
      if (typeof value === 'string') return [{ t: 'text', value }];
      if (typeof value === 'number' || typeof value === 'boolean') return [{ t: 'text', value: String(value) }];
      warnDynamicHeadContent(filePath, 'child expression');
      return [];
    }
    case 'Literal':
      return typeof node.value === 'string' ? [{ t: 'text', value: node.value }] : [];
    default: return [];
  }
}

function getJsxPropertyStructure(parsed: ParsedFile, name: string, propertyName: string, filePath: string): HeadNode[] | null {
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (!decl || decl.type !== 'VariableDeclaration') continue;
    for (const d of decl.declarations ?? []) {
      if (d.id?.type !== 'Identifier' || d.id.name !== name) continue;
      if (!d.init || d.init.type !== 'ObjectExpression') return null;
      for (const prop of d.init.properties ?? []) {
        if (prop.type !== 'Property' || prop.computed) continue;
        const key = prop.key?.type === 'Identifier' ? prop.key.name
          : prop.key?.type === 'Literal' ? String(prop.key.value) : undefined;
        if (key !== propertyName) continue;
        return jsxNodeToStructure(unwrapExpression(prop.value), filePath, parsed.program);
      }
      return null;
    }
  }
  return null;
}

function extractMetadataFromParsed(parsed: ParsedFile): Record<string, unknown> | null {
  if (parsed.synthetic) return null;
  return getNamedExportObject(parsed, 'metadata');
}

function extractDocumentFromParsed(filePath: string, parsed: ParsedFile): RouteDocument | null {
  const ext = path.extname(filePath);
  if (ext === '.mdx' || ext === '.md') return null;
  if (parsed.synthetic) return null;

  // Do NOT go through `getNamedExportObject` here: that evaluates the whole
  // `{ head: <>...</>, ... }` object via `nodeToValue`, which has no case for
  // JSX, so the whole object returns `undefined` and `document` is lost. Walk
  // the properties individually and route `head` through the JSX path.
  const init = unwrapExpression(getNamedExportInit(parsed, 'document'));
  if (!init || init.type !== 'ObjectExpression') return null;

  let html: Record<string, string> | undefined;
  let body: Record<string, string> | undefined;
  for (const prop of init.properties ?? []) {
    if (prop.type !== 'Property' || prop.computed) continue;
    const key = prop.key?.type === 'Identifier' ? prop.key.name
      : prop.key?.type === 'Literal' ? String(prop.key.value) : undefined;
    if (key !== 'html' && key !== 'body') continue;
    const v = nodeToValue(prop.value, parsed.program);
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      if (key === 'html') html = v as Record<string, string>;
      else body = v as Record<string, string>;
    }
  }

  const head = getJsxPropertyStructure(parsed, 'document', 'head', filePath);
  return { html, body, head: head ?? undefined };
}

function extractCssFromParsed(filePath: string, parsed: ParsedFile): string[] {
  const ext = path.extname(filePath);
  if (ext === '.mdx' || ext === '.md') return [];
  if (parsed.synthetic) return [];
  const css: string[] = [];
  const seen = new Set<string>();
  walkAst(parsed.program, (node) => {
    if (node.type !== 'ImportDeclaration') return;
    const source = node.source?.value;
    if (typeof source !== 'string') return;
    if (!CSS_EXT_PATTERN.test(source)) return;
    const resolved = path.resolve(path.dirname(filePath), source);
    if (!seen.has(resolved)) { seen.add(resolved); css.push(resolved); }
  });
  return css;
}

function resolveTitleFromChain(pageMeta: Record<string, unknown> | null, layoutMetas: (Record<string, unknown> | null)[]): string | null {
  const pageTitle = pageMeta?.title;
  let template: string | null = null;
  for (let i = layoutMetas.length - 1; i >= 0; i--) {
    const t = layoutMetas[i]?.title;
    if (t && typeof t === 'object' && !Array.isArray(t)) {
      const obj = t as any;
      if (typeof obj.template === 'string') { template = obj.template; break; }
    }
  }
  if (typeof pageTitle === 'string') {
    if (template && template.includes('%s')) return template.replace('%s', () => pageTitle);
    return pageTitle;
  }
  for (let i = layoutMetas.length - 1; i >= 0; i--) {
    const t = layoutMetas[i]?.title;
    if (typeof t === 'string') return t;
    if (t && typeof t === 'object' && !Array.isArray(t)) {
      const def = (t as any).default;
      if (typeof def === 'string') return def;
    }
  }
  return null;
}

function mergeMetadataChain(pageMeta: Record<string, unknown> | null, layoutMetas: (Record<string, unknown> | null)[]): Record<string, unknown> {
  const merged: Record<string, unknown> = {};
  const sources: (Record<string, unknown> | null)[] = [...layoutMetas, pageMeta];
  for (const src of sources) {
    if (!src) continue;
    for (const [key, value] of Object.entries(src)) {
      if (key === 'title') continue;
      if (value && typeof value === 'object' && !Array.isArray(value) && merged[key] && typeof merged[key] === 'object' && !Array.isArray(merged[key])) {
        merged[key] = { ...(merged[key] as object), ...(value as object) };
      } else {
        merged[key] = value;
      }
    }
  }
  const title = resolveTitleFromChain(pageMeta, layoutMetas);
  if (title !== null) merged.title = title;
  return merged;
}

interface FileFacts {
  hasDefaultExport: boolean;
  isHtmlShell: boolean;
  exports: Set<string>;
  prerender: PrerenderMode | undefined;
}

const fileFactsCache = new WeakMap<ParsedFile, FileFacts>();

function getFileFacts(parsed: ParsedFile): FileFacts {
  const cached = fileFactsCache.get(parsed);
  if (cached) return cached;
  const facts: FileFacts = { hasDefaultExport: false, isHtmlShell: false, exports: new Set(), prerender: undefined };
  for (const stmt of parsed.program.body ?? []) {
    if (stmt.type !== 'ExportNamedDeclaration') continue;
    const decl = stmt.declaration;
    if (decl) {
      if ((decl.type === 'FunctionDeclaration' || decl.type === 'ClassDeclaration') && decl.id?.name) facts.exports.add(decl.id.name);
      else if (decl.type === 'VariableDeclaration') {
        for (const d of decl.declarations ?? []) collectPatternNames(d.id, facts.exports);
      }
    }
    for (const spec of stmt.specifiers ?? []) {
      const exportedName = spec.exported?.name ?? spec.exported?.value;
      if (typeof exportedName === 'string') facts.exports.add(exportedName);
    }
  }
  const prerender = getExportLiteral(parsed, 'prerender');
  if (prerender === 'strict' || prerender === 'fallback') facts.prerender = prerender;
  else if (prerender === false) facts.prerender = false;
  walkAst(parsed.program, (node) => {
    if (node.type === 'ExportDefaultDeclaration') facts.hasDefaultExport = true;
    else if (node.type === 'ExportNamedDeclaration' && Array.isArray(node.specifiers)) {
      for (const spec of node.specifiers) {
        if (spec.exported?.name === 'default') facts.hasDefaultExport = true;
      }
    } else if (node.type === 'JSXElement' && node.openingElement?.name?.name === 'html') facts.isHtmlShell = true;
  });
  fileFactsCache.set(parsed, facts);
  return facts;
}

function hasDefaultExport(parsed: ParsedFile): boolean { return getFileFacts(parsed).hasDefaultExport; }
function isHtmlShellLayout(parsed: ParsedFile): boolean { return getFileFacts(parsed).isHtmlShell; }

function moduleData(filePath: string): DataFlags | null {
  const parsed = readAndParse(filePath);
  if (!parsed) return null;
  const { exports } = getFileFacts(parsed);
  const flags = {} as DataFlags;
  let any = false;
  for (const k of DATA_EXPORTS) { const has = exports.has(k); flags[k] = has; if (has) any = true; }
  return any ? flags : null;
}

function dataSignature(parsed: ParsedFile | null): string {
  if (!parsed) return 'invalid';
  const f = getFileFacts(parsed);
  const data = DATA_EXPORTS.filter(k => f.exports.has(k)).join(',');
  return `${f.hasDefaultExport ? 1 : 0}:${data}`;
}

function readAndParse(filePath: string): ParsedFile | null {
  const ext = path.extname(filePath);
  if (ext === '.mdx' || ext === '.md') {
    const cached = S.mdxAstCache.get(filePath);
    if (cached) return cached;
    const synthetic: ParsedFile = {
      program: { body: [{ type: 'ExportDefaultDeclaration', start: 0, end: 0, declaration: { type: 'Identifier', name: '__mdx_default', start: 0, end: 0 } }] },
      comments: [], synthetic: true,
    };
    S.mdxAstCache.set(filePath, synthetic);
    return synthetic;
  }
  try {
    const stats = fs.statSync(filePath);
    const hit = S.fileParseCache.get(filePath);
    if (hit && hit.mtimeMs === stats.mtimeMs && hit.size === stats.size) return hit.parsed;
    if (stats.size > MAX_FILE_SIZE) { report('warn', 'BINI_R005', filePath, 'File too large to parse'); return null; }
    if (stats.size === 0) return null;
    const source = fs.readFileSync(filePath, 'utf8');
    const parsed = parseFile(source, filePath);
    if (S.fileParseCache.size >= FILE_CACHE_MAX) S.fileParseCache.clear();
    S.fileParseCache.set(filePath, { mtimeMs: stats.mtimeMs, size: stats.size, parsed });
    return parsed;
  } catch { return null; }
}

function isUsableLayout(filePath: string): boolean {
  const cached = S.isUsableLayoutCache.get(filePath);
  if (cached !== undefined) return cached;
  const parsed = readAndParse(filePath);
  const result = parsed !== null && hasDefaultExport(parsed) && !isHtmlShellLayout(parsed);
  S.isUsableLayoutCache.set(filePath, result);
  return result;
}

function listDirNames(dir: string): Set<string> {
  const cached = S.dirListingCache.get(dir);
  if (cached) return cached;
  let names: Set<string>;
  try { names = new Set(fs.readdirSync(dir)); } catch { names = new Set(); }
  S.dirListingCache.set(dir, names);
  return names;
}

function findFile(dir: string, candidates: readonly string[]): string | null {
  const names = listDirNames(dir);
  for (const candidate of candidates) { if (names.has(candidate)) return candidate; }
  return null;
}

function isTypeScriptProject(root: string): boolean {
  const mainEntries = ['src/main.tsx', 'src/main.ts', 'src/main.jsx', 'src/main.js'];
  for (const entry of mainEntries) {
    if (fs.existsSync(path.join(root, entry))) return entry.includes('.ts');
  }
  if (fs.existsSync(path.join(root, 'tsconfig.json'))) return true;
  const appDir = path.join(root, APP_DIR);
  if (fs.existsSync(appDir)) {
    const hasTsFile = (dir: string, depth = 0): boolean => {
      if (depth > 5) return false;
      let entries: fs.Dirent[];
      try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return false; }
      for (const entry of entries) {
        if (entry.isDirectory()) { if (hasTsFile(path.join(dir, entry.name), depth + 1)) return true; }
        else { const ext = path.extname(entry.name); if (ext === '.tsx' || ext === '.ts') return true; }
      }
      return false;
    };
    if (hasTsFile(appDir)) return true;
  }
  return false;
}

function resolveLayoutChain(pageDir: string, appDir: string): string[] {
  const cacheKey = `${pageDir}::${appDir}`;
  const cached = S.layoutChainCache.get(cacheKey);
  if (cached) return cached;
  const chain: string[] = [];
  let current = pageDir;
  const visited = new Set<string>();
  while (true) {
    if (visited.has(current)) { report('warn', 'BINI_R010', current, 'Circular layout chain'); break; }
    visited.add(current);
    const layout = findFile(current, LAYOUT_FILES);
    if (layout) chain.unshift(path.join(current, layout));
    if (path.resolve(current) === path.resolve(appDir)) break;
    const parent = path.dirname(current);
    if (parent === current || chain.length > MAX_DEPTH) break;
    current = parent;
  }
  S.layoutChainCache.set(cacheKey, chain);
  return chain;
}

function resolveTemplate(pageDir: string, appDir: string): string | null {
  const cacheKey = `${pageDir}::${appDir}`;
  if (S.templateCache.has(cacheKey)) return S.templateCache.get(cacheKey)!;
  let current = pageDir;
  const visited = new Set<string>();
  let depth = 0;
  let result: string | null = null;
  while (depth++ < MAX_DEPTH) {
    if (visited.has(current)) break;
    visited.add(current);
    const template = findFile(current, TEMPLATE_FILES);
    if (template) {
      const fullPath = path.join(current, template);
      if (isUsableLayout(fullPath)) { result = fullPath; break; }
    }
    if (path.resolve(current) === path.resolve(appDir)) break;
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
  S.templateCache.set(cacheKey, result);
  return result;
}

function layoutsFor(dir: string, appDir: string, slotRoot: string | null): string[] {
  const chain = resolveLayoutChain(dir, appDir);
  return slotRoot ? chain.filter(l => isInDir(l, slotRoot)) : chain;
}

function templateFor(dir: string, appDir: string, slotRoot: string | null): string | null {
  const t = resolveTemplate(dir, appDir);
  if (slotRoot && t && !isInDir(t, slotRoot)) return null;
  return t;
}

function resolveNearestFile(startDir: string, appDir: string, candidates: readonly string[]): string | null {
  const cacheKey = `${startDir}::${appDir}::${candidates.join(',')}`;
  if (S.nearestFileCache.has(cacheKey)) return S.nearestFileCache.get(cacheKey)!;
  let current = startDir;
  const visited = new Set<string>();
  let depth = 0;
  const appDirResolved = path.resolve(appDir);
  let result: string | null = null;
  while (true) {
    if (visited.has(current) || depth > MAX_DEPTH) break;
    visited.add(current);
    depth++;
    const found = findFile(current, candidates);
    if (found) {
      const fullPath = path.join(current, found);
      if (isUsableLayout(fullPath)) { result = fullPath; break; }
    }
    if (path.resolve(current) === appDirResolved) break;
    const parent = path.dirname(current);
    if (parent === current) break;
    current = parent;
  }
  S.nearestFileCache.set(cacheKey, result);
  return result;
}

interface ImportContext { importRoot: string }

function toImportPath(filePath: string, fromDir: string): string {
  const keepExt = path.extname(filePath) === '.mdx' || path.extname(filePath) === '.md';
  let rel = norm(path.relative(fromDir, filePath));
  if (!rel.startsWith('.')) rel = './' + rel;
  if (!keepExt) rel = rel.replace(/\.(tsx|ts|jsx|js)$/, '');
  return rel;
}

// ─── Route segment parsing ─────────────────────────────────────────────────

interface RouteSegment { kind: 'static' | 'dynamic' | 'catchall' | 'catchall-optional'; value: string }
type InterceptLevel = 'none' | 'same' | 'up' | 'root';

interface RouteNode {
  routePath: string; filePath: string; layouts: string[]; template: string | null;
  dynamic: boolean; segments: RouteSegment[];
  hasRequiredCatchall: boolean; hasOptionalCatchall: boolean;
  slotName: string | null; slotOwnerDir: string | null;
  interceptLevel: InterceptLevel; interceptSourcePath: string | null;
}

interface LayoutChainGroup { layouts: string[]; template: string | null; routes: RouteNode[]; slotName: string | null }
interface ApiRoute { routePath: string; filePath: string; catchallParamName?: string; allowedMethods?: ApiMethod[] }
interface NotFoundBoundary { dirRoutePath: string; filePath: string; layouts: string[] }

function isValidRouteSegment(segment: string): boolean {
  if (!segment || segment.length === 0) return false;
  if (segment.length > MAX_ROUTE_SEGMENT_LENGTH) return false;
  return ALLOWED_ROUTE_PATTERN.test(segment);
}
function isValidParamName(name: string): boolean {
  if (!name || name.length === 0) return false;
  if (name.length > MAX_ROUTE_SEGMENT_LENGTH) return false;
  return ALLOWED_PARAM_PATTERN.test(name);
}
function normalizeRoutePath(routePath: string): string {
  let normalized = routePath.replace(/\/+/g, '/');
  if (normalized === '') return '/';
  if (!normalized.startsWith('/')) normalized = '/' + normalized;
  if (normalized.endsWith('/') && normalized !== '/') normalized = normalized.slice(0, -1);
  return normalized;
}
function isRouteGroup(name: string): boolean { return name.startsWith('(') && name.endsWith(')') && !isInterceptingRoute(name); }
function isInterceptingRoute(name: string): boolean { return name.startsWith('(.)') || name.startsWith('(..)') || name.startsWith('(...)'); }
function interceptLevelFromName(name: string): InterceptLevel {
  if (name.startsWith('(...)')) return 'root';
  if (name.startsWith('(..)')) return 'up';
  if (name.startsWith('(.)')) return 'same';
  return 'none';
}
function stripInterceptPrefix(name: string): string {
  if (name.startsWith('(...)')) return name.slice(5);
  if (name.startsWith('(..)')) return name.slice(4);
  if (name.startsWith('(.)')) return name.slice(3);
  return name;
}
function isRouteSlot(name: string): boolean { return name.startsWith('@') && name.length > 1; }
function isGroupNameValid(name: string): boolean { return ALLOWED_GROUP_PATTERN.test(name); }
function isSlotNameValid(name: string): boolean { return ALLOWED_SLOT_PATTERN.test(name); }

function segmentFromName(entryName: string): RouteSegment | null {
  if (isRouteGroup(entryName)) return null;
  if (entryName.startsWith('[[...') && entryName.endsWith(']]')) {
    const name = entryName.slice(5, -2);
    if (!isValidParamName(name)) return null;
    return { kind: 'catchall-optional', value: name };
  }
  if (entryName.startsWith('[...') && entryName.endsWith(']')) {
    const name = entryName.slice(4, -1);
    if (!isValidParamName(name)) return null;
    return { kind: 'catchall', value: name };
  }
  if (entryName.startsWith('[') && entryName.endsWith(']')) {
    const name = entryName.slice(1, -1);
    if (!isValidParamName(name)) return null;
    return { kind: 'dynamic', value: name };
  }
  if (!isValidRouteSegment(entryName)) return null;
  return { kind: 'static', value: entryName };
}

function segmentToRoutePath(segment: RouteSegment): string {
  if (segment.kind === 'dynamic') return `:${segment.value}`;
  if (segment.kind === 'catchall' || segment.kind === 'catchall-optional') return '*';
  return segment.value;
}

function requiredCatchallGuardPath(routePath: string): string | null {
  if (!routePath.endsWith('/*')) return null;
  const parent = routePath.slice(0, -2);
  return parent === '' ? '/' : parent;
}

function computeInterceptTargetBase(baseRoute: string, level: InterceptLevel): string {
  if (level === 'root') return '';
  if (level === 'up') {
    const parts = baseRoute.split('/').filter(Boolean);
    parts.pop();
    return parts.length > 0 ? '/' + parts.join('/') : '';
  }
  return baseRoute;
}

function resolveIntercept(baseRoute: string, baseSegments: RouteSegment[], level: InterceptLevel, segment: RouteSegment) {
  const targetBase = computeInterceptTargetBase(baseRoute, level);
  const targetSegments: RouteSegment[] = level === 'root' ? [] : level === 'up' ? baseSegments.slice(0, -1) : baseSegments;
  return {
    targetBase,
    targetSegments,
    nextBase: `${targetBase}/${segmentToRoutePath(segment)}`,
    nextSegments: [...targetSegments, segment],
    source: normalizeRoutePath(baseRoute || '/'),
  };
}

// ─── Directory scanning ────────────────────────────────────────────────────

function collectNotFoundBoundaries(dir: string, appDir: string, apiDir: string, baseRoute = '', depth = 0, out: NotFoundBoundary[] = []): NotFoundBoundary[] {
  if (depth > MAX_DEPTH) return out;
  if (!fs.existsSync(dir)) return out;
  const nfFile = findFile(dir, NOT_FOUND_FILES);
  if (nfFile) {
    const fullPath = path.join(dir, nfFile);
    const parsed = readAndParse(fullPath);
    if (parsed && hasDefaultExport(parsed)) {
      out.push({ dirRoutePath: normalizeRoutePath(baseRoute || '/'), filePath: fullPath, layouts: resolveLayoutChain(dir, appDir).filter(l => isUsableLayout(l)) });
    }
  }
  let entries: fs.Dirent[];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  entries.sort((a, b) => cmpStr(a.name, b.name));
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    const fullPath = path.join(dir, entry.name);
    if (path.resolve(fullPath) === path.resolve(apiDir)) continue;
    if (entry.name.startsWith('_')) continue;
    const isGroup = isRouteGroup(entry.name);
    const isSlot = isRouteSlot(entry.name);
    if (isSlot) continue;
    const segment = segmentFromName(entry.name);
    if (!segment && !isGroup) continue;
    const nextBase = segment ? `${baseRoute}/${segmentToRoutePath(segment)}` : baseRoute;
    collectNotFoundBoundaries(fullPath, appDir, apiDir, nextBase, depth + 1, out);
  }
  return out;
}

function scanRoutes(
  dir: string, appDir: string, apiDir: string,
  baseRoute = '', baseSegments: RouteSegment[] = [], depth = 0,
  currentSlot: string | null = null, slotOwnerDir: string | null = null,
): RouteNode[] {
  if (depth > MAX_DEPTH) { report('warn', 'BINI_R011', dir, 'Maximum directory depth reached'); return []; }
  const routes: RouteNode[] = [];
  if (!fs.existsSync(dir)) return routes;
  let entries: fs.Dirent[];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); }
  catch (error) { viteErrorLog(`Failed to read directory ${dir}`, S, error, dir); return routes; }
  entries.sort((a, b) => cmpStr(a.name, b.name));
  const slotRoot = currentSlot && slotOwnerDir ? path.join(slotOwnerDir, '@' + currentSlot) : null;

  for (const entry of entries) {
    if (!entry.isFile() || entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    const ext = path.extname(entry.name);
    const base = path.basename(entry.name, ext);
    if (!(SUPPORTED_EXTS as readonly string[]).includes(ext)) continue;
    if (SPECIAL_BASES.has(base)) continue;

    if (isInterceptingRoute(base)) {
      const level = interceptLevelFromName(base);
      const stripped = stripInterceptPrefix(base);
      const seg = stripped ? segmentFromName(stripped) : null;
      if (!seg) { reportInvalidName(entry.name, dir, 'intercept'); continue; }
      const t = resolveIntercept(baseRoute, baseSegments, level, seg);
      const isIdx = seg.kind === 'static' && seg.value === 'index';
      const segs = isIdx ? t.targetSegments : t.nextSegments;
      routes.push({
        routePath: normalizeRoutePath(isIdx ? (t.targetBase || '/') : t.nextBase),
        filePath: path.join(dir, entry.name),
        layouts: layoutsFor(dir, appDir, slotRoot),
        template: templateFor(dir, appDir, slotRoot),
        dynamic: segs.some(s => s.kind !== 'static'),
        segments: segs,
        hasRequiredCatchall: segs.some(s => s.kind === 'catchall'),
        hasOptionalCatchall: segs.some(s => s.kind === 'catchall-optional'),
        slotName: currentSlot, slotOwnerDir,
        interceptLevel: level, interceptSourcePath: t.source,
      });
      continue;
    }

    const segment = segmentFromName(base);
    if (!segment) { reportInvalidName(entry.name, dir, 'route'); continue; }
    const isIndex = segment.kind === 'static' && segment.value === 'index';
    const rawPath = isIndex ? baseRoute || '/' : `${baseRoute}/${segmentToRoutePath(segment)}`;
    const routePath = normalizeRoutePath(rawPath);
    const fullFilePath = path.join(dir, entry.name);
    const segments = isIndex ? baseSegments : [...baseSegments, segment];
    routes.push({
      routePath, filePath: fullFilePath,
      layouts: layoutsFor(dir, appDir, slotRoot),
      template: templateFor(dir, appDir, slotRoot),
      dynamic: segment.kind === 'dynamic' || segment.kind === 'catchall' || segment.kind === 'catchall-optional',
      segments,
      hasRequiredCatchall: segments.some(s => s.kind === 'catchall'),
      hasOptionalCatchall: segments.some(s => s.kind === 'catchall-optional'),
      slotName: currentSlot, slotOwnerDir,
      interceptLevel: 'none', interceptSourcePath: null,
    });
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
    if (entry.name.startsWith('_')) continue;
    const fullPath = path.join(dir, entry.name);
    if (path.resolve(fullPath) === path.resolve(apiDir)) continue;

    if (isRouteSlot(entry.name)) {
      const slotName = entry.name.slice(1);
      if (!isSlotNameValid(slotName)) { reportInvalidName(entry.name, dir, 'slot'); continue; }
      const slotPage = findFile(fullPath, PAGE_FILES);
      if (slotPage) {
        routes.push({
          routePath: normalizeRoutePath(baseRoute || '/'),
          filePath: path.join(fullPath, slotPage),
          layouts: layoutsFor(fullPath, appDir, fullPath),
          template: templateFor(fullPath, appDir, fullPath),
          dynamic: baseSegments.some(s => s.kind !== 'static'),
          segments: baseSegments,
          hasRequiredCatchall: baseSegments.some(s => s.kind === 'catchall'),
          hasOptionalCatchall: baseSegments.some(s => s.kind === 'catchall-optional'),
          slotName, slotOwnerDir: dir, interceptLevel: 'none', interceptSourcePath: null,
        });
      }
      routes.push(...scanRoutes(fullPath, appDir, apiDir, baseRoute, baseSegments, depth + 1, slotName, dir));
      continue;
    }

    if (isInterceptingRoute(entry.name)) {
      const level = interceptLevelFromName(entry.name);
      const stripped = stripInterceptPrefix(entry.name);
      if (!stripped) { reportInvalidName(entry.name, dir, 'intercept'); continue; }
      const segment = segmentFromName(stripped);
      if (!segment) { reportInvalidName(entry.name, dir, 'intercept'); continue; }
      const t = resolveIntercept(baseRoute, baseSegments, level, segment);
      const { nextBase, nextSegments } = t;
      const pageFile = findFile(fullPath, PAGE_FILES);
      if (pageFile) {
        routes.push({
          routePath: normalizeRoutePath(nextBase),
          filePath: path.join(fullPath, pageFile),
          layouts: layoutsFor(fullPath, appDir, slotRoot),
          template: templateFor(fullPath, appDir, slotRoot),
          dynamic: nextSegments.some(s => s.kind !== 'static'),
          segments: nextSegments,
          hasRequiredCatchall: nextSegments.some(s => s.kind === 'catchall'),
          hasOptionalCatchall: nextSegments.some(s => s.kind === 'catchall-optional'),
          slotName: currentSlot, slotOwnerDir,
          interceptLevel: level, interceptSourcePath: t.source,
        });
      }
      const sub = scanRoutes(fullPath, appDir, apiDir, nextBase, nextSegments, depth + 1, currentSlot, slotOwnerDir);
      for (const r of sub) {
        if (r.interceptLevel === 'none') { r.interceptLevel = level; r.interceptSourcePath = t.source; }
      }
      routes.push(...sub);
      continue;
    }

    const isGroup = isRouteGroup(entry.name);
    if (isGroup) {
      const groupName = entry.name.slice(1, -1);
      if (!isGroupNameValid(groupName)) { reportInvalidName(entry.name, dir, 'group'); continue; }
    }
    const segment = segmentFromName(entry.name);
    if (!segment && !isGroup) { reportInvalidName(entry.name, dir, 'route'); continue; }
    const nextSegments = segment ? [...baseSegments, segment] : baseSegments;
    const nextBase = segment ? `${baseRoute}/${segmentToRoutePath(segment)}` : baseRoute;
    const pageFile = findFile(fullPath, PAGE_FILES);
    if (pageFile) {
      const routePath = normalizeRoutePath(nextBase);
      routes.push({
        routePath, filePath: path.join(fullPath, pageFile),
        layouts: layoutsFor(fullPath, appDir, slotRoot),
        template: templateFor(fullPath, appDir, slotRoot),
        dynamic: nextSegments.some(s => s.kind === 'dynamic' || s.kind === 'catchall' || s.kind === 'catchall-optional'),
        segments: nextSegments,
        hasRequiredCatchall: nextSegments.some(s => s.kind === 'catchall'),
        hasOptionalCatchall: nextSegments.some(s => s.kind === 'catchall-optional'),
        slotName: currentSlot, slotOwnerDir, interceptLevel: 'none', interceptSourcePath: null,
      });
    }
    routes.push(...scanRoutes(fullPath, appDir, apiDir, nextBase, nextSegments, depth + 1, currentSlot, slotOwnerDir));
  }
  return routes;
}

// ─── Route dedup / prioritization ─────────────────────────────────────────

function routeKey(route: RouteNode): string { return `${route.routePath}::${route.interceptLevel}::${route.slotName ?? ''}`; }

function detectRouteConflicts(routes: RouteNode[]): RouteConflict[] {
  const routeMap = new Map<string, string[]>();
  for (const route of routes) {
    const key = routeKey(route);
    const existing = routeMap.get(key) || [];
    existing.push(route.filePath);
    routeMap.set(key, existing);
  }
  const conflicts: RouteConflict[] = [];
  for (const [p, files] of routeMap) {
    if (files.length > 1) { const [pathOnly] = p.split('::'); conflicts.push({ path: pathOnly, files }); }
  }
  return conflicts;
}

function extensionPriority(filePath: string): number {
  const ext = path.extname(filePath);
  const idx = (SUPPORTED_EXTS as readonly string[]).indexOf(ext);
  return idx === -1 ? SUPPORTED_EXTS.length : idx;
}

function routePriority(r: RouteNode): number {
  if (r.hasRequiredCatchall) return 2;
  if (r.hasOptionalCatchall) return 3;
  if (r.dynamic) return 1;
  return 0;
}

function deduplicateRoutes(routes: RouteNode[]): RouteNode[] {
  const seen = new Map<string, RouteNode>();
  for (const route of routes) {
    const key = routeKey(route);
    const existing = seen.get(key);
    if (!existing) seen.set(key, route);
    else if (existing.filePath !== route.filePath) {
      if (route.layouts.length > existing.layouts.length) seen.set(key, route);
      else if (route.layouts.length === existing.layouts.length && extensionPriority(route.filePath) < extensionPriority(existing.filePath)) seen.set(key, route);
    }
  }
  return Array.from(seen.values());
}

interface PreparedRoutes { validRoutes: RouteNode[]; notFoundBoundaries: NotFoundBoundary[] }

function prepareRoutes(appDir: string, apiDir: string): PreparedRoutes {
  let routes = scanRoutes(appDir, appDir, apiDir, '', [], 0, null, null);
  const rootPage = findFile(appDir, PAGE_FILES);
  if (rootPage) {
    routes.unshift({
      routePath: normalizeRoutePath('/'), filePath: path.join(appDir, rootPage),
      layouts: resolveLayoutChain(appDir, appDir), template: resolveTemplate(appDir, appDir),
      dynamic: false, segments: [], hasRequiredCatchall: false, hasOptionalCatchall: false,
      slotName: null, slotOwnerDir: null, interceptLevel: 'none', interceptSourcePath: null,
    });
  }
  const routesFiltered = routes.map(r => ({ ...r, layouts: r.layouts.filter(l => isUsableLayout(l)) }));
  const validRoutes = routesFiltered.filter(r => {
    const parsed = readAndParse(r.filePath);
    S.dataSigs.set(r.filePath, dataSignature(parsed));
    if (parsed === null) return false;
    if (!hasDefaultExport(parsed)) {
      if (path.basename(r.filePath, path.extname(r.filePath)) === 'page') {
        report('error', 'BINI_R001', r.filePath, 'Missing default export');
      }
      return false;
    }
    return true;
  });
  const conflicts = detectRouteConflicts(validRoutes);
  if (conflicts.length > 0) {
    const list = conflicts.map(c => c.path).join(', ');
    report('error', 'BINI_R007', undefined, `Route conflict: ${list}`);
  }
  const deduped = deduplicateRoutes(validRoutes);
  const notFoundBoundaries = collectNotFoundBoundaries(appDir, appDir, apiDir, '');
  return { validRoutes: deduped, notFoundBoundaries };
}

// ─── Manifest builders ─────────────────────────────────────────────────────

function buildRouteMetadataEntry(route: RouteNode, slotCssByOwnerDir: Map<string, string[]>): RouteManifestEntry {
  const pageParsed = readAndParse(route.filePath);
  const layoutEntries = route.layouts.map(l => ({ path: l, parsed: readAndParse(l) }));
  const layoutMetas = layoutEntries.map(l => l.parsed ? extractMetadataFromParsed(l.parsed) : null);
  const pageMeta = pageParsed ? extractMetadataFromParsed(pageParsed) : null;
  const merged = mergeMetadataChain(pageMeta, layoutMetas);
  const title = typeof merged.title === 'string' ? merged.title : undefined;
  const css: string[] = [];
  for (const { path: p, parsed } of layoutEntries) { if (parsed) css.push(...extractCssFromParsed(p, parsed)); }
  if (pageParsed) css.push(...extractCssFromParsed(route.filePath, pageParsed));
  if (route.slotName === null && route.slotOwnerDir === null) {
    const slotDir = route.filePath ? path.dirname(route.filePath) : null;
    if (slotDir) { const slotCss = slotCssByOwnerDir.get(slotDir); if (slotCss) css.push(...slotCss); }
  }
  let document: RouteDocument | null = null;
  const candidates: { path: string; parsed: ParsedFile | null }[] = [{ path: route.filePath, parsed: pageParsed }, ...layoutEntries.slice().reverse()];
  for (const { path: p, parsed } of candidates) {
    if (!parsed) continue;
    const doc = extractDocumentFromParsed(p, parsed);
    if (doc) { document = doc; break; }
  }
  const catchallSegments = route.segments.filter(s => s.kind === 'catchall' || s.kind === 'catchall-optional');
  const catchallSegment = catchallSegments.length > 0 ? catchallSegments[catchallSegments.length - 1] : undefined;
  const catchallKind: 'required' | 'optional' | null =
    catchallSegment?.kind === 'catchall' ? 'required' : catchallSegment?.kind === 'catchall-optional' ? 'optional' : null;
  const exp = pageParsed ? getFileFacts(pageParsed).exports : null;
  const facts = pageParsed ? getFileFacts(pageParsed) : null;
  return {
    title, meta: merged, document, css: [...new Set(css)],
    layouts: route.layouts, filePath: route.filePath,
    dynamic: route.dynamic || route.routePath.includes(':') || route.routePath.includes('*'),
    catchallKind, catchallParamName: catchallSegment?.value,
    slotName: route.slotName ?? undefined,
    loader: exp?.has('loader') ?? false,
    action: exp?.has('action') ?? false,
    shouldRevalidate: exp?.has('shouldRevalidate') ?? false,
    errorBoundary: exp?.has('ErrorBoundary') ?? false,
    hydrateFallback: (exp?.has('HydrateFallback') || exp?.has('hydrateFallbackElement')) ?? false,
    handle: exp?.has('handle') ?? false,
    prerender: facts?.prerender,
  };
}

function buildRouteManifestInternal(appDir: string, apiDir: string): RouteManifest {
  const { validRoutes } = prepareRoutes(appDir, apiDir);
  const slotCssByOwnerDir = new Map<string, string[]>();
  for (const route of validRoutes) {
    if (route.slotName === null || !route.slotOwnerDir) continue;
    const parsed = readAndParse(route.filePath);
    const own = parsed ? extractCssFromParsed(route.filePath, parsed) : [];
    const list = slotCssByOwnerDir.get(route.slotOwnerDir) ?? [];
    list.push(...own);
    slotCssByOwnerDir.set(route.slotOwnerDir, list);
  }
  const staticRoutes: string[] = [];
  const dynamicRoutes: string[] = [];
  const metadata: RouteManifest['metadata'] = {};
  const ordered = [...validRoutes].sort((a, b) => (a.slotName === null ? 0 : 1) - (b.slotName === null ? 0 : 1));
  const slotsByPath = new Map<string, RouteSlotInfo[]>();
  const interceptsByPath = new Map<string, RouteInterceptInfo[]>();
  for (const r of validRoutes) {
    if (r.interceptLevel !== 'none' && r.interceptSourcePath) {
      const list = interceptsByPath.get(r.routePath) ?? [];
      list.push({ from: r.interceptSourcePath, level: r.interceptLevel as 'same' | 'up' | 'root', filePath: r.filePath, slotName: r.slotName });
      interceptsByPath.set(r.routePath, list);
    } else if (r.slotName !== null) {
      const list = slotsByPath.get(r.routePath) ?? [];
      list.push({ slotName: r.slotName, filePath: r.filePath });
      slotsByPath.set(r.routePath, list);
    }
  }
  for (const route of ordered) {
    if (route.interceptLevel !== 'none') continue;
    if (route.slotName !== null && metadata[route.routePath]) continue;
    const entry = buildRouteMetadataEntry(route, slotCssByOwnerDir);
    if (route.slotName === null) {
      const parallel = slotsByPath.get(route.routePath);
      const intercepts = interceptsByPath.get(route.routePath);
      if (parallel?.length) entry.parallel = parallel;
      if (intercepts?.length) entry.intercepts = intercepts;
    }
    if (entry.dynamic) dynamicRoutes.push(route.routePath);
    else staticRoutes.push(route.routePath);
    metadata[route.routePath] = entry;
  }
  return { static: [...new Set(staticRoutes)], dynamic: [...new Set(dynamicRoutes)], all: [...new Set([...staticRoutes, ...dynamicRoutes])], metadata };
}

export function generateRouteManifest(appDir: string, apiDir: string = path.join(appDir, 'api')): RouteManifest {
  clearBuildCaches();
  // Also reset the parse caches so the manifest is always derived from the
  // raw on-disk source. During a Vite build, the `transform` hook may have
  // populated these with ASTs of the *pre-processed* source; that AST can
  // differ from the raw file (e.g. an identifier moved by an earlier plugin),
  // which would make static extraction of `document.head` fail.
  S.fileParseCache.clear();
  S.parsedFileCache.clear();
  return buildRouteManifestInternal(appDir, apiDir);
}

export function generateBuildManifest(appDir: string, apiDir: string = path.join(appDir, 'api')): BuildManifest {
  clearBuildCaches();
  const routes = scanApiRoutes(apiDir, '');
  return {
    routes: routes.map(r => ({ routePath: r.routePath, filePath: r.filePath, allowedMethods: (r.allowedMethods ?? [...API_METHODS]) as ApiMethod[], catchallParamName: r.catchallParamName })),
    appDir, apiDir,
  };
}

// ─── Route matching (public) ──────────────────────────────────────────────

function isUnsafeSegment(value: string): boolean {
  return value === '.' || value === '..' || value.includes('/') || value.includes('\\') || value.includes('\0');
}

function matchRouteForEntry(manifest: RouteManifest, pattern: string, pathname: string): Record<string, string> | null {
  const entry = manifest.metadata[pattern];
  return matchRoute(pattern, pathname, { enforceNonEmptyCatchAll: entry?.catchallKind === 'required', catchallParamName: entry?.catchallParamName });
}

export function getMetadataForRoute(manifest: RouteManifest, pathname: string): RouteManifestEntry | null {
  const exact = manifest.metadata[pathname];
  if (exact) return exact;
  for (const pattern of manifest.dynamic) {
    if (matchRouteForEntry(manifest, pattern, pathname)) { const entry = manifest.metadata[pattern]; if (entry) return entry; }
  }
  return null;
}

export function getCssForRoute(manifest: RouteManifest, pathname: string): string[] | null {
  return getMetadataForRoute(manifest, pathname)?.css ?? null;
}

export function matchRoute(pattern: string, pathname: string, options: { enforceNonEmptyCatchAll?: boolean; catchallParamName?: string } = {}): Record<string, string> | null {
  const { enforceNonEmptyCatchAll = false, catchallParamName } = options;
  const patParts = pattern.split('/').filter(Boolean);
  const urlParts = pathname.split('/').filter(Boolean);
  const lastPat = patParts[patParts.length - 1];
  const isOptionalCatchAll = lastPat === '**';
  const isRequiredCatchAll = lastPat === '*';

  if (isOptionalCatchAll || isRequiredCatchAll) {
    const prefix = patParts.slice(0, -1);
    if (urlParts.length < prefix.length) return null;
    if (isRequiredCatchAll && enforceNonEmptyCatchAll && urlParts.length === prefix.length) return null;
    const params: Record<string, string> = {};
    for (let i = 0; i < prefix.length; i++) {
      if (prefix[i].startsWith(':')) {
        let value: string;
        try { value = decodeURIComponent(urlParts[i]); } catch { return null; }
        if (isUnsafeSegment(value)) return null;
        params[prefix[i].slice(1)] = value;
      } else if (prefix[i] !== urlParts[i]) return null;
    }
    const rawTail = urlParts.slice(prefix.length);
    const decodedTail: string[] = [];
    for (const seg of rawTail) {
      let decoded: string;
      try { decoded = decodeURIComponent(seg); } catch { return null; }
      if (isUnsafeSegment(decoded)) return null;
      decodedTail.push(decoded);
    }
    const tail = decodedTail.join('/');
    params['*'] = tail;
    if (catchallParamName) params[catchallParamName] = tail;
    return params;
  }

  if (patParts.length !== urlParts.length) return null;
  const params: Record<string, string> = {};
  for (let i = 0; i < patParts.length; i++) {
    if (patParts[i].startsWith(':')) {
      let value: string;
      try { value = decodeURIComponent(urlParts[i]); } catch { return null; }
      if (isUnsafeSegment(value)) return null;
      params[patParts[i].slice(1)] = value;
    } else if (patParts[i] !== urlParts[i]) return null;
  }
  return params;
}

export function matchManifestRoute(manifest: RouteManifest, pathname: string): RouteMatchResult {
  const exact = manifest.metadata[pathname];
  if (exact) return { type: exact.dynamic ? 'dynamic' : 'static', routePath: pathname };
  for (const pattern of manifest.dynamic) {
    const params = matchRouteForEntry(manifest, pattern, pathname);
    if (params) return { type: 'dynamic', routePath: pattern, params };
  }
  return { type: 'not_found' };
}

