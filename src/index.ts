const useColor =
  !process.env.NO_COLOR &&
  (process.env.FORCE_COLOR ? process.env.FORCE_COLOR !== '0' : Boolean(process.stdout?.isTTY));

const paint = (open: number, close: number) => (text: string): string => {
  if (!useColor) return text;
  const o = `\x1b[${open}m`; const c = `\x1b[${close}m`;
  return o + text.split(c).join(c + o) + c;
};

const color = { dim: paint(2, 22), red: paint(31, 39), green: paint(32, 39), yellow: paint(33, 39) };

