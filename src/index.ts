export interface RouteManifest {
  static: string[];
  dynamic: string[];
  all: string[];
  metadata: {
    [routePath: string]: RouteManifestEntry;
  };
}

export interface RouteMatchResult {
  type: 'static' | 'dynamic' | 'not_found';
  routePath?: string;
  params?: Record<string, string>;
}

function buildRouteMetadataEntry(route: RouteNode): RouteManifestEntry {
  const pageParsed = readAndParse(route.filePath);
  const layoutEntries = route.layouts.map(l => ({
    path: l,
    parsed: readAndParse(l),
  }));

  const layoutMetas = layoutEntries.map(l =>
    l.parsed ? extractMetadataFromParsed(l.parsed) : null
  );
  const pageMeta = pageParsed ? extractMetadataFromParsed(pageParsed) : null;
  const merged = mergeMetadataChain(pageMeta, layoutMetas);
  const title = typeof merged.title === 'string' ? merged.title : undefined;

  const css: string[] = [];
  for (const { path: p, parsed } of layoutEntries) {
    if (parsed) css.push(...extractCssFromParsed(p, parsed));
  }
  if (pageParsed) css.push(...extractCssFromParsed(route.filePath, pageParsed));

  let document: RouteDocument | null = null;
  const candidates: { path: string; parsed: ParsedFile | null }[] = [
    { path: route.filePath, parsed: pageParsed },
    ...layoutEntries.slice().reverse(),
  ];
  for (const { path: p, parsed } of candidates) {
    if (!parsed) continue;
    const doc = extractDocumentFromParsed(p, parsed);
    if (doc) {
      document = doc;
      break;
    }
  }

  const catchallSegments = route.segments.filter(
    s => s.kind === 'catchall' || s.kind === 'catchall-optional'
  );
  const catchallSegment = catchallSegments.length > 0
    ? catchallSegments[catchallSegments.length - 1]
    : undefined;

  const catchallKind: 'required' | 'optional' | null =
    catchallSegment?.kind === 'catchall'
      ? 'required'
      : catchallSegment?.kind === 'catchall-optional'
        ? 'optional'
        : null;

  return {
    title,
    meta: merged,
    document,
    css,
    layouts: route.layouts,
    filePath: route.filePath,
    dynamic: route.dynamic || route.routePath.includes(':') || route.routePath.includes('*'),
    catchallKind,
    catchallParamName: catchallSegment?.value,
    slotName: route.slotName ?? undefined,
  };
}

function buildRouteManifestInternal(
  appDir: string,
  apiDir: string,
  strictMode: boolean,
): RouteManifest {
  const { validRoutes } = prepareRoutes(appDir, apiDir, strictMode);

  const staticRoutes: string[] = [];
  const dynamicRoutes: string[] = [];
  const metadata: RouteManifest['metadata'] = {};

  for (const route of validRoutes) {
    const entry = buildRouteMetadataEntry(route);
    if (entry.dynamic) dynamicRoutes.push(route.routePath);
    else staticRoutes.push(route.routePath);

    metadata[route.routePath] = entry;
  }

  return {
    static: [...new Set(staticRoutes)],
    dynamic: [...new Set(dynamicRoutes)],
    all: [...new Set([...staticRoutes, ...dynamicRoutes])],
    metadata,
  };
}

export function generateRouteManifest(
  appDir: string,
  apiDir: string = path.join(appDir, 'api'),
  options: { strictMode?: boolean } = {},
): RouteManifest {
  clearBuildCaches();
  return buildRouteManifestInternal(appDir, apiDir, options.strictMode ?? true);
}

